/**
 * Двери в панели, переехавшие из правой колонки (Сессия 55).
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. До Сессии 55 списки элементов, слайдов и глав, а также
 * свойства выбранной метки жили в правой колонке — она была на экране
 * ВСЕГДА, и тест мог сразу спросить `getByTestId('element-row-…')`.
 * Колонки больше нет: у Канвы и КапКута справа от полотна пусто, панели
 * открываются слева от рейки. Теперь у каждой панели своя дверь, и тест
 * обязан её открыть — ровно как автор.
 *
 * ПОЧЕМУ ОБЩИЙ ФАЙЛ, А НЕ СТРОЧКА В КАЖДОМ ТЕСТЕ. Дверь — это то, что
 * ломается при следующем переносе облика. Разложенная по трём десяткам
 * файлов, она превратит любой такой перенос в три десятка правок, и часть
 * из них будет забыта: забытая правка выглядит как упавший тест, а упавший
 * тест правят подгонкой. Одно место — одна правка.
 *
 * ЗДЕСЬ НЕТ ОЖИДАНИЙ «ПАНЕЛЬ ОТКРЫЛАСЬ» СВЕРХ НЕОБХОДИМОГО: помощник
 * доводит до состояния, а утверждения о содержимом — дело самого теста.
 * Помощник, проверяющий за тест его предмет, делает тест зелёным по чужой
 * причине.
 */
import { expect, type Page } from '@playwright/test';

/**
 * Открывает панель «Слои» — список элементов сцены.
 *
 * Дверь стоит в полосе над холстом и видна ВСЕГДА, в том числе когда
 * не выделено ничего: список элементов — содержимое сцены, а не свойство
 * выделения (см. PropBar.tsx). Именно поэтому вызывать этот помощник можно
 * до любого выделения.
 */
export async function openLayers(page: Page): Promise<void> {
  await page.getByTestId('propbar-layers').click();
  await expect(page.getByTestId('element-list')).toBeVisible();
}

/**
 * Открывает панель «Объект» — свойства выделенного элемента.
 *
 * Дверь живёт ВНУТРИ пилюли свойств, а пилюля при пустом выделении
 * не рендерится вовсе. Поэтому вызывать после выделения, иначе кнопки
 * на экране нет — и это не поломка помощника, а верное поведение.
 */
export async function openObject(page: Page): Promise<void> {
  await page.getByTestId('propbar-more').click();
}

/**
 * Открывает панель «Главы» — список глав и правила выхода.
 *
 * Дверь стоит на доске веток: главы и есть её предмет. Поэтому помощник
 * сначала переключает нижнюю зону на вид «Ветки».
 */
export async function openChapters(page: Page): Promise<void> {
  await page.getByTestId('view-branches').click();
  await page.getByTestId('branches-open-chapters').click();
}

/**
 * Открывает панель «Метка» — свойства выбранной метки дорожки.
 *
 * Своей двери у неё НЕТ и быть не может: без выбранной метки показывать
 * нечего. Панель открывается сама при выборе метки (Editor.tsx). Помощник
 * поэтому только выбирает метку и ждёт панель — он выражает тот факт, что
 * выбор метки и есть дверь.
 */
export async function openMark(page: Page, markTestId: string): Promise<void> {
  await page.getByTestId(markTestId).click();
  await expect(page.getByTestId('mark-panel')).toBeVisible();
}

/**
 * Разворачивает ленту карточек слайдов в дорожке.
 *
 * По умолчанию лента СВЁРНУТА — решение владельца 15.08.2026 по замеру:
 * развёрнутая отнимала у сцены 98 px. Дверь — голова полосы «Слайды».
 *
 * Помощник ИДЕМПОТЕНТЕН: нажимать переключатель вслепую нельзя, второй
 * вызов свернул бы ленту обратно, и тест упал бы на пустом месте, начав
 * с состояния, которого не заказывал.
 */
export async function openSlideStrip(page: Page): Promise<void> {
  const toggle = page.getByTestId('slide-strip-toggle');
  if ((await toggle.getAttribute('aria-expanded')) !== 'true') {
    await toggle.click();
  }
  await expect(page.getByTestId('slide-strip')).toBeVisible();
}

/**
 * Разрезает главу по метке — меню правой кнопки по её ромбу.
 *
 * ЗАВЕДЁН 25.08.2026. До этого разрез вызывали кнопкой «Разделить
 * повествование здесь» в карточке метки. Кнопки больше нет: по решению
 * владельца метка с вариантами ответа и ЕСТЬ развилка, а разрез делает
 * то же нажатие, которым задают вопрос, и кнопка «Завести ветку под этот
 * ответ». Отдельным жестом разрез остался ровно там, где живут остальные
 * действия над меткой, — в меню дорожки.
 *
 * Помощник нужен затем же, зачем и остальные двери в этом файле: следующий
 * перенос облика иначе превратится в десяток одинаковых правок, часть
 * которых забудут.
 */
export async function splitChapterAtGate(page: Page, markTestId: string): Promise<void> {
  const box = await page.getByTestId(markTestId).boundingBox();
  if (!box) throw new Error(`метки «${markTestId}» не видно — разрезать нечего`);
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2, { button: 'right' });
  await page.getByRole('menuitem', { name: 'Разрезать главу здесь' }).click();
}
