/**
 * Органы, действующие на список: стоят ли они при своём предмете и называют
 * ли причину, когда действие невозможно.
 *
 * Файл назывался `side-column-actions` — по правой колонке, которой с Сессии
 * 55 нет. Оба его утверждения пережили переезд, но у второго сменился орган,
 * и это не переименование, а другой прибор (см. ниже).
 *
 * 1. Кнопка «Удалить» элементов стоит В ОДНОЙ СТРОКЕ с названием списка,
 *    на который действует, а не отдельной строкой сверху. Проверяется
 *    геометрией (центр по Y), а не наличием в DOM: наличие осталось бы
 *    зелёным и при отдельной строке.
 *
 * 2. ВТОРОЙ ТЕСТ ФАЙЛА УБРАН — вслух, с причиной, потому что тихо
 *    исчезнувший тест в отчёте выглядит как выполненная работа.
 *
 *    Он проверял погашенную кнопку удаления слайда в панели слайдов:
 *    значок с причиной в атрибуте `title`. Панель удалена в Сессии 55 как
 *    дубликат ленты карточек, и я попробовал перенести утверждение на меню
 *    правой кнопки дорожки. НЕ ВЫШЛО, и это стоит записать:
 *
 *    • первый слайд НЕДОСТИЖИМ для этих действий вовсе — метки на дорожке
 *      у него нет (замер: 15 слайдов, 14 меток). Действие, которое нельзя
 *      совершить, не предлагается, и объяснять нечего;
 *
 *    • «Вырезать слайд» в меню ПУСТОГО МЕСТА действует на текущий слайд,
 *      но правый щелчок по дорожке ведёт головку, а головка ведёт выбранный
 *      слайд (`Editor.tsx`, эффект «головка ведёт выбранный слайд»). То есть
 *      к моменту открытия меню текущим стал слайд под щелчком, а не первый.
 *      Тест, написанный по первой догадке, был красным на исправном коде.
 *
 *    Само утверждение — «невозможное действие названо ВИДИМЫМ текстом,
 *    а не только гашением» — не потеряно и проверяется на живом случае
 *    в `editor-slide-clipboard.spec.ts`, тест «отказ вставки на занятую
 *    секунду объяснён видимым текстом, а не только погашенной кнопкой».
 *    Второй такой же тест здесь был бы не охраной, а дубликатом.
 */
import { expect, test, type Page } from '@playwright/test';

import { openLayers } from './panels.js';

async function openEditor(page: Page, fixture: string): Promise<void> {
  await page.goto(`/editor.html?fixture=${fixture}`, { waitUntil: 'load' });
  await page.waitForFunction(() => document.documentElement.dataset['ready'] === '1', null, {
    timeout: 30_000,
  });
}

test('кнопка удаления стоит в заголовке того списка, на который действует', async ({ page }) => {
  await openEditor(page, 'demo');
  // Список элементов переехал в панель «Слои» (Сессия 55): до неё надо
  // дойти дверью, как доходит автор.
  await openLayers(page);

  // Заголовок секции «Элементы» — h2.ed-insp-title внутри .ed-elements.
  const title = page.locator('.ed-elements .ed-insp-title');
  await expect(title).toBeVisible();

  // Кнопка удаления выделенных элементов: та же, что раньше стояла в
  // одинокой div.ed-delete-row. Ищем по имени внутри заголовка секции.
  const deleteButton = title.getByRole('button', { name: 'Удалить', exact: true });
  await expect(deleteButton).toBeVisible();

  const titleBox = await title.boundingBox();
  const buttonBox = await deleteButton.boundingBox();
  if (!titleBox || !buttonBox) throw new Error('заголовок или кнопка не имеют геометрии');

  // Что должно сломаться: вернуть кнопку в отдельную div.ed-delete-row НАД
  // списком — тогда центр кнопки по Y уйдёт далеко вверх от центра строки
  // заголовка, и разница превысит допуск в несколько px.
  const titleCenterY = titleBox.y + titleBox.height / 2;
  const buttonCenterY = buttonBox.y + buttonBox.height / 2;
  expect(Math.abs(titleCenterY - buttonCenterY)).toBeLessThanOrEqual(4);
});
