/**
 * Бюджет высоты нижней зоны: сцена не имеет права исчезнуть (Сессия 47).
 *
 * ЧТО СЛОМАНО И КАК ЭТО ВЫГЛЯДИТ. Нижняя зона — третья строка грида
 * .ed-root (auto 1fr auto), то есть её высота считается ОТ СОДЕРЖИМОГО.
 * Две панели зоны раскрываются кнопкой: «Озвучка» (свёрнута по умолчанию,
 * решение владельца 11.08.2026) и «Слайды» (свёрнута по умолчанию, решение
 * владельца 15.08.2026). Каждая, раскрываясь, растит зону — а растёт зона
 * ВВЕРХ, за счёт строки 1fr, в которой живёт холст. У холста пола нет,
 * и 1fr честно отдаёт всё, что осталось, вплоть до нуля.
 *
 * Замерено 18.08.2026 на живом редакторе, фикстура demo:
 *
 *   окно 1280×800, ничего не раскрыто     зона 367  холст 283
 *   окно 1280×800, лента                  зона 465  холст 185
 *   окно 1280×800, лента + озвучка        зона 567  холст  83
 *   окно 1280×720, лента + озвучка        зона 567  холст   3
 *   окно 1280×660, лента + озвучка        зона 567  холст   0
 *
 * Три пикселя чёрной полоски вместо сцены, «Вписать (7 %)», ни ошибки,
 * ни предупреждения. Автор нажал две кнопки, обе — обычная работа
 * (раскрыть озвучку, чтобы загрузить файл; раскрыть ленту, чтобы
 * посмотреть слайды), и остался без единственного места, ради которого
 * редактор существует.
 *
 * ЭТО ТОТ ЖЕ ДЕФЕКТ, ЧТО УЖЕ ЧИНИЛИ ПО ГОРИЗОНТАЛИ. В styles.ts живёт
 * --ed-stage-min: 320px с дословной причиной: «1fr сцены отдаёт всё, что
 * осталось, то есть НОЛЬ: холст исчезал целиком». Там пол поставили,
 * здесь — нет. Число пола по вертикали взято той же долей: 320/1920 = 1/6,
 * значит 1080/6 = 180. При обоих полах масштаб сцены в упоре одинаков
 * по обеим осям, и это не совпадение, а то же правило.
 *
 * ПОЧЕМУ ЭТОГО НЕ ЛОВИЛ НИ ОДИН ТЕСТ. Все e2e открывают редактор в его
 * состоянии по умолчанию, где обе панели свёрнуты, а там зона 367 и места
 * хватает всем. Дефект живёт ровно в том состоянии, в которое автор
 * переходит руками и в котором ни один тест редактор не видел.
 */
import { expect, test, type Page } from '@playwright/test';

/**
 * Всё постоянное, что стоит между окном и холстом: шапка окна, полоса
 * свойств, полоса масштаба и линия под областью холста. Из этой суммы
 * и из пола сцены складывается бюджет зоны, записанный в styles.ts
 * переменной --ed-zone-budget-offset.
 *
 * Замерено 18.08.2026: 49 + 57 + 43 + 1. Первые три постоянны НАМЕРЕННО,
 * и у каждой в styles.ts своя купленная причина: шапка постоянна, иначе
 * сцена уезжает при выделении элемента; полоса свойств постоянна, иначе
 * элемент уходит из-под курсора между щелчками двойного щелчка (Сессия 29);
 * полоса масштаба постоянна по той же причине.
 *
 * ЧЕТВЁРТОЕ СЛАГАЕМОЕ НАЙДЕНО ПРОГОНОМ. Сумма трёх полос — 149 — выглядела
 * полной, а холст выходил ровно на пиксель меньше: 179 при поле 180. Этим
 * пикселем оказался border-bottom у .ed-main, видимая линия под областью
 * холста. Сложение по памяти дало бы 149 и молча промахнулось.
 */
const CHROME_ABOVE_AND_BELOW = 154;

/** Пол сцены по высоте: 1080/6, та же доля, что у --ed-stage-min (320/1920). */
const STAGE_MIN_H = 180;

async function openEditor(page: Page): Promise<void> {
  await page.goto('/editor.html?fixture=demo', { waitUntil: 'load' });
  await page.waitForFunction(() => document.documentElement.dataset['ready'] === '1', null, {
    timeout: 30_000,
  });
  await page.waitForFunction(
    () => (window as unknown as { __transport?: { state: string } }).__transport?.state === 'ready',
    null,
    { timeout: 30_000 },
  );
}

/** Высоты, из которых складывается вся арифметика зоны, одним замером. */
async function heights(page: Page): Promise<{
  window: number;
  header: number;
  propbar: number;
  zoomStrip: number;
  mainLine: number;
  stageHost: number;
  zone: number;
}> {
  return page.evaluate(() => {
    const node = (selector: string): Element => {
      const found = document.querySelector(selector);
      if (!found) throw new Error(`нет узла ${selector}`);
      return found;
    };
    const h = (selector: string): number => node(selector).getBoundingClientRect().height;
    return {
      window: window.innerHeight,
      header: h('.ed-header'),
      propbar: h('.ed-propbar-row'),
      zoomStrip: h('.ed-zoom-strip'),
      // Линия под областью холста — из вычисленного стиля, а не из
      // раскладки: иначе слагаемое бралось бы из того же источника,
      // что и проверяемая сумма, и тест был бы верен при любой правке.
      // Линия под областью холста. С 20.08.2026 живёт на .ed-stages, а не
      // на .ed-main: нижняя зона переехала ВНУТРЬ .ed-main вторым рядом
      // (рейка и каталог стали колоннами во всю высоту, как у натуры),
      // и линия у .ed-main оказалась бы под дорожкой, а не под холстом.
      // Физически линия там же, где была, — сменился только узел.
      mainLine: Number.parseFloat(getComputedStyle(node('.ed-stages')).borderBottomWidth),
      stageHost: h('.ed-stage-host'),
      zone: h('.ed-track-column'),
    };
  });
}

/**
 * НЕСУЩИЙ ТЕСТ. Что должно сломаться, чтобы он покраснел: любое снятие
 * потолка с нижней зоны. На коде до починки даёт 3 px против порога 180.
 *
 * Окно 1280×720 — не произвольное: это ноутбучный размер, на котором дефект
 * доходит до крайности (холст 3 px). На 800 он даёт 83 px — тоже негодные,
 * но 3 px нагляднее и порог ловит оба.
 */
test('нижняя зона: раскрыв обе панели, автор не остаётся без сцены', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 720 });
  await openEditor(page);

  // Положительный контроль ДО жеста: пока панели свёрнуты, сцена цела.
  // Без него «сцена мала» и «редактор не открылся» выглядят одинаково.
  const before = await heights(page);
  expect(before.stageHost, 'до раскрытия панелей сцена уже мала — прибор врёт').toBeGreaterThan(
    STAGE_MIN_H,
  );

  await page.getByTestId('audio-source-toggle').click();
  await page.getByTestId('slide-strip-toggle').click();

  // Обе панели ДЕЙСТВИТЕЛЬНО раскрылись. Без этой проверки тест зелен,
  // когда кнопки перестали работать вовсе: нераскрытая панель зону
  // не растит, и сцена остаётся целой по неверной причине.
  await expect(page.getByTestId('audio-source-toggle')).toHaveAttribute('aria-expanded', 'true');
  await expect(page.getByTestId('slide-strip-toggle')).toHaveAttribute('aria-expanded', 'true');
  await expect(page.getByTestId('slide-strip')).toBeVisible();

  const after = await heights(page);
  expect(
    after.zone,
    'зона не выросла — значит раскрытие панелей ничего не изменило, и тест ничего не проверяет',
  ).toBeGreaterThan(before.zone);

  expect(
    after.stageHost,
    `сцена ужата до ${after.stageHost} px при поле ${STAGE_MIN_H}: раскрыв панели зоны, автор остался без холста`,
  ).toBeGreaterThanOrEqual(STAGE_MIN_H);
});

/**
 * Тот же дефект на 1280×800 — размере, на котором работает вся остальная
 * проверка. Отдельным тестом, а не параметром: 800 это умолчание конфига,
 * и покрасневший на нём тест читается как «сломано у всех», а не «сломано
 * на маленьком окне».
 */
test('нижняя зона: на 1280×800 раскрытые панели тоже не съедают сцену', async ({ page }) => {
  await openEditor(page);
  const before = await heights(page);
  expect(before.window, 'окно не 800 — тест меряет не то, что называет').toBe(800);

  await page.getByTestId('audio-source-toggle').click();
  await page.getByTestId('slide-strip-toggle').click();
  await expect(page.getByTestId('slide-strip')).toBeVisible();

  const after = await heights(page);
  expect(after.zone).toBeGreaterThan(before.zone);
  expect(
    after.stageHost,
    `сцена ужата до ${after.stageHost} px при поле ${STAGE_MIN_H}`,
  ).toBeGreaterThanOrEqual(STAGE_MIN_H);
});

/**
 * ОХРАНА ЧИСЛА, А НЕ ПОВЕДЕНИЯ. Потолок зоны в styles.ts записан как
 * calc(100vh - 330px), где 330 = 150 постоянного хрома + 180 пола сцены.
 * Литерал в CSS считать неоткуда, и он сгниёт молча в тот день, когда
 * шапке добавят строку. Этот тест — единственное место, где он сверяется
 * с живым браузером.
 *
 * Что должно сломаться, чтобы он покраснел: изменение высоты шапки, полосы
 * свойств, полосы масштаба или толщины линии под холстом без правки числа
 * в styles.ts.
 */
test('нижняя зона: постоянный хром между окном и холстом складывается в 154 px', async ({
  page,
}) => {
  await openEditor(page);
  const measured = await heights(page);
  const sum = measured.header + measured.propbar + measured.zoomStrip + measured.mainLine;
  expect(
    sum,
    `постоянный хром даёт ${sum} px (шапка ${measured.header}, свойства ${measured.propbar}, масштаб ${measured.zoomStrip}, линия ${measured.mainLine}) — потолок зоны в styles.ts считает от ${CHROME_ABOVE_AND_BELOW}`,
  ).toBe(CHROME_ABOVE_AND_BELOW);
});

/**
 * ОХРАНА ОБЩЕГО РЕСУРСА. Высота зоны в состоянии по умолчанию — та самая
 * величина, от которой считается масштаб сцены, а от него — пороги
 * прилипания в жестовых e2e ЧУЖИХ файлов. Связь неочевидна и уже роняла
 * чужие тесты (Сессия 18: панель действий отняла 44 px, масштаб упал
 * с 0.208333 до 0.202778).
 *
 * Что должно сломаться, чтобы он покраснел: любая правка, сдвинувшая зону
 * в состоянии по умолчанию. Потолок зоны такой правкой быть НЕ должен:
 * на 1280×800 он равен 800 − 330 = 470, а зона по умолчанию 306.
 *
 * ЧИСЛА ОБНОВЛЕНЫ ОДИН РАЗ, ОСОЗНАННО, и вот чем это отличается от подгонки
 * теста под код. Задача 2 свела три полосы-заголовка нижней зоны в одну
 * и освободила 61 px; решение отдать их ХОЛСТУ, а не дорожке, принято
 * приёмщиком явно 18.08.2026 — из-за главной жалобы владельца, что сцена
 * крошечная. Зона 367 → 306, холст 283 → 344, вписывание 23 % → 28 %.
 * То есть сдвиг чисел здесь и есть предмет работы, а не её побочный след.
 *
 * Тест при этом не ослаб: он по-прежнему падает от ЛЮБОЙ незапланированной
 * правки высоты зоны — просто теперь охраняет новое значение.
 *
 * ЧИСЛА ОБНОВЛЕНЫ ВТОРОЙ РАЗ 20.08.2026, и здесь сдвиг — СЛЕД работы,
 * а не её предмет. Называю прямо, потому что разница важна.
 *
 * Нижняя зона переехала внутрь .ed-main вторым рядом: рейка и каталог
 * стали колоннами во всю высоту, а зона — правее них, как у обеих натур
 * (замер КапКута: зона с x = 356, не с нуля; замер Канвы 20.08: нижняя
 * строка окна тоже начинается правее панели). Зона стала уже: 1440 -> 1012
 * при окне 1440.
 *
 * И вот следствие, которое числа поймали, а глаз бы пропустил: строка
 * причин над лентой слайдов («Первый слайд вырезать нельзя · Начало главы
 * занято · Буфер пуст») в узкой зоне ПЕРЕНОСИТСЯ на вторую строку.
 * Замер: высота 37 вместо 21, нужно 852 px при доступных 852. Зона
 * 306 -> 322, холст 344 -> 328 — ровно те же 16 px.
 *
 * То есть высота холста зависит от того, влез ли текст в ширину окна.
 * Это дефект, и лечится он не числом: три причины относятся к ТРЁМ разным
 * кнопкам и печатаются одновременно, хотя место каждой — в подсказке
 * своей кнопки. Формулировки уже укорочены (state/slides.ts, Editor.tsx),
 * этого не хватило. Полная починка трогает ленту слайдов, то есть нижнюю
 * зону, а её переделка идёт отдельной частью по прямому слову владельца.
 * Долг записан вслух: docs/research/2026-08-20-journal-redesign-canva.md.
 *
 * ЧИСЛО ХОЛСТА ПОДРОСЛО 328 -> 331 в тот же день, и это ПРИБЫЛЬ, а не сдвиг:
 * полоса масштаба приведена к натурным 40 px (была 43) и потеряла верхнюю
 * линию, которая входила в постоянный хром отдельным пикселем. Три пикселя
 * ушли холсту. Высота зоны при этом не изменилась вовсе.
 *
 * ЧИСЛА ОБНОВЛЕНЫ ТРЕТИЙ РАЗ 21.08.2026, и здесь сдвиг — ПРЕДМЕТ работы,
 * а не её след. Называю прямо, потому что разница важна и потому что этот
 * тест — единственное место, где такие сдвиги вообще видны.
 *
 * Из зоны удалены ТРИ РЯДА ОРГАНОВ, которых у обеих натур над дорожкой нет
 * вовсе (замер 21.08.2026: у Канвы над дорожкой ноль органов, у КапКута один
 * ряд значков; у нас было 17 кнопок в трёх рядах, 96 px из 306):
 *
 *   .ed-transport (40)          -> транспорт в нижнюю полосу окна, по центру
 *   .ed-slide-strip-note (21)   -> причины в пункты меню правой кнопки
 *   часть .ed-zone-head          -> переключатель вида в ту же полосу,
 *                                   буфер слайдов в меню по метке слайда
 *
 * Зона 322 -> 233, холст 324 -> 413. Восемьдесят девять пикселей отданы
 * ХОЛСТУ — ровно то, на что владелец жаловался громче всего («сцена
 * крошечная»), и ровно то, ради чего затевалась переделка.
 *
 * ПОСТОЯННЫЙ ХРОМ ПРИ ЭТОМ НЕ ИЗМЕНИЛСЯ и остался 154: полоса масштаба
 * никуда не переезжала, она лишь получила две новые группы внутри той же
 * высоты 40. Это не совпадение, а проверка на то, что зона похудела сама,
 * а не за счёт чего-то над ней.
 *
 * И ТУТ ЖЕ УБЫЛО 331 -> 324: строка полосы свойств 48 -> 56, чтобы вокруг
 * всплывающей пилюли был воздух (у натуры пилюля 40 в строке 56, по 8
 * сверху и снизу). Семь пикселей отданы обратно осознанно, по прямому
 * слову владельца — «она должна как бы летать», — и названы здесь вслух,
 * чтобы следующий не искал, куда они делись.
 */
test('нижняя зона: в состоянии по умолчанию её высота не сдвинулась', async ({ page }) => {
  await openEditor(page);
  const measured = await heights(page);
  expect(measured.window).toBe(800);
  expect(measured.zone, 'высота зоны по умолчанию уехала — проверьте чужие жестовые e2e').toBe(233);
  expect(measured.stageHost, 'высота холста по умолчанию уехала').toBe(413);
});
