/**
 * Список элементов: обрезанную подпись можно прочитать целиком.
 *
 * Замер 18.08.2026 (фикстура demo, окно 1280): колонка списка 231 px,
 * обрезаны ПЯТЬ строк из семи. Худшая — «Возобновление — с той же секунды.
 * Перем…»: нужно 251 px, видно 123. Остальные: 239/133, 214/135, 162/123,
 * 116/112.
 *
 * Обрезка сама по себе законна: шире колонке взяться неоткуда, а полная
 * подпись длиннее всей строки целиком (251 против 231), то есть не помещается
 * ни при каком расположении внутри неё. Незаконно было то, что прочитать
 * подпись целиком нельзя было НИГДЕ рядом со списком.
 *
 * ⚠️ Оговорка, названная вслух: «нигде» верно не полностью. У ТЕКСТОВОГО
 * элемента полное содержимое читается в панели «Объект» (`Inspector`,
 * `MultilineField` «Текст»), а фон фигуры — в поле стиля. Но добраться туда
 * можно только выделив элемент и открыв «Ещё…» — ту самую дверь, которая
 * до Задачи 1 лежала за краем полосы и не была видна вовсе. Здесь чинится
 * сам список: он существует, чтобы РАЗЛИЧАТЬ элементы, а две строки,
 * обрезанные до одинакового начала, различить не дают.
 */
import { expect, test, type Page } from '@playwright/test';

test.use({ viewport: { width: 1280, height: 800 } });

async function openEditor(page: Page): Promise<void> {
  await page.goto('/editor.html?fixture=demo', { waitUntil: 'load' });
  await page.waitForFunction(() => document.documentElement.dataset['ready'] === '1', null, {
    timeout: 30_000,
  });
  await expect(page.getByTestId('element-row-title')).toBeVisible();
}

/**
 * Что должно сломаться, чтобы покраснел: снять `title` со строки списка —
 * обрезанная подпись снова становится нечитаемой целиком.
 *
 * Откуда взято ожидаемое (второй вопрос к тесту, после «что сломается»):
 * из `textContent` подписи, а НЕ из того же атрибута, который проверяется.
 * CSS-обрезка многоточием не трогает textContent, поэтому там лежит полный
 * текст, а в title — то, что положил код. Источники разные, тождеством
 * проверка быть не может.
 *
 * Пустой она тоже быть не может: положительный контроль требует, чтобы
 * обрезанные строки на этом окне ДЕЙСТВИТЕЛЬНО были.
 */
test('обрезанную подпись элемента можно прочитать целиком', async ({ page }) => {
  await openEditor(page);

  const probe = await page.evaluate(() => {
    const rows = Array.from(document.querySelectorAll('.ed-element-item'));
    return rows.map((item) => {
      const summary = item.querySelector('.ed-element-summary');
      const button = item.querySelector('.ed-element-row');
      if (!summary || !button) throw new Error('строка списка без подписи или без кнопки');
      return {
        full: (summary.textContent ?? '').trim(),
        cut: summary.scrollWidth > summary.clientWidth,
        client: summary.clientWidth,
        scroll: summary.scrollWidth,
        title: button.getAttribute('title'),
      };
    });
  });

  // Положительный контроль: обрезка на этом окне действительно есть,
  // иначе проверять «читается ли обрезанное» не на чем.
  const cut = probe.filter((row) => row.cut);
  expect(cut.length, `ни одна подпись не обрезана — проверять нечего`).toBeGreaterThanOrEqual(3);

  for (const row of cut) {
    expect(
      row.title,
      `подпись обрезана (${row.client} из ${row.scroll} px), а прочитать её негде: «${row.full}»`,
    ).not.toBeNull();

    // Подсказка обязана быть про ЭТУ строку, а не про соседнюю: видимое
    // начало (без многоточия, которое дописал потолок в 40 знаков) обязано
    // быть началом подсказки. Сравнение равенством тут было бы неверным
    // и поймало бы исправный код: видимое намеренно короче полного.
    const stem = row.full.replace(/…$/u, '');
    expect(
      row.title!.startsWith(stem),
      `подсказка не про эту строку: видно «${row.full}», в подсказке «${row.title}»`,
    ).toBe(true);
    expect(row.title!.length).toBeGreaterThanOrEqual(stem.length);
  }
});

/**
 * Подпись обязана быть ПОЛНОЙ, а не той же обрезанной строкой.
 *
 * Отдельным тестом, а не проверкой внутри предыдущего: тот сравнивает title
 * с textContent и остался бы зелёным, если бы обрезать начали ОБА — например,
 * укоротив саму подпись в `elementRows.ts`. Здесь ожидаемое берётся из
 * ТРЕТЬЕГО источника — из текста проекта, который знает фикстура, — и
 * поэтому ловит и такой случай.
 *
 * Что должно сломаться, чтобы покраснел: начать класть в title обрезанное
 * значение (например, `row.summary.slice(0, 20)`).
 */
test('в подсказке лежит полный текст, а не обрезанный', async ({ page }) => {
  await openEditor(page);

  const title = await page.getByTestId('element-row-footer').getAttribute('title');
  expect(title, 'у строки footer нет подсказки').not.toBeNull();
  // Фикстура demo: текст элемента footer начинается этими словами и
  // продолжается за краем колонки. Проверяем именно ХВОСТ — начало видно
  // и без подсказки, и тест на нём был бы зелёным при любой обрезке.
  expect(title).toContain('Перемотки не происходит');
});
