/**
 * @player/player — Видео как ведомая картинка.
 *
 * Решение и числа — [ADR-028](../../../docs/adr/ADR-028-video-follows-audio.md),
 * замеры — `docs/research/2026-08-12-video-sync.md`.
 *
 * **Инвариант №1 здесь не нарушается, а исполняется.** Видео не двигает
 * сцену, не открывает гейт и не завершает сегмент: оно картинка, которой
 * говорят, где быть. Право решать остаётся у позиции аудио.
 *
 * Почему не «выставлять время каждый кадр», как ведётся таймлайн
 * (инвариант №2): замерено, что при этом картинка идёт **10.1 кадра
 * в секунду вместо 30**, с 65 залипаниями за минуту и провалами до 866 мс.
 * Установка `currentTime` чаще, чем видео успевает выдать кадр, не ускоряет
 * показ, а подавляет его. Цена самой установки при этом ничтожна (p95
 * 0.1 мс) — отвергнуто по тому, что видит зритель, а не по стоимости.
 *
 * Почему сверка редкая: у видео **собственный ровный ход**. Замерено, что
 * свободно идущее видео отстаёт от звука на 17.4–18.1 мс и за минуту
 * не уезжает ни на миллисекунду. Порог 0.25 с за ту же минуту не был
 * превышен ни разу — механизм существует как страховка (декодер способен
 * залипнуть на слабой машине или при уходе вкладки в фон), а не как
 * рабочий режим.
 */

/**
 * Порог сверки, СЕКУНДЫ МЕДИАВРЕМЕНИ.
 *
 * Не кадры и не пиксели: сравниваются позиции, у которых нет экранной
 * природы. Названо явно по той же причине, по какой `SNAP_PX` назван
 * ЭКРАННЫМИ пикселями — единица, оставленная подразумеваемой, однажды
 * уже дала верный ответ по неверной причине.
 *
 * Величина взята много больше кадра (0.25 с против 0.033 с) намеренно:
 * задача порога — не догонять полкадра, а поймать залипание декодера.
 */
export const VIDEO_RESYNC_S = 0.25;

/**
 * Видео с точки зрения синхронизации: ровно то, что нужно, и ничего сверх.
 *
 * Узкий тип, а не `HTMLVideoElement`, по двум причинам. Во-первых, это
 * граница модуля: всё остальное у медиаэлемента к синхронизации отношения
 * не имеет. Во-вторых, юнит-тесты плеера идут в среде `node` без DOM
 * (`vitest.config.ts`), и настоящего `<video>` там не существует.
 *
 * Имя проверено на столкновение с глобальными DOM-типами: `TimedVideo`
 * двойника не имеет. (Тип `Node` из ядра однажды сломал бы
 * `target instanceof Node` в `StageView` — коллизию ищут заранее.)
 */
export interface TimedVideo {
  /** Пусто — источника нет; такой узел не трогаем вовсе. */
  readonly src: string;
  currentTime: number;
  readonly paused: boolean;
  play(): Promise<void>;
  pause(): void;
}

/** Собирает видео-узлы сцены. Отдельно от логики: в среде `node` не зовётся. */
export function collectVideos(stage: HTMLElement): TimedVideo[] {
  return [...stage.querySelectorAll('video')];
}

/**
 * Сверка в кадре: поправить, только если расхождение перевалило порог.
 *
 * Возвращает число исправленных — по нему тест отличает «промолчал»
 * от «поправил», не заглядывая внутрь.
 *
 * `position` — позиция в ДОРОЖКЕ, а не в сегменте. При сценарии «один файл»
 * (голос и лицо — одна запись) медиавремя видео совпадает с медиавременем
 * дорожки, а время сегмента отличается от него на `audio.offset`
 * (`player.ts`, `#toSegmentTime`). Перепутать легко, и при `offset = 0`
 * ошибка невидима: обе шкалы совпадают.
 */
export function syncVideos(videos: readonly TimedVideo[], position: number): number {
  let corrected = 0;
  for (const video of videos) {
    if (video.src === '') continue;
    if (Math.abs(video.currentTime - position) > VIDEO_RESYNC_S) {
      video.currentTime = position;
      corrected += 1;
    }
  }
  return corrected;
}

/**
 * Пуск по расписанию: выставить позицию и играть.
 *
 * Позиция ставится БЕЗУСЛОВНО, а не по порогу, — это момент расписания,
 * а не сверка. Замерено, почему момент важен: старт, опоздавший на 60 мс,
 * даёт постоянный сдвиг −40…−47 мс, который дальше никуда не уходит.
 * Вся точность синхронизации сводится к тому, когда позван `play()`.
 *
 * Тот же приём и по той же причине, что стык узлов в S9: **планируется,
 * а не обнаруживается**.
 */
export function startVideos(videos: readonly TimedVideo[], position: number): void {
  for (const video of videos) {
    if (video.src === '') continue;
    video.currentTime = position;
    void video.play().catch((error: unknown) => {
      // Не глушим и не подставляем фолбэк: отказ автовоспроизведения —
      // настоящая поломка синхронности, и молчащая картинка при идущем
      // звуке выглядит как «видео сломалось», а не как «политика браузера».
      console.error('[video] play() отклонён, картинка встанет при идущем звуке:', error);
    });
  }
}

/**
 * Остановка: гейт, конец сегмента, уничтожение.
 *
 * Инвариант №4 для видео исполняется тем же механизмом, что для звука:
 * замерено, что за 1.2 с остановки через `ctx.suspend()` позиция не ушла
 * на 0 мс, видео не ушло на 0 мс, показано 0 кадров, назад не поехало
 * ничего. Возобновление — с той же позиции, перемотки не возникает.
 */
export function pauseVideos(videos: readonly TimedVideo[]): void {
  for (const video of videos) {
    if (video.src === '') continue;
    video.pause();
  }
}
