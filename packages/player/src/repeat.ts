/**
 * Повтор куска: что молчит, когда зритель возвращается к уже слышанному.
 *
 * Автор может провести ребро выхода НАЗАД, к уже пройденному куску —
 * «повтори объяснение и попробуй снова». Решение владельца (02.08.2026):
 * остановки ВНУТРИ повторяемого куска не открываются повторно; остановка,
 * которая отправила на повтор, спрашивает снова.
 *
 * Модуль делится надвое так же, как `morph.ts` делится на `planMorph`
 * и `buildMorph`: обе функции здесь — чистые запросы без DOM и без часов,
 * поэтому проверяются юнит-тестом напрямую. `Player` их ЗОВЁТ и не хранит
 * своей копии этого правила — расхождение между классом и тестом было бы
 * тихим и невидимым ни в одном юните.
 */

/**
 * Какие остановки этого куска откроются на текущем проходе.
 *
 * Молчит та, на которую в ЭТОМ просмотре уже отвечали (§5 [Р] `product.md`:
 * «гейты внутри не задаются заново»). Зритель вернулся посмотреть
 * объяснение, а не переотвечать на решённое.
 *
 * След — отдельное множество идентификаторов, а НЕ наличие значения
 * в `answers`: предпросмотр редактора «смотреть как зритель, ответивший X»
 * засевает ответы заранее, и по ним остановки замолчали бы, не открывшись
 * ни разу.
 *
 * Порядок результата совпадает с порядком входа — расписание строится
 * дальше сортировкой по времени, но само отфильтрованное перечисление
 * не должно тасовать то, что не тасовал автор.
 */
export function openableGates<G extends { id: string }>(
  gates: readonly G[],
  answeredHere: ReadonlySet<string>,
): G[] {
  return gates.filter((gate) => !answeredHere.has(gate.id));
}

/**
 * Чьи ответы стереть, уходя на повтор.
 *
 * Стираются ровно те остановки, чьи переменные прочитало СРАБОТАВШЕЕ
 * правило выхода. Иначе зритель вернётся, доиграет пройденное, попадёт
 * в ту же развилку с тем же ответом и уедет на повтор снова — вечная петля
 * по построению.
 *
 * `rule === null` — сработал запасной выход, у него условий нет и стирать
 * нечего.
 *
 * Ищет по ВСЕМ сегментам объяснения, а не только по тому, откуда зритель
 * уходит: переменную мог записать гейт из другого куска (ответы живут
 * на всё объяснение, не на сегмент), и виновная остановка обязана
 * найтись независимо от того, где она стоит.
 */
export function answersToClear(
  segments: readonly { gates: readonly { id: string; recordAs: string }[] }[],
  rule: { when: readonly { variable?: string }[] } | null,
): Set<string> {
  const cleared = new Set<string>();
  if (rule === null) return cleared;

  // Условие без переменной в реальной схеме не встречается (у каждого вида
  // Condition она обязательна), но входной тип здесь — узкая структурная
  // форма, а не Condition целиком: пропустить недостающее поле дешевле,
  // чем уронить весь переход из-за формы, которую функция сама не диктует.
  const read = new Set(
    rule.when
      .map((condition) => condition.variable)
      .filter((variable): variable is string => variable !== undefined),
  );

  for (const segment of segments) {
    for (const gate of segment.gates) {
      if (read.has(gate.recordAs)) cleared.add(gate.id);
    }
  }
  return cleared;
}
