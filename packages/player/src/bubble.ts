/**
 * Права зрителя на каплю: кто ею владеет в этот момент и что зритель может.
 *
 * → ADR-032, docs/design/bubble.md §2
 *
 * Инвариант №3 не ослаблен, а уточнён: сцена остаётся `pointer-events: none`
 * навсегда, а разрешение выдаётся ОДНОМУ элементу и ТОЛЬКО вне авторских
 * отрезков. Измерено (S17): `pointer-events: auto` на потомке мёртвой сцены
 * возвращает попадания ему одному, сосед остаётся `body`.
 *
 * Правки зрителя живут ЗДЕСЬ, а не в проекте: это его настройка, как
 * громкость, и границей главы она не сбрасывается (решение владельца
 * 13.08.2026).
 */
import { resolveTimeRef, type AuthorSpan, type Word } from '@player/core';

/** Кто распоряжается элементом в этот момент. */
export type Owner = 'author' | 'viewer';

/**
 * Насколько ужимается свёрнутая капля.
 *
 * Ужимается, а не прячется `display: none`. Разница измерена и несущая:
 * голос живёт ВНУТРИ того же видеофайла, и единственный способ его потерять —
 * вынуть узел из документа (S17: 0 байт звука, пауза). Любое сокрытие стилем
 * звук сохраняет.
 *
 * Не ровно ноль: нулевой масштаб в некоторых сборках схлопывает матрицу
 * и роняет элемент со слоя композитора, а доезд обратно тогда идёт рывком.
 */
const COLLAPSED_SCALE = 0.001;

/**
 * Сколько длится доезд капли к авторскому месту.
 *
 * `bubble.md` §2: возврат к автору ПЛАВНЫЙ, а не прыжком. Здесь это переход
 * по `scale` — свойство семейства трансформаций, то есть композитор,
 * а не раскладка (инвариант №8).
 */
const RETURN_MS = 280;

/**
 * Кому принадлежит элемент в этот момент.
 *
 * Границы отрезка ВКЛЮЧАЮТСЯ в авторское владение с обеих сторон? Нет:
 * начало включается, конец — нет. Иначе два отрезка встык (а их порождает
 * разрез главы) дали бы на своей общей секунде двух хозяев сразу, и ответ
 * зависел бы от порядка перебора.
 */
export function ownerAt(
  spans: readonly AuthorSpan[],
  words: readonly Word[],
  elementId: string,
  seconds: number,
): Owner {
  for (const span of spans) {
    if (span.elementId !== elementId) continue;
    const from = resolveTimeRef(span.from, words);
    const to = resolveTimeRef(span.to, words);
    if (seconds >= from && seconds < to) return 'author';
  }
  return 'viewer';
}

/**
 * Какой элемент главы является каплей.
 *
 * ПЕРВЫЙ элемент типа `video`. Правило живёт здесь, а не в редакторе,
 * чтобы у автора и у зрителя оно было одно: разойдись эти два ответа —
 * автор рисовал бы отрезки одной голове, а права получала бы другая,
 * и заметить это можно было бы только глазами на чужом проекте.
 * Направление зависимостей это разрешает: `editor → player` (инвариант №6).
 *
 * Несколько капель на сцене одновременно не измерены ни разу (`bubble.md`
 * §8.3: цена двойного декодирования неизвестна), поэтому вторая и далее
 * прав не получают — и это названо здесь, а не выяснится однажды само.
 */
export function bubbleElementOf(
  elements: readonly { readonly id: string; readonly type: string }[],
): string | undefined {
  return elements.find((element) => element.type === 'video')?.id;
}

/** Что зритель сделал с каплей. Живёт в плеере и переживает смену главы. */
export interface ViewerState {
  collapsed: boolean;
}

/**
 * Применяет владение к живому узлу капли.
 *
 * Ужимание идёт через НЕЗАВИСИМОЕ свойство `scale`, а не через `transform`,
 * и это не стилистика. `transform` принадлежит рендеру (поворот элемента)
 * и морфингу (переход между слайдами); запиши мы туда — две правды об одном
 * свойстве стирали бы друг друга на каждом слайде. `filter` тоже занят:
 * им работает переход «размытие». `scale` не трогает никто, а складывается
 * с `transform` сам, оставаясь на композиторе.
 */
export function applyOwnership(
  node: HTMLElement,
  owner: Owner,
  viewer: ViewerState,
): void {
  if (owner === 'author') {
    // Внутри отрезка зритель не может НИЧЕГО — ни свернуть, ни двинуть.
    // Указатель не возвращается, свёрнутость зрителя не применяется:
    // капля доезжает до авторского состояния переходом ниже.
    node.style.pointerEvents = '';
    node.style.scale = '';
    node.style.transition = `scale ${RETURN_MS}ms ease`;
    return;
  }

  node.style.pointerEvents = 'auto';
  node.style.transition = `scale ${RETURN_MS}ms ease`;
  node.style.scale = viewer.collapsed ? String(COLLAPSED_SCALE) : '';
}

/** Снимает всё, что поставило владение: узел возвращается рендеру нетронутым. */
export function clearOwnership(node: HTMLElement): void {
  node.style.pointerEvents = '';
  node.style.scale = '';
  node.style.transition = '';
}
