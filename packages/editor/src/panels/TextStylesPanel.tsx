/**
 * Вкладка «Текст»: список карточек, в каждой — образец, написанный СВОИМ
 * кеглем.
 *
 * ⬛ ПОЧЕМУ ЭТО НЕ СЕТКА ПЛИТОК, ХОТЯ ОСТАЛЬНЫЕ ВКЛАДКИ — СЕТКА.
 *
 * До 20.08.2026 текстовые заготовки показывались той же сеткой 3×2, что
 * фигуры и шаблоны: шесть чёрных квадратиков со снимком сцены внутри.
 * Владелец положил рядом натуру и наш экран и сказал, что не похоже даже
 * примерно. Он был прав, и дело не в оформлении: у натуры это ДРУГОЙ
 * КОМПОНЕНТ.
 *
 * Замер живой Канвы 20.08.2026, вкладка «Текст», окно 1879×968:
 *
 *   поиск            328×56  @88,73   r=16, рамка 1, кегль 14/400
 *   главная кнопка   328×40  @88,145  залитая, r=12, 14/600, белый текст
 *   вторая кнопка    328×40  @88,193  прозрачная, r=12, 14/600
 *   заголовок раздела «Стили текста по умолчанию» 14/600
 *   карточка 1       313×90  @88,373  r=16, поле 16, образец 28/700
 *   карточка 2       313×51  @88,471  r=16, поле 16, образец 16.8/700
 *   карточка 3       313×46  @88,530  r=16, поле 16, образец 12/400
 *   зазор карточек   8
 *
 * Смысл приёма: карточка показывает не «как это будет выглядеть на сцене»,
 * а СТУПЕНЬ РАЗМЕРА, и показывает её прямым текстом. Высота карточки сама
 * следует за кеглем — 90 у заголовка против 46 у основного, — поэтому
 * ступени видны ещё до чтения, одной формой списка.
 *
 * Снимок сцены здесь был бы хуже, а не лучше: в масштабе 1920×1080 подпись
 * в 28 px превращается в четыре пикселя, а вписанная в свою коробку она
 * теряет ровно то, ради чего её выбирают, — соотношение с соседними
 * ступенями.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ: «Волшебный текст» (у них — генерация текста
 * моделью), «Фирменные шрифты» и «Динамический текст» с нумерацией страниц.
 * Это их возможности, которых у нас нет; кнопка без действия — обман
 * такой же, как пункт рейки без содержимого.
 */
import type { ReactElement } from 'react';

import { ELEMENT_LIBRARY } from '../state/library.js';
import { Button, EmptyState } from '../ui/index.js';

export interface TextStylesPanelProps {
  onInsert: (itemId: string) => void;
  /** Что набрано в поиске панели. Пустая строка — показать всё. */
  query: string;
}

/**
 * Кегль образца в карточке — НЕ кегль заготовки на сцене.
 *
 * На сцене заголовок 96 px при ширине 1920; в карточке шириной 313 такой
 * образец не поместился бы вовсе. Показывается ступень, приведённая
 * к панели: отношения между ступенями сохранены (заголовок вдвое крупнее
 * подзаголовка, тот вдвое крупнее подписи), а абсолютные числа взяты
 * с натуры — 28 / 16.8 / 12.
 */
const SAMPLE_SIZE: Readonly<Record<string, { size: number; weight: number }>> = {
  'text-title': { size: 28, weight: 700 },
  'text-subtitle': { size: 17, weight: 700 },
  text: { size: 14, weight: 400 },
  'text-body': { size: 12, weight: 400 },
  'text-caption': { size: 11, weight: 400 },
  'text-quote': { size: 15, weight: 400 },
};

export function TextStylesPanel({ onInsert, query }: TextStylesPanelProps): ReactElement {
  const needle = query.trim().toLowerCase();
  /*
   * Порядок карточек — ОТ КРУПНОГО К МЕЛКОМУ, как у натуры: заголовок,
   * подзаголовок, основной текст. Список ступеней читается сверху вниз,
   * и обратный порядок ломал бы это чтение.
   *
   * Заготовка `text` из карточек ИСКЛЮЧЕНА: её кладёт главная кнопка над
   * списком, и вторая точка входа в то же действие — задвоение, которое
   * этот проект уже покупал («две панели рядом дают две одинаковые
   * подписи»). У натуры так же: кнопка сверху, ступени под ней, и «просто
   * текстового поля» среди ступеней нет.
   */
  const ORDER = ['text-title', 'text-subtitle', 'text-body', 'text-caption', 'text-quote'];
  const items = ELEMENT_LIBRARY
    .filter((item) => item.category === 'text' && item.id !== 'text'
      && (needle === '' || item.label.toLowerCase().includes(needle)))
    .slice()
    .sort((a, b) => ORDER.indexOf(a.id) - ORDER.indexOf(b.id));

  if (items.length === 0) {
    return <EmptyState title="Ничего не нашлось" hint="Попробуйте другое слово" />;
  }

  return (
    <>
      {/* Главное действие вкладки — залитая кнопка во всю ширину, как
          у натуры («Добавить текстовое поле», 328×40, r=12). Она кладёт
          заготовку `text` — ту же, что раньше клала плитка с этим именем;
          плитки больше нет, чтобы одно действие не имело двух точек входа
          на одном экране. */}
      <Button
        kind="главная"
        className="ed-text-add"
        /* Имя органа осталось прежним — insert-text. Оно называет ДЕЙСТВИЕ
           («вставить текст»), а не место, где стоит кнопка; действие то же
           самое, что делала прежняя плитка. Завести новое имя значило бы
           объявить новое действие и заодно оборвать десяток существующих
           проверок, которые проверяют вставку, а не вёрстку панели. */
        data-testid="insert-text"
        onClick={() => onInsert('text')}
      >
        Добавить текстовое поле
      </Button>

      <div className="ed-catalog-section">
        <h3 className="ed-catalog-section-title">
          {needle === '' ? 'Стили текста' : 'Найдено'}
        </h3>
        <span className="ed-catalog-section-note">{items.length}</span>
      </div>

      <div className="ed-text-styles" role="list">
        {items.map((item) => {
          const sample = SAMPLE_SIZE[item.id] ?? { size: 14, weight: 400 };
          return (
            <button
              key={item.id}
              type="button"
              role="listitem"
              className="ed-text-style-card"
              data-testid={`insert-${item.id}`}
              onClick={() => onInsert(item.id)}
            >
              <span
                className="ed-text-style-sample"
                style={{ fontSize: `${sample.size}px`, fontWeight: sample.weight }}
              >
                {item.label}
              </span>
            </button>
          );
        })}
      </div>
    </>
  );
}
