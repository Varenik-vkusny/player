/**
 * Категории каталога хрома редактора — ДАННЫЕ, а не разметка.
 *
 * По образцу `state/library.ts`: рельс (`CatalogRail.tsx`) рисует кнопки
 * перебором этого массива, а не литералами в JSX. Так пополнение каталога
 * (шестая категория, другая подпись) требует правки только этого файла.
 */
import type { IconName } from '../ui/index.js';

/** Одна категория рельса: что показывает и как подписана кнопка. */
export interface CatalogCategory {
  readonly id: CategoryId;
  /** Русская подпись кнопки и головы панели. */
  readonly label: string;
  /**
   * Контур значка кнопки — имя из закрытого перечня `ui/icons.ts` (Lucide,
   * ADR-034). До Сессии 52 здесь был `glyph: string`, один символ шрифта
   * (▦ ◇ T ◐ ✦ ↑): буква системного шрифта, размер и толщина которой не
   * подчиняются ничему, а на машине без глифа остаётся пустой прямоугольник
   * молча, без ошибки. Контур рисует сам редактор — и выглядит одинаково
   * везде.
   */
  readonly icon: IconName;
  /** Пояснение одной фразой, показывается в голове панели под заголовком. */
  readonly hint: string;
}

/** Категории рельса — порядок совпадает с порядком кнопок сверху вниз. */
export type CategoryId = 'templates' | 'shapes' | 'text' | 'theme' | 'styles' | 'own';

/**
 * Идентификатор ЛЮБОЙ панели каталога, включая `object`.
 *
 * `object` — панель свойств выделенного элемента. На рельсе её нет и не
 * может быть: она открывается кнопкой с полосы свойств, а не с рельса,
 * потому что без выделенного элемента показывать нечего. Отдельный тип
 * (шире `CategoryId`) существует, чтобы состояние «какая панель открыта»
 * могло принять это значение, а рельс — не мог его нарисовать.
 */
export type PanelId = CategoryId | 'object' | 'layers' | 'chapters' | 'mark';

/*
 * ПАНЕЛИ БЕЗ ПУНКТА НА РЕЙКЕ: object, layers, chapters, mark.
 *
 * До 20.08.2026 списки элементов, слайдов и глав жили в отдельной ПРАВОЙ
 * колонке. Замер натуры: у Канвы справа от полотна нет ничего — панели
 * открываются только слева, от рейки, а свойства выделенного живут
 * в полосе над полотном. То же у КапКута с точностью до того, что у него
 * справа панель свойств, а не списки.
 *
 * Решение владельца 19.08.2026 — «убрать совсем, как у Канвы». Панели
 * не удалены: они переехали туда, где у нас уже живёт `object` (панель
 * свойств выделенного, переехавшая с правой колонки ещё в Сессии 30).
 * То есть приём не новый — он просто доведён до конца.
 *
 * КРОМЕ СПИСКА СЛАЙДОВ: он не переехал, а УДАЛЁН (панель `slides` вместе
 * с `panels/SlidePanel.tsx`). Дубликат, а не панель: лента карточек
 * в дорожке (`track/SlideStrip.tsx`) показывает те же слайды по порядку
 * и теми же снимками, выбор — щелчком по карточке, а добавление
 * и удаление — пунктами меню правой кнопки на дорожке. Два органа
 * для одной работы — ровно тот «визуальный шум», который владелец назвал
 * задачей сессии; и дверь к этой панели вести было неоткуда.
 *
 * На РЕЙКЕ их нет, и это тоже с натуры: у Канвы рейка — источники
 * содержимого (шаблоны, элементы, текст, бренд, загрузки), а слои
 * открываются из полосы свойств, страницы — из нижней строки окна.
 * Владелец сказал о том же своими словами 20.08.2026: механика слайдов
 * и глав должна работать в дорожке и на ветках, а не отдельным списком.
 *
 * `mark` — панель выделенной метки дорожки. На рейке её НЕТ по той же
 * причине, что и `object`: без выделенной метки показывать нечего.
 * Она открывается сама, когда автор выбирает метку, и закрывается,
 * когда выбор снят.
 */

/**
 * Имена панелей БЕЗ пункта на рейке. Заголовок панели — единственное место,
 * где автор читает, что он открыл: у панелей с пунктом рейки имя подсвечено
 * на ней самой, у этих подсвечивать негде.
 *
 * `object` в перечень не входит намеренно: у него имя по умолчанию, и оно
 * же стоит на кнопке-двери в полосе свойств.
 */
export const PANEL_TITLES: Partial<Record<PanelId, string>> = {
  layers: 'Слои',
  chapters: 'Главы',
  mark: 'Метка',
};

