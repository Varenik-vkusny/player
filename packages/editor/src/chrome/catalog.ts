/**
 * Категории каталога хрома редактора — ДАННЫЕ, а не разметка.
 *
 * По образцу `state/library.ts`: рельс (`CatalogRail.tsx`) рисует кнопки
 * перебором этого массива, а не литералами в JSX. Так пополнение каталога
 * (шестая категория, другая подпись) требует правки только этого файла.
 */

/** Одна категория рельса: что показывает и как подписана кнопка. */
export interface CatalogCategory {
  readonly id: CategoryId;
  /** Русская подпись кнопки и головы панели. */
  readonly label: string;
  /** Один символ-значок кнопки — своей мелкой графики каталог не заводит, см. `PropBar.tsx`. */
  readonly glyph: string;
  /** Пояснение одной фразой, показывается в голове панели под заголовком. */
  readonly hint: string;
}

/** Категории рельса — порядок совпадает с порядком кнопок сверху вниз. */
export type CategoryId = 'templates' | 'shapes' | 'text' | 'theme' | 'styles' | 'own';

/**
 * Идентификатор ЛЮБОЙ панели каталога, включая `object`.
 *
 * `object` — панель свойств выделенного элемента. На рельсе её нет и не
 * может быть: она открывается кнопкой с полосы свойств, а не с рельса,
 * потому что без выделенного элемента показывать нечего. Отдельный тип
 * (шире `CategoryId`) существует, чтобы состояние «какая панель открыта»
 * могло принять это значение, а рельс — не мог его нарисовать.
 */
export type PanelId = CategoryId | 'object';

