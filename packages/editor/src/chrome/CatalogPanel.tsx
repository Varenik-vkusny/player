/**
 * Оболочка широкой панели каталога справа от рельса: строка поиска сверху
 * и тело с содержимым выбранной категории.
 *
 * **20.08.2026 голова панели переделана по натуре.** Было: заголовок
 * категории крупным кеглем плюс пояснение под ним. Замер живой Канвы
 * (окно 1879×968, панель «Шаблоны»):
 *
 *   панель            361×911
 *   шапка панели      360×86   — в ней ТОЛЬКО строка поиска
 *   строка поиска     328×58   @ поле 16 от края, отступ 16 сверху,
 *                              скругление 16, фон белый
 *   заголовка панели  НЕТ ВООБЩЕ
 *
 * Заголовок у них не нужен потому, что выбранный пункт рейки и так подсвечен
 * цветом — имя категории написано слева, в двух сантиметрах, и повторять его
 * значит занимать самое верхнее место панели тем, что автор уже знает.
 *
 * **Поиск НАСТОЯЩИЙ, а не для вида.** Он фильтрует плитки по подписи прямо
 * при наборе. Пустая строка поиска, поставленная ради сходства, была бы тем
 * же самым, что пункт рейки без содержимого, — обманом; отсюда же решение
 * не заводить категории «Проекты» и «Приложения», которых у нас нет.
 *
 * Кнопка сворачивания существует ТОЛЬКО пока панель отрисована: свёрнутый
 * каталог Editor.tsx не рендерит вовсе (ширина колонки уходит в 0 через
 * --ed-catalog-w). Дорога назад — рельс категорий слева, он не сворачивается
 * никогда. Поэтому aria-expanded здесь всегда true.
 */
import type { ReactElement, ReactNode } from 'react';

import { SearchField } from '../ui/index.js';

export interface CatalogPanelProps {
  /**
   * Имя категории. На экране больше НЕ печатается (см. шапку модуля), но
   * остаётся именем области для тех, кто её не видит: панель без имени
   * в дереве доступности — это «регион», и переходить по нему нечем.
   */
  title: string;
  /** Что сейчас набрано в поиске. */
  query: string;
  onQueryChange: (value: string) => void;
  children: ReactNode;
  /**
   * Печатать ли имя панели заголовком.
   *
   * У категорий рейки — НЕТ: имя подсвечено на рейке в двух сантиметрах
   * слева, и повторять его значит занимать верх панели известным.
   * Так у натуры.
   *
   * У панелей БЕЗ пункта на рейке — ДА, и это не исключение ради
   * исключения: «Объект» открывается кнопкой из полосы свойств, нигде
   * не подсвечен, и без заголовка автор попадает в безымянную панель
   * и не понимает, куда. Признак назван тем, что он значит, а не
   * категорией: правило «имя показывают там, где его больше негде
   * прочитать» переживёт появление седьмой категории.
   */
  showTitle?: boolean;
  /** Сворачивает панель каталога. */
  onCollapse: () => void;
}

export function CatalogPanel(
  { title, query, onQueryChange, children, showTitle = false, onCollapse }: CatalogPanelProps,
): ReactElement {
  return (
    <aside className="ed-catalog" data-testid="catalog" aria-label={title}>
      {showTitle ? <h2 className="ed-catalog-title">{title}</h2> : null}
      <div className="ed-catalog-head">
        <SearchField
          label={`Поиск в категории «${title}»`}
          placeholder={`Поиск: ${title.toLowerCase()}`}
          value={query}
          onChange={onQueryChange}
          testId="catalog-search"
        />
        <button
          type="button"
          className="ed-catalog-collapse"
          data-testid="collapse-catalog"
          aria-expanded="true"
          aria-label="Свернуть панель каталога"
          onClick={onCollapse}
        >
          <span aria-hidden="true">«</span>
        </button>
      </div>
      <div className="ed-catalog-body">{children}</div>
    </aside>
  );
}
