/**
 * Отбор полей стиля для полосы свойств над холстом (`stage/PropBar.tsx`,
 * Сессия 30). Чистая функция от типов выделенных элементов — вынесена из
 * компонента, чтобы состав полосы проверялся юнитом без подъёма React
 * (тот же довод ADR-010, что и у `panels/styleDraft.ts`).
 *
 * Один выделенный элемент — на полосу идут только ЧАСТЫЕ поля его типа.
 * Список снят с натуры каркаса, а не выдуман: `design/main.js`, константа
 * `BAR_FIELDS` (строки 107-111, комментарий рядом — «не пихать кучу кнопок
 * в одно место: на панели частое, редкое в панели «Объект»»):
 *
 *   текст:    font-family, font-size, font-weight, color, text-align
 *             (без line-height — оно применимо, но не частое);
 *   картинка: border-radius (без background — оно применимо ALL_TYPES,
 *             но у картинки заливка фона редкость, а не частый случай);
 *   фигура:   background, border-radius (оба её применимых поля разом —
 *             сужать у фигуры нечего, оба частые).
 *
 * `video` и `group` в каркасе не описаны вовсе — Canva-референс и владелец
 * их не разбирали, продуктового решения о «частом» для них не было.
 * Придумывать его здесь значило бы выдать догадку за решение, поэтому
 * для них отдаются ВСЕ применимые поля (см. `styleFieldsFor`) — как если бы
 * узкого списка не было вовсе.
 *
 * Несколько выделенных — правило ДРУГОЕ, и оно тоже снято прогоном того же
 * каркаса, а не выдумано: `design/main.js`, функция `buildBar`, `var many =
 * list.length > 1` (строка 468) и `fieldsFor` (строка 309-314). На полосу
 * идут ВСЕ поля, применимые сразу ко ВСЕМ выделенным типам (пересечение
 * по `appliesTo`), а НЕ только частые — иначе автор, выделив троих текстов,
 * не увидел бы «Межстрочный», хотя оно есть у каждого. Правило переключается
 * по ЧИСЛУ выделенных, а не по разнообразию типов: два элемента ОДНОГО типа
 * тоже получают полный список применимых полей, а не частый — так ветвится
 * сам каркас (`list.length > 1`, а не проверка «типы разные»).
 *
 * Пустой входной массив (`types.length === 0`, ничего не выделено) и
 * непустой массив, для которого отбор дал пустой результат («Общих свойств
 * нет» — оба типа применимы, но пересечение пусто, либо у типа нет частых
 * полей вовсе), — РАЗНЫЕ случаи для вызывающего кода: первый значит «полоса
 * вообще не показывает поля стиля», второй — «покажи явную надпись». Эта
 * функция сигналит оба одинаково пустым результатом; различать их обязан
 * вызывающий по длине входного `types`, а не эта функция по выдумыванию
 * третьего состояния.
 */
import type { Element } from '@player/core';

import { STYLE_FIELDS, styleFieldsFor, type StyleFieldDef, type StyleFieldKey } from './style.js';

/** Частые поля — см. комментарий модуля. Ключ отсутствует ⇒ узкого списка нет. */
const BAR_FIELD_KEYS: Partial<Record<Element['type'], readonly StyleFieldKey[]>> = {
  text: ['font-family', 'font-size', 'font-weight', 'color', 'text-align'],
  image: ['border-radius'],
  shape: ['background', 'border-radius'],
};

/** Поля стиля полосы для данного состава типов выделения. См. комментарий модуля. */
export function propbarStyleFields(types: readonly Element['type'][]): readonly StyleFieldDef[] {
  if (types.length === 0) return [];

  if (types.length === 1) {
    const type = types[0]!;
    const applicable = styleFieldsFor(type);
    const frequent = BAR_FIELD_KEYS[type];
    return frequent ? applicable.filter((field) => frequent.includes(field.key)) : applicable;
  }

  return STYLE_FIELDS.filter((field) => types.every((type) => field.appliesTo.includes(type)));
}
