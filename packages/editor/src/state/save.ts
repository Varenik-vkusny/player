import { loadProject, type Project } from '@player/core';

/**
 * Канал предпросмотра «редактор → плеер».
 *
 * Раньше был localStorage — см. историю файла. Спайк `spikes/s8-quota`
 * измерил на настоящем Chromium: квота на origin — ровно 5 МБ в символах
 * UTF-16 (10 485 760 байт, считая ключ и значение вместе), а `setItem` при
 * превышении бросает `QuotaExceededError` синхронно, ДО того, как успевает
 * открыться вкладка плеера. С вшитыми картинками проект уходит в мегабайты
 * за один data-URI — граница будет пройдена не в теории, а на первом же
 * реальном скриншоте.
 *
 * Опаснее самого исключения то, что происходит со старым значением: спайк
 * показал, что провалившийся `setItem` НЕ трогает то, что уже лежало
 * в сторадже. Значит если открыть вкладку плеера отдельно (например,
 * обновить уже открытую), она увидит не пустоту и не ошибку, а прошлый
 * успешно сохранённый проект — без единого признака, что только что была
 * попытка его перезаписать. Это и есть тихий отказ, которого CLAUDE.md
 * не допускает.
 *
 * IndexedDB не имеет квоты такого порядка — контрольная запись в том же
 * спайке прошла на 30 МБ за 59 мс — и остаётся синхронной по смыслу: запись
 * дожидается своего завершения (событие `complete` транзакции, не просто
 * успех одного `put`), и только потом открывается вкладка. Гонки между
 * «плеер уже загрузился и ищет данные» и «редактор ещё не дописал» здесь
 * нет по построению: к моменту `window.open` данные уже физически на диске.
 */
const PREVIEW_DB = 'player-preview';
const PREVIEW_DB_VERSION = 1;
const PREVIEW_STORE = 'projects';
/** Ключ записи с последним переданным на просмотр проектом. */
export const PREVIEW_KEY = 'current';

/**
 * Открывает (и при необходимости создаёт) базу канала предпросмотра.
 *
 * `indexedDB` может физически отсутствовать (например, в некоторых режимах
 * приватного просмотра) — тогда обращение к нему бросает синхронно, и это
 * тоже обязано долететь до вызывающего, а не превратиться в зависшее
 * обещание.
 */
function openPreviewDb(): Promise<IDBDatabase> {
  return new Promise((resolve, reject) => {
    if (typeof indexedDB === 'undefined') {
      reject(new Error('IndexedDB недоступен в этой вкладке'));
      return;
    }
    const request = indexedDB.open(PREVIEW_DB, PREVIEW_DB_VERSION);
    request.onupgradeneeded = () => {
      request.result.createObjectStore(PREVIEW_STORE);
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => {
      reject(request.error ?? new Error('indexedDB.open не сообщил причину отказа'));
    };
  });
}

/**
 * Кладёт текст проекта в IndexedDB и ждёт, пока транзакция действительно
 * завершится. Ждём именно `complete`, а не успех `put`: `put` сообщает, что
 * запрос принят, а не что он записан, — а плеер откроется уже после этого
 * вызова и обязан найти данные на месте.
 */
async function putPreview(text: string): Promise<void> {
  const db = await openPreviewDb();
  try {
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction(PREVIEW_STORE, 'readwrite');
      tx.objectStore(PREVIEW_STORE).put(text, PREVIEW_KEY);
      tx.oncomplete = () => resolve();
      tx.onerror = () => reject(tx.error ?? new Error('транзакция IndexedDB не сообщила причину'));
      tx.onabort = () => reject(tx.error ?? new Error('транзакция IndexedDB прервана'));
    });
  } finally {
    db.close();
  }
}

/**
 * Превращает проект в текст файла.
 *
 * Перед выдачей результат прогоняется через loadProject. Это не паранойя:
 * редактор правит проект десятками мелких действий, и единственный момент,
 * когда ошибку ещё можно связать с тем, что автор сделал, — прямо сейчас.
 * Найденная при следующем открытии, она будет выглядеть как испорченный файл
 * без причины.
 *
 * Отступ в два пробела: файл читают и сравнивают глазами, а однострочный
 * JSON в двадцать тысяч символов сравнить нельзя.
 */
export function serializeProject(project: Project): string {
  const text = JSON.stringify(project, null, 2);
  // Разбор обратно, а не проверка исходного объекта: сериализация умеет
  // терять — undefined, NaN, циклы. Проверять надо то, что действительно
  // окажется в файле.
  loadProject(JSON.parse(text));
  return text;
}

/**
 * Отдаёт проект файлом.
 *
 * Ссылка живёт ровно до клика: у объектных URL нет сборщика мусора,
 * и незакрытый URL держит копию файла в памяти вкладки до её закрытия.
 */
export function downloadProject(project: Project, fileName = 'project.json'): void {
  const text = serializeProject(project);
  const url = URL.createObjectURL(new Blob([text], { type: 'application/json' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  link.click();
  URL.revokeObjectURL(url);
}

/**
 * Читает проект из файла, который выбрал автор.
 *
 * Вторая половина `downloadProject`: унести работу было чем, вернуть — нечем.
 *
 * Обе возможные ошибки поднимаются наверх и обе разные по смыслу, поэтому
 * различаются текстом. Негодный JSON — это «файл не тот» (автор выбрал
 * картинку или обрезанную копию). Непрошедшая валидацию структура — это
 * «файл тот, но испорчен», и `ProjectLoadError` уже несёт список проблем
 * полем `issues`, который не нужно пересказывать.
 *
 * Тихо подставить пустой проект или фикстуру здесь нельзя: автор потерял бы
 * файл, ничего об этом не узнав, — он бы решил, что открылось, и продолжил
 * править не то.
 */
export async function openProjectFile(file: File): Promise<Project> {
  const text = await file.text();

  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (error) {
    throw new Error(`Файл ${file.name} не похож на проект: ${String(error)}`);
  }

  return loadProject(parsed);
}

/**
 * Кладёт проект туда, откуда его возьмёт плеер, и открывает предпросмотр.
 *
 * Через хранилище, а не через адресную строку: проект с настоящей озвучкой
 * и вшитыми картинками может весить мегабайты, и в URL он не помещается.
 * Бэкенда в этой сессии нет по условию задачи.
 *
 * IndexedDB, а не sessionStorage и не localStorage. У новой вкладки
 * собственное sessionStorage; оно копируется от открывающей страницы только
 * если окно открыто БЕЗ noopener, а полагаться на это значило бы обменять
 * работающий предпросмотр на связь между вкладками, которая нам не нужна.
 * localStorage отпал по итогам замера (`spikes/s8-quota`) — квота 5 МБ
 * символов слишком мала для проекта с картинками.
 *
 * Ошибка канала обязана быть видна автору немедленно и в этой же вкладке:
 * если здесь тихо проглотить исключение, откроется вкладка плеера, которая
 * попробует найти данные, не найдёт (или, хуже, найдёт старый проект от
 * прошлого успешного сохранения — см. комментарий у констант выше) и
 * покажет ошибку не там, где она на самом деле возникла. Поэтому при сбое —
 * `alert` с точным текстом прямо здесь, и throw вслед за ним, чтобы отказ
 * остался виден и в консоли, и тем, кто вызывает `openInPlayer` из теста.
 */
export async function openInPlayer(project: Project, url = '/?from=editor'): Promise<void> {
  const text = serializeProject(project);

  try {
    await putPreview(text);
  } catch (error) {
    const message = `Не удалось передать проект в плеер: ${String(error)}`;
    // window.alert, а не просто throw: клик по кнопке в Editor.tsx не ждёт
    // и не ловит эту функцию (`onClick={() => openInPlayer(...)}`), значит
    // непойманное исключение уйдёт только в консоль — автор его не увидит.
    // alert — единственный способ гарантированно показать текст в этой же
    // вкладке без изменений в компоненте.
    window.alert(message);
    throw new Error(message);
  }

  window.open(url, '_blank', 'noopener');
}
