/**
 * Время, написанное для глаз автора. Одинаковые случаи — одинаково.
 *
 * ЗАЧЕМ ЭТОТ МОДУЛЬ. Замерено 18.08.2026 на одном экране редактора:
 * одно и то же нулевое время было написано ТРЕМЯ способами сразу —
 * `00:00.0` на часах транспорта, `0.00 с` на чипе слайда и в счётчике
 * ленты, `0.000 с` в видимой строке причины под лентой. Автор не может
 * понять, одно это число или разные.
 *
 * ПРАВИЛО ЗДЕСЬ НЕ «ВЕЗДЕ ОДИНАКОВО», А «ОДИНАКОВЫЕ СЛУЧАИ ОДИНАКОВО».
 * Перепись всех тридцати шести мест форматирования показала, что часть
 * разнобоя осмысленна и сводить её было бы ошибкой:
 *
 *   - часы транспорта идут каждый кадр и читаются как часы, а не как
 *     число секунд: `MM:SS.S`. Записать их как `48.60 с` значило бы
 *     отнять у автора привычный вид положения в дорожке;
 *   - поля ввода в панели метки пишут число с ЗАПЯТОЙ (`1,45`) — это
 *     не подпись, а редактируемое значение, и запятая там по русской
 *     раскладке чисел. Свести его с подписью значило бы сломать ввод;
 *   - сообщения `throw new Error(...)` держат три знака намеренно: они
 *     адресованы тому, кто чинит код, и обязаны называть предмет точно.
 *
 * Остаётся один случай, и он-то и был написан двумя способами: МОМЕНТ
 * ИЛИ ДЛИТЕЛЬНОСТЬ В СЕКУНДАХ, ПОКАЗАННЫЕ АВТОРУ ПОДПИСЬЮ. Для него —
 * `secondsText`.
 *
 * ПОЧЕМУ ДВА ЗНАКА, А НЕ ТРИ И НЕ ОДИН — это выведено, а не выбрано
 * по вкусу. Две метки не могут стоять ближе, чем `MARK_HIT_SECONDS`
 * (`state/slides.ts`), а это ровно 0.01 с. Значит два знака после точки
 * различают любые две метки, какие модель вообще допускает, и ни один
 * лишний знак ничего не добавляет. Третий знак показывал бы автору
 * разряд, в котором у продукта не бывает различий.
 */

/**
 * Момент или длительность в секундах — подписью для автора: `1.45 с`.
 *
 * Единица написана словом при числе, а не подразумевается: подпись
 * `1.45` в интерфейсе, где рядом живут кадры, проценты и пиксели,
 * читается неоднозначно.
 */
export function secondsText(seconds: number): string {
  return `${seconds.toFixed(2)} с`;
}

/**
 * Положение в дорожке на часах транспорта и подписи линейки: `00:01.5`.
 *
 * Отрицательное и нечисловое приводится к нулю — часы обязаны показывать
 * время, а не `NaN:aN.a`. Это перенесено дословно из прежней `formatTime`
 * в `track/TrackView.tsx` вместе с причиной: значение приходит из
 * аудиоконтекста, и до первого кадра оно может быть каким угодно.
 */
export function clockText(seconds: number): string {
  const safe = Number.isFinite(seconds) && seconds > 0 ? seconds : 0;
  const minutes = Math.floor(safe / 60);
  const rest = safe - minutes * 60;
  return `${String(minutes).padStart(2, '0')}:${rest.toFixed(1).padStart(4, '0')}`;
}

/**
 * Как назвать остановку в тексте для автора.
 *
 * У гейта НЕТ поля имени — схема даёт только `id`, `at`, `config`,
 * `onWrong`, `maxAttempts`, `recordAs`. Но человеческий текст у него есть,
 * и его написал сам автор: у вопроса и у ввода это `prompt`, у «Дальше» —
 * надпись `label` на кнопке. Ключ схемы («gate-choice») автору не говорит
 * ничего, поэтому в подпись идёт вопрос.
 *
 * Длинный вопрос обрезается: подпись метки — строка подсказки, а не место
 * для абзаца. Обрезка ЯВНАЯ, с многоточием, чтобы автор видел, что текст
 * продолжается, а не думал, будто вопрос такой и есть.
 *
 * Пустой вопрос — законный случай (автор ещё не написал), и тогда остановка
 * называется своим временем: оно стоит на дорожке под самой меткой,
 * и по нему остановку видно.
 */
export function gateName(
  gate: { readonly config: { readonly kind: string; readonly prompt?: string; readonly label?: string } },
  seconds: number,
): string {
  const written = (gate.config.kind === 'continue' ? gate.config.label : gate.config.prompt) ?? '';
  const text = written.trim();
  if (text === '') return `на ${secondsText(seconds)}`;
  const LIMIT = 40;
  return text.length <= LIMIT ? `«${text}»` : `«${text.slice(0, LIMIT - 1).trimEnd()}…»`;
}
