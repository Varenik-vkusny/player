import type { JSX } from 'react';

/**
 * Значок выравнивания: собирается из прямоугольников в поле 16×16.
 *
 * Переехал сюда из stage/PropBar.tsx (Сессия 45, Задача 4) без единой
 * правки рисунка. Причина переезда — имя: там он назывался Icon, и в одном
 * пакете оказалось бы два разных компонента с этим именем, ровно тот
 * разнобой, ради конца которого библиотека и заводится.
 *
 * Почему он НЕ значок из Lucide и не станет им заодно: это не пиктограмма,
 * а схема. Полоса показывает, К ЧЕМУ равняем, а блоки — что равняется;
 * двенадцать таких схем читаются как семья только потому, что построены
 * по одной сетке из одних прямоугольников. Заменить их набором общих
 * значков — решение про облик, а не переименование, и принимается оно
 * отдельно.
 *
 * Своя мелкая графика, а не шрифт значков: шрифт — это внешний файл,
 * а плеер собирается без внешних загрузок (инвариант №9), и заводить
 * его ради двенадцати кнопок редактора значило бы держать два разных
 * правила для одного проекта.
 */
export type Shape = readonly [x: number, y: number, width: number, height: number];

export function AlignIcon({ shapes }: { shapes: readonly Shape[] }): JSX.Element {
  return (
    <svg viewBox="0 0 16 16" aria-hidden="true" focusable="false">
      {shapes.map(([x, y, width, height], index) => (
        <rect key={index} x={x} y={y} width={width} height={height} />
      ))}
    </svg>
  );
}
