import type { ButtonHTMLAttributes, JSX, ReactNode } from 'react';

/**
 * Вид кнопки. Перечень ЗАКРЫТЫЙ, а не строка класса: строка позволила бы
 * завести пятый вид молча, и разнобой вернулся бы тем же путём, каким
 * пришёл — 42 кнопки написаны одним классом при живом запрете плодить своё.
 *
 * Сегодня вид ровно один, и это не заготовка под будущее, а перепись:
 * у всех 42 обычных кнопок редактора СЕГОДНЯ одно оформление (.ed-action),
 * то есть «главной», «тихой» и «значка» в продукте не существует. Завести
 * их — решить, какая кнопка на экране главная, а это вопрос облика, и
 * решается он отдельно, а не выводится из перечня.
 */
export type ButtonKind = 'обычная';

/** Вид → класс-модификатор. У единственного вида модификатора нет. */
const KIND_CLASS: Record<ButtonKind, string> = { обычная: '' };

interface ButtonOwnProps {
  kind?: ButtonKind;
  /**
   * Почему кнопка погашена. Показывается подсказкой при наведении и только
   * когда кнопка действительно погашена.
   *
   * НЕ обязательна, и это осознанно. Замерено 17.08.2026: из 21 погашаемой
   * кнопки причину несут 6. Дописать недостающие 15 — значит сочинить
   * пользовательский текст, а он не выводится из кода. Важнее другое:
   * у нижней зоны причины уже выводятся ВИДИМОЙ строкой через точку-разделитель
   * (SlideStrip: «Первый слайд вырезать нельзя · Буфер пуст»), и это механизм
   * лучше подсказки — на подсказки при наведении не смотрят. Требовать reason
   * типом значило бы толкать причины обратно в title, то есть чинить наоборот.
   */
  reason?: string;
  children: ReactNode;
}

type ButtonProps = ButtonOwnProps & ButtonHTMLAttributes<HTMLButtonElement>;

/**
 * Единственная обычная кнопка редактора.
 *
 * type="button" по умолчанию: кнопка внутри формы иначе отправляет её.
 * Перекрыть можно, передав type явно — спред стоит после.
 */
export function Button({ kind = 'обычная', reason, children, ...rest }: ButtonProps): JSX.Element {
  const { className, title, disabled, ...others } = rest;
  const modifier = KIND_CLASS[kind];
  return (
    <button
      type="button"
      // className вызывающего ДОПИСЫВАЕТСЯ, а не заменяет: он нужен там, где
      // кнопка встаёт в чужую раскладку (flex-доля, ширина колонки). Оформление
      // при этом остаётся за .ed-btn — подменить его строкой нельзя.
      className={['ed-btn', modifier, className].filter(Boolean).join(' ')}
      disabled={disabled}
      title={disabled === true ? (reason ?? title) : title}
      {...others}
    >
      {children}
    </button>
  );
}
