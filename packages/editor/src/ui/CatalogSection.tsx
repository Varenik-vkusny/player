/**
 * Заголовок раздела внутри панели каталога: имя слева, счёт справа.
 *
 * Замер живой Канвы 20.08.2026: «Недавно использованные» 14px/700 слева
 * по левому полю содержимого, «Просмотреть все» 12px/600 справа, тем же
 * почти чёрным цветом. Второй раздел ниже — «Больше шаблонов для вас».
 *
 * Справа у нас СЧЁТ, а не ссылка «Просмотреть все». Ссылке некуда вести:
 * весь набор уже на экране, а кнопка, которая ничего не делает, — обман
 * той же породы, что пункт рейки без содержимого.
 *
 * Живёт в библиотеке, потому что разделов теперь три панели: шаблоны,
 * заготовки и стили текста. Копия в каждой разъехалась бы молча — это
 * в проекте уже случалось со шкалой кеглей.
 */
import type { JSX } from 'react';

export interface CatalogSectionProps {
  title: string;
  /** Сколько заготовок в разделе. Показывается справа от имени. */
  count: number;
}

export function CatalogSection({ title, count }: CatalogSectionProps): JSX.Element {
  return (
    <div className="ed-catalog-section">
      <h3 className="ed-catalog-section-title">{title}</h3>
      <span className="ed-catalog-section-note">{count}</span>
    </div>
  );
}
