import { useState, type JSX, type ReactNode } from 'react';

import { Icon } from './Icon.js';

/**
 * Складывающийся заголовок панели боковой колонки.
 *
 * Складной становится САМА панель, а не обёртка вокруг неё. Причина
 * измерима: семь панелей редактора уже рисуют свой h2.ed-insp-title
 * со своим названием, и обёртка снаружи дала бы по ДВА заголовка на
 * панель, а текст пришлось бы держать в двух местах сразу — тот самый
 * разнобой, ради конца которого заводится библиотека.
 *
 * Поэтому Section возвращает ФРАГМЕНТ, а не свой контейнер: он встаёт
 * ровно на место прежнего h2 внутри панели, и раскладка панели
 * (её собственные display: flex, gap и потолки списков) остаётся
 * нетронутой. Свой контейнер сдвинул бы всех детей на уровень ниже
 * и отобрал бы у панели её же gap — правка облика мимоходом.
 *
 * Заголовок остаётся заголовком: кнопка лежит ВНУТРИ h2, а не вместо
 * него. Иначе тот, кто не видит экрана, теряет оглавление колонки —
 * панели перестают быть местами, к которым можно перейти.
 *
 * Сложенная секция обязана не занимать высоту ВООБЩЕ, а не прятать
 * содержимое прокруткой: замерено 17.08.2026, что несжимаемым секциям
 * правой колонки нужно 890 px, а на ноутбуке колонка даёт 368. Пока
 * содержимое лежит в DOM, оно эти 890 и занимает, где бы ни стояла
 * прокрутка. Поэтому дети именно СНИМАЮТСЯ, а не гасятся display: none:
 * тогда высота уходит вместе с ними, и это видно в scrollHeight колонки.
 *
 * Состояние держится здесь, а не в редакторе: свёрнутость — свойство
 * показа, а не проекта, и в файл она не уезжает.
 */
export function Section({
  title,
  defaultOpen = true,
  children,
}: {
  title: string;
  defaultOpen?: boolean;
  children: ReactNode;
}): JSX.Element {
  const [open, setOpen] = useState(defaultOpen);
  return (
    <>
      <h2 className="ed-insp-title">
        {/* Имя кнопки задаётся явно, а не берётся из подписи: подпись набрана
            прописными средствами CSS (text-transform у .ed-insp-title), и на
            слух осталась бы просто названием панели — «Главы», — без глагола,
            то есть без обещания, что нажатие вообще что-то сделает. */}
        <button
          type="button"
          className="ed-section-toggle"
          aria-expanded={open}
          aria-label={`${open ? 'Свернуть' : 'Развернуть'} «${title}»`}
          onClick={() => setOpen((was) => !was)}
        >
          <Icon name={open ? 'chevron-down' : 'chevron-right'} />
          <span className="ed-section-name">{title}</span>
        </button>
      </h2>
      {open ? children : null}
    </>
  );
}
