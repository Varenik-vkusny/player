/**
 * Пики звуковой волны для waveform в редакторе: один проход по отсчётам, на
 * каждый бакет — минимум и максимум.
 *
 * **Почему свой код, а не библиотека.** Решено и обосновано в
 * `docs/research/audio.md`, §5 (проверено 2026-07-27):
 *
 * - **wavesurfer.js не берём.** Лицензия и живость в порядке (BSD-3-Clause,
 *   7.12.11, ноль рантайм-зависимостей), проблема не в качестве: «wavesurfer —
 *   это плеер. Он несёт собственный транспорт, собственное управление
 *   воспроизведением и собственную отрисовку. Взять его в редактор — значит
 *   завести вторую реализацию воспроизведения рядом с нашим плеером» — то есть
 *   прямо против инвариантов №5 и №6.
 * - **peaks.js не берём.** LGPL-3.0 в бандлируемом ESM (границы копилефта при
 *   бандлинге неочевидны, а инвариант №9 требует самостоятельный ESM-файл) плюс
 *   штатный путь через бэкенд `bbc/audiowaveform`.
 * - Своё — это ровно «один проход по `Float32Array`: на каждый пиксель ширины
 *   берём min/max в бакете». Ноль зависимостей, ноль ADR и автоматическая
 *   согласованность с плеером: рисуем тот же буфер, который звучит.
 *
 * `OfflineAudioContext` здесь не нужен вовсе — тот же §5: он полезен, только
 * если сначала понижать частоту дискретизации. Мы её не понижаем, значит и
 * повода нет.
 *
 * **Почему проход обязан быть один.** Дорожка озвучки — 10 минут моно 48 кГц,
 * это 28.8 млн отсчётов и ~110 МБ в памяти (§4 того же документа). Любой
 * `slice`/`subarray` внутри цикла или промежуточный массив на бакет — это
 * вторая копия тех же мегабайт и второй обход памяти. Поэтому ниже нет ни
 * одной аллокации в цикле по отсчётам и ни одного повторного чтения отсчёта:
 * внутренние циклы всех бакетов вместе дают ровно `samples.length` итераций.
 *
 * Модуль чистый: ни DOM, ни канвы, ни Web Audio. На вход идёт то, что вернул
 * `AudioBuffer.getChannelData(0)` — один канал, потому что дорожка озвучки
 * моно (следствие §4, не «пока что»). Проверяется в node без jsdom.
 */

/** Огибающая одного бакета: самый низкий и самый высокий отсчёт внутри него. */
export interface Peak {
  readonly min: number;
  readonly max: number;
}

/**
 * Огибающая: на каждый бакет минимум и максимум отсчётов.
 *
 * `buckets` — сколько колонок нарисует вызывающий, обычно ширина канвы в
 * пикселях. Длина результата всегда равна `buckets`, даже когда отсчётов
 * меньше: вызывающий рисует фиксированное число колонок, и молча вернуть
 * массив другой длины значило бы переложить на него разбор нашего решения.
 *
 * **Границы бакетов.** Отсчёты режутся встык: конец бакета — начало
 * следующего. Ни один отсчёт не теряется и ни один не учитывается дважды даже
 * при длине, не кратной числу бакетов; остаток раздаётся по одному отсчёту и
 * размазан по всей ширине, а не свален в начало.
 *
 * **Бакетов больше, чем отсчётов.** Часть бакетов остаётся пустой и получает
 * `{ min: 0, max: 0 }` — ровную линию по центру. Выбрано вместо усечения
 * результата до длины массива по двум причинам: длина результата остаётся
 * контрактом («сколько просили колонок, столько и вернули»), а пустая колонка
 * честно говорит «здесь нет отсчёта» вместо того, чтобы придумывать
 * промежуточное значение интерполяцией. Для реального редактора случай
 * вырожденный: 1200 колонок против 28.8 млн отсчётов.
 */
export function computePeaks(samples: Float32Array, buckets: number): Peak[] {
  if (!Number.isInteger(buckets) || buckets <= 0) {
    throw new RangeError(`Число бакетов должно быть целым положительным, получено ${buckets}`);
  }
  const total = samples.length;
  if (total === 0) {
    // Пустая дорожка — это не «пики нулевой ширины», это несостоявшаяся
    // загрузка звука. Вернуть плоскую линию значило бы нарисовать тишину
    // там, где на самом деле ничего не декодировалось.
    throw new RangeError('Пустая дорожка: считать пики не из чего');
  }

  // Длина бакета целая, остаток раздаётся по одному отсчёту. Сумма длин равна
  // `total` по построению: base * buckets + remainder === total. Это не
  // зависит от вещественной арифметики вовсе.
  //
  // Привычная формула floor((i + 1) * total / buckets) даёт то же разбиение,
  // но её произведение при больших `buckets` вылезает за предел точного целого
  // в double, и границы начинают врать молча — как раз тот случай, когда
  // «правдоподобные числа с видом настоящих».
  const base = Math.floor(total / buckets);
  const remainder = total % buckets;

  const peaks: Peak[] = new Array<Peak>(buckets);
  let start = 0;
  // Ошибка Брезенхэма: накапливаем остаток и отдаём лишний отсчёт, как только
  // накопилось на целый. Так лишние отсчёты распределены равномерно по ширине.
  let carry = 0;

  for (let bucket = 0; bucket < buckets; bucket += 1) {
    let length = base;
    carry += remainder;
    if (carry >= buckets) {
      carry -= buckets;
      length += 1;
    }
    const end = start + length;

    // Начальные значения берём из первого отсчёта бакета, а не из ±Infinity:
    // иначе пустой бакет вернул бы бесконечности наружу, а тишина оказалась бы
    // корректной лишь по случайности.
    let min = 0;
    let max = 0;
    if (end > start) {
      const first = samples[start]!;
      min = first;
      max = first;
      for (let i = start + 1; i < end; i += 1) {
        const value = samples[i]!;
        // `else if` здесь не экономия, а факт: min <= max, поэтому отсчёт не
        // может быть одновременно ниже минимума и выше максимума.
        if (value < min) min = value;
        else if (value > max) max = value;
      }
    }

    peaks[bucket] = { min, max };
    start = end;
  }

  return peaks;
}

/** Вертикальный столбик пика в пикселях: `top` от верха полосы, высота вниз. */
export interface Bar {
  readonly top: number;
  readonly height: number;
}

/**
 * Пик → геометрия столбика на полосе высотой `height`.
 *
 * Отдельная функция, а не арифметика на месте отрисовки, по той же причине,
 * по которой существует `stage/geometry.ts`: соглашение о переводе амплитуды
 * в пиксели должно жить в одном месте. Здесь оно такое: +1 — верх полосы,
 * −1 — низ, 0 — середина, ось Y растёт вниз, как в канве и в CSS.
 *
 * Амплитуда зажимается в ±1. Значения за этими пределами законны — float-PCM
 * их допускает, и декодер отдаёт перегрузку на клиппированном материале, — но
 * нарисовать их негде: без зажима столбик уедет за полосу и перекроет соседей.
 * Это ограничение картинки, а не подмена данных: сам `Peak` не меняется.
 */
export function peakToBar(peak: Peak, height: number): Bar {
  if (!Number.isFinite(height) || height <= 0) {
    throw new RangeError(`Высота полосы должна быть конечным положительным числом, получено ${height}`);
  }
  if (!Number.isFinite(peak.min) || !Number.isFinite(peak.max)) {
    throw new RangeError(`Пик должен состоять из конечных чисел, получено ${peak.min}..${peak.max}`);
  }
  if (peak.min > peak.max) {
    // Такой пик не мог получиться из `computePeaks`, значит его собрали руками
    // и перепутали поля. Отрицательная высота столбика ушла бы в канву молча.
    throw new RangeError(`Минимум пика больше максимума: ${peak.min} > ${peak.max}`);
  }
  const top = ((1 - clampAmplitude(peak.max)) / 2) * height;
  const bottom = ((1 - clampAmplitude(peak.min)) / 2) * height;
  return { top, height: bottom - top };
}

function clampAmplitude(value: number): number {
  if (value > 1) return 1;
  if (value < -1) return -1;
  return value;
}
