/**
 * Разведение близких меток по рядам внутри полосы.
 *
 * ЗАЧЕМ. Метки стоят там, где стоят их секунды, и при близких слайдах
 * налезают друг на друга. Замер 22.08.2026, фикстура demo, метка 18 px:
 *
 *   окно 1920 — 7 перекрывающихся пар, недостижима 1 метка из 16
 *   окно 1440 — 8 пар, недостижимо 5
 *   окно 1280 — 8 пар, недостижимо 7
 *
 * «Недостижима» здесь измерено, а не предположено: `elementFromPoint`
 * в центре метки отдаёт СОСЕДНЮЮ. То есть на ноутбучном экране почти
 * половину слайдов нельзя выбрать нажатием — ни автору, ни тесту.
 *
 * Порядок наложения (ранняя выше поздней) это лечил лишь наполовину:
 * при перекрытии меньше половины ширины центры обеих свободны, а больше —
 * недоступной становится просто другая метка.
 *
 * ЧТО ДЕЛАЕТ ЭТА ФУНКЦИЯ. Раскладывает метки по рядам так, чтобы соседи
 * по горизонтали попадали в РАЗНЫЕ ряды. Сдвиг по вертикали разводит их
 * центры, и обе становятся достижимы, даже когда прямоугольники всё ещё
 * пересекаются.
 *
 * Ряд — не «этаж» с отдельной высотой: полоса остаётся прежней, метки
 * внутри неё смещаются на несколько пикселей вверх и вниз. Высота зоны
 * от этого не меняется ни на пиксель, и жестовые e2e чужих файлов,
 * зависящие от масштаба сцены, остаются нетронутыми.
 */

/** Метка для раскладки: чем её звать и где её центр по горизонтали. */
export interface RowInput {
  readonly key: string;
  /** Центр метки в пикселях полотна. */
  readonly x: number;
}

/**
 * Раскладывает метки по рядам жадно, слева направо.
 *
 * Жадность здесь не упрощение, а верный ответ: метки уже отсортированы
 * по времени, и ряд, освободившийся раньше всех, — единственный разумный
 * выбор. Перебор не дал бы ничего, кроме иллюзии основательности.
 *
 * `maxRows` ограничивает раскладку высотой полосы. Если свободного ряда
 * нет вовсе — метка идёт в тот, где последний сосед кончается РАНЬШЕ
 * других: полностью развести три метки, стоящие в одной точке, нельзя
 * никаким числом рядов, и честнее оставить наименьшее перекрытие,
 * чем притвориться, что задача решена.
 */
export function assignMarkRows(
  marks: readonly RowInput[],
  markWidth: number,
  maxRows: number,
): ReadonlyMap<string, number> {
  if (maxRows < 1) throw new Error(`Рядов не может быть меньше одного, дано ${maxRows}`);

  const rows = new Map<string, number>();
  // Правый край последней метки в каждом ряду. -Infinity — ряд пуст.
  const lastRight: number[] = Array.from({ length: maxRows }, () => -Infinity);

  const ordered = [...marks].sort((a, b) => a.x - b.x);
  const half = markWidth / 2;

  for (const mark of ordered) {
    const left = mark.x - half;

    let chosen = 0;
    let free = false;
    for (let row = 0; row < maxRows; row += 1) {
      if (lastRight[row]! <= left) {
        chosen = row;
        free = true;
        break;
      }
    }

    if (!free) {
      // Свободных нет: берём ряд с наименьшим перекрытием.
      chosen = 0;
      for (let row = 1; row < maxRows; row += 1) {
        if (lastRight[row]! < lastRight[chosen]!) chosen = row;
      }
    }

    rows.set(mark.key, chosen);
    lastRight[chosen] = mark.x + half;
  }

  return rows;
}
