/**
 * Раскладка плиток глав в виде «Ветки» — чистая, без DOM.
 *
 * `branches.md` §5.2: «Ширина плитки равна длительности главы, поэтому
 * пропорции читаются без цифр». Это и есть смысл вида: автор видит,
 * что «Производная» вчетверо длиннее «Итога», не читая ни одной цифры.
 *
 * Живёт отдельным модулем, а не внутри вида, по той же причине, что
 * и `tiers.ts`: правило раскладки проверяется юнит-тестом без браузера,
 * а разметка остаётся разметкой.
 */

/**
 * Наименьшая ширина плитки. Не косметика, а достижимость.
 *
 * Пустая глава имеет длительность 0, и пустые главы рождаются САМИМ
 * разрезом по развилке (`split.ts`: ветки создаются пустыми по построению,
 * `product.md` §2б). Чистая пропорция дала бы им ширину 0 px — плитку,
 * которую не видно и по которой нельзя щёлкнуть, то есть главу, в которую
 * автор не может войти, чтобы её наполнить. Молча.
 *
 * 24 px — минимальная мишень, по которой уверенно попадают указателем.
 */
export const MIN_TILE_PX = 24;

/** То немногое, что раскладке нужно знать о главе. */
export interface TileSource {
  readonly seconds: number;
}

/**
 * Ширины плиток в пикселях при доступной полосе `totalPx`.
 *
 * Сумма может ПРЕВЫСИТЬ `totalPx`, и это законно: `branches.md` §12 прямо
 * запрещает «заставлять ветку помещаться» в какой-либо отрезок. Лишнее
 * уезжает в горизонтальную прокрутку, а пропорции остаются честными —
 * ужимание длинной ветки под ширину экрана как раз и соврало бы о них.
 *
 * Отрицательная длительность в валидном проекте невозможна, но приходит
 * сюда как число: считаем её нулём, а не бросаем — раскладка отвечает
 * на вопрос «какой ширины», а не «валиден ли проект».
 */
export function tileWidths(tiles: readonly TileSource[], totalPx: number): readonly number[] {
  if (tiles.length === 0) return [];

  const seconds = tiles.map((tile) => Math.max(0, tile.seconds));
  const total = seconds.reduce((sum, value) => sum + value, 0);

  // Все главы пустые — пропорции не существует, и выдумывать её нельзя.
  // Ровные плитки здесь единственный честный ответ.
  if (total <= 0) {
    return tiles.map(() => Math.max(MIN_TILE_PX, totalPx / tiles.length));
  }

  return seconds.map((value) => Math.max(MIN_TILE_PX, (value / total) * totalPx));
}
