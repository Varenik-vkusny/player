/**
 * Звуковая волна дорожки.
 *
 * Компонент чисто презентационный, и это требование к устройству, а не вкус:
 * вид редактора перепишут целиком в отдельной сессии, и всё, что умеет
 * продукт, обязано пережить эту переписку. Та же причина, по которой
 * `transport.ts` написан без React. Отсюда границы: ни загрузки, ни
 * декодирования, ни Web Audio, ни состояния кроме ссылки на канву. На вход —
 * готовые данные пропсами, наружу — ничего, кроме картинки.
 *
 * Арифметики амплитуд здесь тоже нет: перевод пика в столбик живёт в
 * `peaks.ts` и вызывается через `peakToBar`. Соглашение «+1 — верх полосы,
 * −1 — низ» обязано лежать в одном месте, иначе редактор и его будущая
 * замена начнут рисовать один и тот же звук по-разному.
 *
 * Канва, а не DOM-узлы: колонок обычно столько же, сколько пикселей ширины,
 * и тысяча с лишним `div` рядом с уже живущей сценой — это тысяча с лишним
 * узлов на каждый кадр воспроизведения.
 */
import { useLayoutEffect, useRef, type ReactElement } from 'react';

import { peakToBar, type Peak } from './peaks.js';

/** Ещё не проигранная волна. Приглушённый цвет редактора. */
const WAVE_COLOR = '#7d8fa5';
/** Проигранная часть. Тот же акцент, что у рамки выделения и ручек. */
const PLAYED_COLOR = '#4c8dff';

export interface WaveformProps {
  /**
   * Готовая огибающая. Длина массива задаёт число колонок.
   *
   * Перерисовка привязана к ссылке на массив: пики считаются один раз на
   * дорожку, и пересобирать их на каждое движение головки незачем.
   */
  peaks: readonly Peak[];
  /** Размер области в CSS-пикселях. */
  width: number;
  height: number;
  /**
   * Цвет волны и цвет уже проигранной части.
   *
   * При `exactOptionalPropertyTypes` необязательный проп значит «либо не
   * передавай вовсе, либо передавай строку»: явный `undefined` не пройдёт
   * по типам. Это не придирка компилятора, а ровно то, что нужно, —
   * `color={theme.wave}` с неизвестно чем внутри должен падать на месте
   * вызова, а не тихо превращаться в цвет по умолчанию.
   */
  color?: string;
  playedColor?: string;
  /** Доля дорожки, которая уже проиграна, 0..1. Ею закрашивается левая часть. */
  progress?: number;
}

export function Waveform({
  peaks,
  width,
  height,
  color = WAVE_COLOR,
  playedColor = PLAYED_COLOR,
  progress = 0,
}: WaveformProps): ReactElement {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  // useLayoutEffect, а не useEffect: перерисовка обязана попасть в тот же
  // кадр, что и новый размер канвы. Иначе кадр между раскладкой и отрисовкой
  // показывает волну прежней ширины — видимое мигание.
  useLayoutEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) throw new Error('Waveform: канва не смонтирована');

    // Нулевой или отрицательный размер — контейнер ещё не разложен. Это
    // штатное состояние первого кадра, а не ошибка: рисовать нечего и не на
    // чем. Условие через `!(width > 0)`, потому что так же отсеивается NaN.
    if (!(width > 0) || !(height > 0)) return;

    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('Waveform: браузер не дал 2d-контекст канвы');

    if (!Number.isFinite(progress)) {
      // Иначе NaN уехал бы в ширину обрезки, канва молча проигнорировала бы
      // прямоугольник, и «проигранное не закрашивается» пришлось бы искать
      // глазами вместо стектрейса.
      throw new RangeError(`Доля проигранного должна быть конечным числом, получено ${progress}`);
    }

    // Битмап крупнее CSS-размера ровно во столько раз, сколько физических
    // пикселей приходится на CSS-пиксель. Без этого волна мыльная на любом
    // хорошем экране.
    // Нижняя граница в один физический пиксель — не подстраховка «на всякий
    // случай», а то, что не даёт нулю попасть в делитель: полоса высотой
    // в полпикселя округлилась бы в битмап нулевой высоты, и минимальная
    // высота столбика ниже стала бы Infinity. Канва проглотила бы такой путь
    // молча.
    const dpr = window.devicePixelRatio;
    const pixelWidth = Math.max(1, Math.round(width * dpr));
    const pixelHeight = Math.max(1, Math.round(height * dpr));
    // Присваивание width/height сбрасывает битмап целиком, поэтому пишем их
    // только при реальной смене размера: `progress` меняется каждый кадр
    // воспроизведения, и переаллокация битмапа шла бы шестьдесят раз
    // в секунду ради тех же самых чисел.
    if (canvas.width !== pixelWidth) canvas.width = pixelWidth;
    if (canvas.height !== pixelHeight) canvas.height = pixelHeight;

    // setTransform, а не scale: scale домножается на текущую матрицу, и на
    // второй перерисовке масштаб стал бы dpr², на третьей dpr³ — тихо
    // и правдоподобно. Коэффициент берётся из округлённого битмапа, а не из
    // dpr напрямую: при дробном dpr (1.25, 2.625) это разные числа, и волна
    // не доезжала бы до правого края на долю пикселя.
    ctx.setTransform(pixelWidth / width, 0, 0, pixelHeight / height, 0, 0);
    // Дальше все координаты — CSS-пиксели.
    ctx.clearRect(0, 0, width, height);

    // Столбик тоньше физического пикселя не виден вовсе. Без нижней границы
    // тишина рисовалась бы разрывом, хотя computePeaks на пустом бакете
    // обещает ровно обратное — ровную линию по центру.
    const minBarHeight = height / pixelHeight;

    // Путь собирается целиком и заливается одним вызовом: колонок порядка
    // тысячи, и тысяча fillRect на кадр — это тысяча отдельных заливок.
    const wave = new Path2D();
    if (peaks.length === 0) {
      // Пиков нет — ровная линия по центру. Не «ничего»: пустая полоса
      // неотличима от неразложенного контейнера, а мусор от прошлого кадра
      // уже стёрт clearRect.
      wave.rect(0, (height - minBarHeight) / 2, width, minBarHeight);
    } else {
      const columnWidth = width / peaks.length;
      // Индексный цикл, а не entries(): перерисовка идёт каждый кадр
      // воспроизведения, а entries() отдаёт по паре-массиву на колонку.
      for (let index = 0; index < peaks.length; index += 1) {
        const bar = peakToBar(peaks[index]!, height);
        const barHeight = Math.max(bar.height, minBarHeight);
        // Тонкий столбик растягивается симметрично от своей середины, иначе
        // тишина съезжала бы вниз относительно центра полосы.
        const top = bar.top - (barHeight - bar.height) / 2;
        wave.rect(index * columnWidth, top, columnWidth, barHeight);
      }
    }

    ctx.fillStyle = color;
    ctx.fill(wave);

    // Проигранное — та же волна, обрезанная по головке. Обрезка, а не выбор
    // цвета по колонке: граница проходит там, где она есть на самом деле,
    // а не по ближайшему краю столбика.
    //
    // Доля зажимается в 0..1. Перелёт на дробную ошибку в конце дорожки —
    // штатное дело, а не повод падать; конечность значения уже проверена.
    const playedWidth = Math.max(0, Math.min(progress, 1)) * width;
    if (playedWidth > 0) {
      ctx.save();
      ctx.beginPath();
      ctx.rect(0, 0, playedWidth, height);
      ctx.clip();
      ctx.fillStyle = playedColor;
      ctx.fill(wave);
      ctx.restore();
    }
  }, [peaks, width, height, color, playedColor, progress]);

  // CSS-размер задаётся стилем, размер битмапа — эффектом. Разные величины,
  // и смешивать их нельзя: атрибуты width/height React не трогает, потому
  // что мы их сюда не передаём, и единственный их хозяин — эффект выше.
  return (
    <canvas
      className="ed-waveform"
      ref={canvasRef}
      style={{ width: `${width}px`, height: `${height}px` }}
    />
  );
}
