/**
 * Одна таблица подписей приёма перехода — единственный источник слов,
 * которые видит автор.
 *
 * До этой сессии слово приёма подставлялось тернарником в ДВУХ местах
 * (`panels/SlidePanel.tsx`, `Editor.tsx`), оставшимся от версии схемы,
 * где приёмов было два (`morph`/`cut`). Схема v9 несёт восемь
 * (`packages/core/src/schema.ts`, `TRANSITIONS`), и тернарник по union
 * типизируется без единой ошибки компилятора — оба места молча подписывали
 * `dissolve`/`slide`/`scale`/`blur`/`wipe`/`circle` словом «разрез», хотя
 * на сцене идёт движение. Таблица делает такое расхождение невозможным:
 * добавить девятый приём в схему — значит получить ошибку типов здесь же,
 * а не найти дефект подписи в другом файле сессией позже.
 *
 * `label` — короткое имя для плитки каталога (`panels/MarkPanel.tsx`,
 * `SlideMarkPanel`) и для строки в списке слайдов (`panels/SlidePanel.tsx`).
 * `hint` — одна фраза, что приём делает, для `title`/`aria-label` плитки.
 *
 * Слова автора, а не схемы (`MarkPanel.tsx`, комментарий у `SlideMarkPanel`):
 * `morph`/`cut`/`dissolve` и остальные ключи перечисления в интерфейс
 * не текут — там только то, что здесь записано. Имена и порядок каталога —
 * из `docs/design/screens.md` §4.2, «Срез» первым: «нет перехода» — запись
 * каталога, а не пустой выбор, тот же закон, что «нет цвета» ≠ «белый цвет».
 *
 * Порядок объекта — порядок каталога. `Object.entries`/`Object.keys`
 * на объекте со строковыми ключами (а не числовыми) отдают их в порядке
 * объявления (ECMA-262 [[OwnPropertyKeys]]) — это тот же порядок,
 * что и в §4.2, и он НЕ совпадает с порядком `TRANSITIONS` в схеме
 * (там `blur` перед `wipe`/`circle`; здесь — после).
 *
 * Ключ типа — `Slide['transition']`, а не переписанный руками список строк:
 * отдельного экспортированного имени `Transition` в ядре нет, но тип поля
 * выводится из схемы через `z.infer` (`SlideSchema.transition`), и запись
 * `Record<Slide['transition'], …>` даёт ту же защиту — TypeScript откажется
 * собирать этот файл, если каталог схемы и эта таблица разойдутся числом
 * значений в любую сторону.
 */
