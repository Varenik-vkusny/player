/**
 * Масштаб холста редактора — чистые функции, без DOM и без React.
 *
 * До Сессии 32 сцена всегда была вписана в контейнер целиком, и приблизиться
 * было нельзя: в окне 1920×1080 масштаб выходил 0.378, то есть буква кеглем
 * 24 рисовалась девятью пикселями. Мелкое поправить нельзя не потому, что
 * инструмент не даёт, а потому, что не видно, куда целиться.
 *
 * **Лестница снята с живой Canva 11.08.2026**, а не выдумана и не скопирована
 * с масштаба дорожки (`track/zoom.ts`, где ступени `×1 ×2 ×4 ×8 ×16` —
 * множители, потому что дорожка растягивается относительно своей ширины).
 * У холста иначе: там восемь АБСОЛЮТНЫХ процентов и отдельным пунктом
 * «Подогнать». Процент абсолютный проверен замером: при вписывании Canva
 * показывает 60 %, и это 1149 CSS-px на сцену шириной 1920.
 *
 * Вписывание — не ступень лестницы, а отдельное состояние (`'fit'`), и это
 * важно: растянутое окно обязано двигать вписывание и не имеет права трогать
 * число, которое автор выбрал руками.
 *
 * Само число живёт в состоянии `StageView` и имеет РОВНО ОДНОГО потребителя —
 * функцию, которая переводит его в CSS-трансформацию. Ни один жест мыши его
 * не читает: `scenePointOf`, `syncFrame`, `guidesToHost` и порог прилипания
 * берут масштаб из `getBoundingClientRect()` сцены, куда трансформация уже
 * входит (ADR-007, «масштаб берётся из DOM, никогда из сохранённого
 * значения»). Сохранённое здесь число сломало бы перетаскивание ТИХО.
 */
import type { StageSize, Zoom } from '@player/player';

/** Ступени масштаба холста — доли, а не проценты: в CSS едет доля. */
export const STAGE_ZOOM_STEPS = [0.1, 0.25, 0.5, 0.75, 1, 1.25, 2, 3] as const;

/**
 * Фактический масштаб: заданное автором число или посчитанное вписывание.
 *
 * `fitScale` приходит аргументом, а не считается здесь: его источник —
 * `fitStage` в плеере, и вторая формула вписывания в редакторе была бы
 * нарушением инварианта №5, причём тихим (на масштабе 1 обе дают одно и то же).
 */
export function effectiveScale(zoom: Zoom, fitScale: number): number {
  return zoom === 'fit' ? fitScale : zoom;
}

/** Подпись масштаба для автора. Проценты, как в Canva, а не доли. */
export function zoomPercent(scale: number): string {
  return `${Math.round(scale * 100)} %`;
}

/**
 * Следующая ступень ВВЕРХ от текущего фактического масштаба.
 *
 * От вписывания шагает от того, что видно сейчас, а не от начала лестницы:
 * при вписывании 60 % «+» обязан дать 75 %, а не 10 %. Так же ведёт себя
 * Canva — проверено на её документе, а не по памяти.
 *
 * На верхней ступени возвращает её же: кнопка гаснет, а не исчезает и не
 * бросает (`canZoomIn`). Ступень остаётся законным понятием, просто дальше
 * идти некуда — тот же приём, что у `zoomBlockedReason` дорожки.
 */
export function zoomIn(zoom: Zoom, fitScale: number): Zoom {
  const current = effectiveScale(zoom, fitScale);
  return STAGE_ZOOM_STEPS.find((step) => step > current + EPSILON) ?? lastStep();
}

/** Следующая ступень ВНИЗ. Разбор — у `zoomIn`. */
export function zoomOut(zoom: Zoom, fitScale: number): Zoom {
  const current = effectiveScale(zoom, fitScale);
  const below = STAGE_ZOOM_STEPS.filter((step) => step < current - EPSILON);
  return below.length > 0 ? below[below.length - 1]! : STAGE_ZOOM_STEPS[0];
}

export function canZoomIn(zoom: Zoom, fitScale: number): boolean {
  return effectiveScale(zoom, fitScale) < lastStep() - EPSILON;
}

export function canZoomOut(zoom: Zoom, fitScale: number): boolean {
  return effectiveScale(zoom, fitScale) > STAGE_ZOOM_STEPS[0] + EPSILON;
}

/**
 * Размер ПОЛОТНА, внутри которого лежит сцена, в пикселях контейнера.
 *
 * Не «сцена × масштаб», а максимум из него и размера окна — по каждой оси
 * отдельно. Обе половины несут смысл:
 *
 * - при вписывании полотно равно окну, полос прокрутки не появляется вовсе,
 *   и картинка получается ТА ЖЕ, что была до появления масштаба: `fitStage`
 *   получает те же числа и возвращает те же округлённые отступы;
 * - при увеличении полотно больше окна ровно на столько, сколько нужно
 *   прокрутке, а сцена внутри него стоит без отступов.
 *
 * Петли «полоса прокрутки съела ширину → пересчёт → полоса пропала» здесь
 * быть не может, и это следует из знака: появление полосы только УМЕНЬШАЕТ
 * окно, а уменьшение окна может добавить полос, но никогда не убирает.
 * Процесс монотонный, значит сходится.
 *
 * Вверх округляется намеренно: полотно, урезанное на дробную часть, обрезало
 * бы сцене последний столбец пикселей.
 */
export function canvasSize(
  stage: StageSize,
  scale: number,
  hostWidth: number,
  hostHeight: number,
): { width: number; height: number } {
  return {
    width: Math.max(hostWidth, Math.ceil(stage.width * scale)),
    height: Math.max(hostHeight, Math.ceil(stage.height * scale)),
  };
}

/**
 * Запас на двоичную неточность долей. `0.1 + 0.65` даёт 0.7500000000000001,
 * и сравнение «строго больше» без запаса перепрыгнуло бы ступень, на которой
 * автор сейчас стоит.
 */
const EPSILON = 1e-9;

function lastStep(): number {
  return STAGE_ZOOM_STEPS[STAGE_ZOOM_STEPS.length - 1]!;
}
