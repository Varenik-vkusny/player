/**
 * Куда положить всплывающее меню, чтобы оно не вылезло за край окна.
 *
 * Отдельным модулем и чистой функцией, а не тремя строками внутри
 * компонента, и причина не в красоте. Через интерфейс этот расчёт почти
 * недостижим: сцена в раскладке редактора стоит НАВЕРХУ (её низ около
 * 330 px), меню высотой ~208 px до нижнего края окна не достаёт, а низкое
 * окно уводит сцену из видимой области прокруткой. То есть внутри
 * компонента разворот был бы кодом, который выглядит рабочим и не проверен
 * ничем — а такой код ломается ровно тогда, когда до него наконец дойдут.
 *
 * Здесь он проверяется напрямую, без DOM и без браузера.
 */

/** Отступ от края окна, чтобы меню не липло к границе. */
export const EDGE_MARGIN = 8;

export interface Placement {
  readonly x: number;
  readonly y: number;
}

/**
 * `at` — где нажали (координаты окна), `size` — измеренный размер меню,
 * `viewport` — размер окна.
 *
 * По умолчанию меню растёт вправо-вниз от курсора: так его читают, и так
 * оно не накрывает то, по чему нажали. Не влезло — разворачивается в другую
 * сторону от ТОЙ ЖЕ точки, а не сдвигается на разницу: сдвиг увёл бы меню
 * из-под курсора, и автор потерял бы связь между нажатием и появившимся.
 *
 * Меню, которое не помещается ни так, ни эдак (оно выше окна), прижимается
 * к краю с отступом: показать частично лучше, чем увести за границу совсем.
 */
export function placeMenu(
  at: Placement,
  size: { readonly width: number; readonly height: number },
  viewport: { readonly width: number; readonly height: number },
): Placement {
  const overflowsRight = at.x + size.width + EDGE_MARGIN > viewport.width;
  const overflowsBottom = at.y + size.height + EDGE_MARGIN > viewport.height;

  return {
    x: overflowsRight ? Math.max(EDGE_MARGIN, at.x - size.width) : at.x,
    y: overflowsBottom ? Math.max(EDGE_MARGIN, at.y - size.height) : at.y,
  };
}
