/**
 * Полоса свойств над холстом: частые поля стиля выделения и дверь в полный
 * список свойств. До Сессии 48 здесь же жили выравнивание, раскладка, слои
 * и «копировать форматирование» — они переехали за дверь, см. ниже.
 *
 * До Сессии 30 это была полоса РАСПОЛОЖЕНИЯ (`ArrangeBar`, переименована).
 * Задание Сессии 30 переносит сюда частые поля стиля выделенного элемента
 * (или общие поля при множественном выделении — `state/propbar.ts`,
 * `propbarStyleFields`), а редкие остаются в панели «Объект» (бывший
 * `Inspector` из правой колонки, теперь открывается кнопкой «Объект» этой
 * полосы — переименована из «Ещё…» в Сессии 53, см. ниже). Виджеты полей —
 * те же, что у панели «Объект»
 * (`panels/styleFieldWidget.tsx`, `StyleFieldWidget`): задание прямо
 * требует переиспользовать приём правки стиля, а не заводить второй.
 *
 * **Строка полосы занимает своё место ВСЕГДА, исчезают только кнопки.**
 * Это куплено настоящим дефектом, найденным в Сессии 29 (журнал §8):
 * полоска, появлявшаяся вместе с выделением, ломала двойной клик по
 * элементу. Физика одна для обоих способов её разместить:
 *
 * - наложением поверх холста — первый клик двойного щелчка выделяет
 *   элемент, полоска возникает ПОД КУРСОРОМ, и второй клик попадает
 *   в её кнопку. В прогоне так и вышло: двойной клик по заголовку нажал
 *   «Выровнять по нижнему краю», и элемент уехал на низ холста;
 * - строкой в раскладке — появление строки уменьшает холст, сцена
 *   пересчитывает масштаб, и элемент уезжает из-под курсора; второй клик
 *   промахивается мимо него.
 *
 * Общее у обоих — обстановка под курсором меняется между двумя кликами
 * одного жеста. Постоянная высота строки убирает причину, а не симптом.
 * Высота — 48px (19.08.2026), до этого 56, до этого 38. Средний шаг был
 * взят под подпись над значением; замер показал, что подписей на экране нет
 * вовсе (1x1, clip-path: inset(50%)), поэтому высота приведена к тому, что
 * на строке действительно стоит: орган 28 плюс поля 8 и 8.
 *
 * Подписи кнопок расположения разведены с инспектором намеренно. У выключки
 * текста (`state/style.ts`) уже есть «По левому краю», и одинаковая подпись
 * на одном экране — это не только строгий режим Playwright, но и живая
 * путаница: выключка двигает текст ВНУТРИ элемента, а эта кнопка двигает
 * сам элемент по холсту. Поэтому здесь «Выровнять по левому краю».
 *
 * Кнопка «Объект» (до Сессии 53 — «Ещё…») — ОДНА дверь в панель «Объект».
 * В каркасе рядом с ней стоит ещё «Положение», ведущая туда же, и задание
 * прямо запрещает вторую дверь: автор перестаёт смотреть в обе. Здесь её
 * нет и не будет.
 *
 * **Сессия 53.** Подпись «Ещё…» переименована в «Объект»: дверь называется
 * именем панели, в которую ведёт (`Editor.tsx`, `handleSelectCategory('object')`,
 * заголовок панели по умолчанию — «Объект»), а не содержимым за ней
 * («Расположение») — за дверью лежит не только оно, а полный список свойств
 * объекта. Замер живой Канвы 19.08.2026 подтвердил саму дверь (у натуры
 * тоже стоит кнопка «Расположение» 121px), но не её подпись — имя панели
 * решает точнее, чем имя одного из её разделов.
 *
 * **Строка прокручивается и обязана об этом говорить (Сессия 46).** Замер
 * 18.08.2026 при окне 1280 и открытом каталоге — том состоянии, в котором
 * редактор открывается: полосе нужно 1276 px, достаётся 586. За краем
 * остаются ВСЕ тринадцать кнопок выравнивания, раскладки, слоёв и формата
 * и сама «Ещё…» — то есть единственная дверь ко всем прочим свойствам была
 * не видна вовсе. Отсюда ScrollStrip: он не убирает переполнение (при этой
 * ширине оно неустранимо — см. ниже), а делает его видимым и проходимым.
 *
 * **Переполнение при окне 1280 неустранимо перестановкой, и это числа,
 * а не мнение.** Из нужных 1276 px поля стиля занимают 697, а кнопки
 * с разделителями и «Ещё…» занимали 540. Доступно 586 — то есть не
 * помещались даже ОДНИ ПОЛЯ, без единой кнопки.
 *
 * **Сессия 48, решение владельца 18.08.2026.** С полосы убраны ВСЕ органы
 * расположения — выравнивание объектов, раскладка, слои, «копировать
 * форматирование» (13 кнопок и 4 разделителя, было 540 px) — и переехали
 * в блок «Расположение» панели «Объект» (`panels/Inspector.tsx`), за дверь
 * «Ещё…». На полосе остаются только частые поля стиля, названные владельцем
 * поимённо (шрифт, кегль, начертание, цвет, `text-align`) и сама дверь.
 * Подписи и `data-testid` органов не задвоены: обе точки показа зовут один
 * список — `stage/organs.ts`.
 *
 * Это НЕ делает полосу помещающейся при 1280 с открытым каталогом: одним
 * полям нужно 673 px при доступных 586. Задача не обещала этого и не могла —
 * см. `stage/organs.ts` и промпт Сессии 48. Полоса по-прежнему может
 * переполняться и по-прежнему обязана сообщать об этом (`ScrollStrip` ниже,
 * Сессия 46) — просто порог переполнения ниже, чем был.
 */
import { Fragment, type ReactElement } from 'react';

import type { LengthOrPercent, StyleFieldDef, StyleFieldKey, StyleReadResult } from '../state/style.js';
import { StyleFieldWidget } from '../panels/styleFieldWidget.js';
import { ScrollStrip } from '../ui/index.js';

export interface PropBarProps {
  /** Сколько элементов выделено: от этого зависит, какие кнопки живые. */
  selectedCount: number;
  /** Поля стиля полосы — уже отобранные `propbarStyleFields` вызывающим кодом. */
  styleFields: readonly StyleFieldDef[];
  /** Текущее значение поля — вызывающий код решает, из чьего style его читать. */
  styleValueOf: (key: StyleFieldKey) => StyleReadResult;
  onStyleCommit: (key: StyleFieldKey, value: string | number | LengthOrPercent) => void;
  /** Живое событие набора числа — см. комментарий styleFieldWidget.tsx. */
  onStyleLiveCommit: (key: StyleFieldKey, value: string | number | LengthOrPercent) => void;
  onStyleCommitHistory: () => void;
  /**
   * Открывает панель «Объект» — единственная дверь в полный список свойств
   * и, с Сессии 48, в блок «Расположение» (выравнивание, раскладка, слои,
   * «копировать форматирование» — см. шапку модуля).
   */
  onOpenObject: () => void;
  /**
   * Показания выделения: что сейчас выделено и какая у него геометрия.
   * Переехали сюда из правого верхнего угла шапки 19.08.2026 — там они
   * занимали место главного действия и повторяли текст пустого состояния
   * этой же полосы. Подробности в комментарии на месте выноса (Editor.tsx).
   */
  selectionReadout: string;
}

export function PropBar({
  selectedCount,
  selectionReadout,
  styleFields,
  styleValueOf,
  onStyleCommit,
  onStyleLiveCommit,
  onStyleCommitHistory,
  onOpenObject,
}: PropBarProps): ReactElement {
  // Ничего не выделено — ни полей стиля, ни кнопок расположения, но СТРОКА
  // остаётся: её высота постоянна, иначе холст менял бы размер в момент
  // выделения (см. шапку модуля). Внутренний тулбар (testid `propbar`) тут
  // же не монтируется вовсе — тот же приём, что был у прежнего ArrangeBar:
  // не «спрятан», а не существует в DOM, пока нечем его наполнить.
  //
  // Пустое состояние с 19.08.2026 — строка показаний плюс короткая подсказка,
  // а не EmptyState: заголовок «Ничего не выделено» стоял одновременно здесь
  // и в правом верхнем углу шапки, то есть одна мысль печаталась дважды
  // на одном экране. Показания переехали сюда и говорят её один раз.
  if (selectedCount === 0) {
    return (
      <div className="ed-propbar-row">
        {/* Заголовок пустого состояния БОЛЬШЕ НЕ ПИШЕТСЯ отдельно: его роль
            играет сама строка показаний, которая в этом случае и говорит
            «ничего не выделено». Раньше на экране стояли обе фразы сразу —
            эта и такая же в правом верхнем углу шапки. */}
        <span className="ed-selection" data-testid="selection-readout">
          {selectionReadout}
        </span>
        {/* Не EmptyState: у него заголовок обязателен (и это верно — молчащая
            пустая панель читается как поломка), а здесь заголовок уже сказан
            строкой слева. Второй раз то же самое печатать незачем. */}
        <span className="ed-propbar-hint">Выберите элемент на холсте</span>
      </div>
    );
  }

  return (
    <div className="ed-propbar-row">
      <span className="ed-selection" data-testid="selection-readout">
        {selectionReadout}
      </span>
      <ScrollStrip className="ed-propbar" role="toolbar" label="Свойства объекта" testId="propbar">
        {styleFields.length === 0 ? (
          <span className="ed-propbar-hint">Общих свойств нет</span>
        ) : (
          styleFields.map((field, index) => {
            /*
              Разделитель ставится там, где МЕНЯЕТСЯ группа, а не через
              заданное число полей: состав полосы зависит от того, что
              выделено (у текста пять полей, у фигуры два, у нескольких
              разнотипных — пересечение), и любое «каждое N-е» рассыпалось бы
              на первом же другом выделении. Признак берётся из поля,
              а не из порядкового номера.

              Перед первым полем разделителя нет: он отделяет группы друг
              от друга, а не открывает полосу.
            */
            const previous = index > 0 ? styleFields[index - 1] : undefined;
            const startsNewGroup = previous !== undefined && previous.group !== field.group;
            return (
              <Fragment key={field.key}>
                {startsNewGroup ? <span className="ed-propbar-sep" aria-hidden="true" /> : null}
                <div className="ed-propbar-field">
                  <StyleFieldWidget
                    field={field}
                    read={styleValueOf(field.key)}
                    onCommit={(value) => onStyleCommit(field.key, value)}
                    onLiveCommit={(value) => onStyleLiveCommit(field.key, value)}
                    onCommitHistory={onStyleCommitHistory}
                  />
                </div>
              </Fragment>
            );
          })
        )}

        {/* Кнопки расположения (выравнивание, раскладка, слои, «копировать
            форматирование») уехали за дверь «Объект» в Сессии 48 — см. шапку
            модуля и panels/Inspector.tsx, блок «Расположение». Распорка
            перед дверью остаётся: та же роль, что и раньше — прижать
            «Объект» к правому краю полосы. */}
        <span className="ed-propbar-spacer" aria-hidden="true" />

        {/* Подпись «Объект» — это Сессия 53: дверь названа именем панели,
            в которую ведёт (Editor.tsx, `title={currentCatalogCategory?.label
            ?? 'Объект'}`), а не содержимым за ней («Расположение»), потому
            что за дверью лежит не только расположение, а полный список
            свойств объекта. testid, класс и обработчик не меняются. */}
        <button
          type="button"
          className="ed-propbar-more"
          data-testid="propbar-more"
          onClick={onOpenObject}
        >
          Объект
        </button>
      </ScrollStrip>
    </div>
  );
}
