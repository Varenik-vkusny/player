import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { ICON_PATHS } from '../src/ui/icons.js';

const SRC = join(process.cwd(), 'packages/editor/src');

/**
 * Поверхность связей в дереве веток — НЕ значок, а холст: внутри лежат
 * <path> по вычисленной геометрии глав. Переносить её в библиотеку значков
 * нечего, переиспользованию она не подлежит.
 *
 * Список из одного файла, а не правило «кроме файлов, где есть svg»:
 * второй такой случай обязан появиться осознанно, а не просочиться.
 */
const NOT_AN_ICON: readonly string[] = ['track/BranchesView.tsx'];

/**
 * Метки на дорожке: ромб у слайда, столбик у остановки (MarksLane.tsx).
 * Из-под правила о символах выведены НАМЕРЕННО и до Сессии 47 («Дорожка»).
 *
 * Причина не в трудоёмкости. **Ромб — понятие продукта, а не украшение:**
 * владелец описал модель словами «каждый слайд показывается ромбом, чтобы
 * было видно, на какой секунде он приходит и с анимацией он или без».
 * Сменить ему рисунок внутри задачи про значки значило бы решить вопрос
 * облика мимоходом, не спросив.
 *
 * Вторая причина — размер: метки идут по дорожке плотно и ставятся
 * попиксельно (.ed-mark-gate стоит на top 43px), а значок Lucide — контур
 * в поле 24×24 с толщиной 2. На месте сплошного глифа он даст другую
 * плотность, и это видно, а не измеряется.
 */
const GLYPHS_DEFERRED: readonly string[] = ['track/MarksLane.tsx'];

/** Все .tsx пакета редактора, кроме самой библиотеки ui/ и названных исключений. */
function chromeSources(): { path: string; text: string }[] {
  const out: { path: string; text: string }[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'ui') walk(full);
      } else if (entry.name.endsWith('.tsx')) {
        const relative = full.slice(SRC.length + 1).split('\\').join('/');
        if (!NOT_AN_ICON.includes(relative)) {
          out.push({ path: relative, text: readFileSync(full, 'utf8') });
        }
      }
    }
  };
  walk(SRC);
  return out;
}

/** Сама библиотека ui/ — то, что chromeSources намеренно пропускает. */
function libraryTsx(): { path: string; text: string }[] {
  const dir = join(SRC, 'ui');
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.tsx'))
    .map((entry) => ({
      path: `ui/${entry.name}`,
      text: readFileSync(join(dir, entry.name), 'utf8'),
    }));
}

describe('хром редактора пользуется общей библиотекой ui/', () => {
  // Правило без охраны гниёт: CLAUDE.md запрещает плодить своё, и при
  // живом запрете написаны 84 кнопки (замер 17.08.2026).
  it('нет сырых <svg> вне ui/', () => {
    const guilty = chromeSources()
      .filter((f) => f.text.includes('<svg'))
      .map((f) => f.path);
    expect(guilty, `сырые <svg>: ${guilty.join(', ')}`).toEqual([]);
  });

  /**
   * Символ из шрифта — не значок, а буква: его рисует шрифт системы,
   * размер и толщина не подчиняются ничему, а на машине без глифа
   * остаётся пустой прямоугольник (ADR-034).
   *
   * Точные знаки, а не «любой не-ASCII»: в интерфейсе законно живут
   * кавычки-ёлочки, тире и знак умножения у ступеней масштаба.
   */
  it('значки не рисуются символами из шрифта', () => {
    const glyphs = ['\u25AE', '\u25A0', '\u2702'];
    const guilty = chromeSources()
      .filter((f) => !GLYPHS_DEFERRED.includes(f.path))
      .filter((f) => glyphs.some((g) => f.text.includes(g)))
      .map((f) => f.path);
    expect(guilty, `символы вместо значков: ${guilty.join(', ')}`).toEqual([]);
  });

  /**
   * Обычная кнопка — одна, и пишется она только через ui/Button.
   *
   * Правило НЕ «сырых button вне ui/ нет», как задумывалось: перепись
   * 17.08.2026 показала, что из 84 кнопок редактора 42 несут СВОЙ класс
   * с собственной геометрией и состоянием (выбранная плитка приёма, текущий
   * слайд, ручка стыка на дорожке, образец цвета, кнопка-поле ввода).
   * Запретить им быть кнопками нельзя — они не варианты обычной кнопки,
   * а разные органы. Поэтому охраняется то, что охранять осмысленно:
   * ОБЫЧНУЮ кнопку руками не пишут.
   *
   * Что должно сломаться, чтобы покраснело: кто-то ставит className
   * ed-btn или ed-action на свой button вместо того, чтобы взять Button.
   * Именно так и появились 42 одинаковые кнопки при живом запрете
   * плодить своё — класс копировался, а не переиспользовался компонент.
   */
  it('обычная кнопка не пишется руками', () => {
    const guilty = chromeSources()
      // ed-action(?![a-z]) — иначе правило ловит .ed-actions, контейнер-ряд
      // кнопок, который кнопкой не является. Поймано на себе: первая редакция
      // правила краснела на двух исправных файлах.
      // У ed-btn такого запрета нет намеренно: ed-btn-что-нибудь — это как раз
      // вид, написанный руками мимо перечня, и его ловить надо.
      .filter((f) => /ed-action(?![a-z])|ed-btn/.test(f.text))
      .map((f) => f.path);
    expect(guilty, `обычная кнопка руками: ${guilty.join(', ')}`).toEqual([]);
  });

  /**
   * Тот же закон, что у ролей цвета и ступеней кегля: набор «на будущее»
   * гниёт молча, потому что его никто не открывает. Значок заводится
   * тогда, когда его ставят, а не заранее.
   */
  it('каждый контур из ICON_PATHS хотя бы раз использован', () => {
    // Библиотека читается ЦЕЛИКОМ, а не одним Icon.tsx: значок, который
    // ставит другой компонент библиотеки (стрелка у ui/Section), живее
    // некуда, но одному Icon.tsx он не виден — и правило объявило бы
    // мёртвым работающий значок. Ошибка перечисления, а не смысла:
    // «мёртвый» здесь значит «нигде не поставлен», а ui/ — такое же «где-то».
    const used = chromeSources()
      .concat(libraryTsx())
      .map((f) => f.text)
      .join('\n');
    const dead = Object.keys(ICON_PATHS).filter(
      (name) => !used.includes(`name="${name}"`) && !used.includes(`'${name}'`),
    );
    expect(dead, `значки без применения: ${dead.join(', ')}`).toEqual([]);
  });
});

/**
 * Органы ввода, которые НЕЛЬЗЯ перевести на библиотеку без потери поведения.
 *
 * Список, а не правило: каждый случай обязан появиться осознанно и на виду.
 * Заполняется по итогам перевода Сессии 51 — пусто он не останется, и это
 * не слабость охраны, а её устройство. Обойти охрану случайно нельзя,
 * а обойти нарочно — значит вписать себя сюда, где это прочтут.
 */
const RAW_ORGAN_ALLOWED: readonly string[] = [
  // ⬛ СПРЯТАННЫЕ ОТ АВТОРА ОРГАНЫ ВЫБОРА ФАЙЛА — три штуки.
  //
  // Требование владельца «не остаётся ничего от дефолтного html» — про то,
  // что автор ВИДИТ. Эти органы он не видит никогда: они спрятаны
  // (display: none в Editor.tsx, clip: rect(0 0 0 0) в AudioSourcePanel),
  // а нажимает их отдельная видимая кнопка библиотеки через ref.click().
  // Перевести их на FileField значило бы поменять способ нажатия
  // с программного на родной label — то есть тронуть ПОВЕДЕНИЕ открытия
  // файла ради числа в отчёте. Замена облика не меняет орган; здесь менять
  // было бы нечего, кроме поведения.
  'Editor.tsx',
  'track/AudioSourcePanel.tsx',

  // ⬛ ПОРОГ СРАВНЕНИЯ в форме условия выхода (SegmentPanel.tsx).
  //
  // Это не число, а ЧЕРНОВИК СТРОКИ, который проверяется в момент нажатия
  // «Добавить», а не при наборе. NumberField устроен наоборот: он коммитит
  // каждое валидное нажатие клавиши через свой черновик. Перевод дал бы
  // тихий дефект: автор печатает «12x», поле его не коммитит, и кнопка
  // «Добавить» подхватывает ПРЕЖНЕЕ валидное число — то есть отправляет
  // не то, что автор видит на экране. Плюс пропал бы родной степпер.
  'panels/SegmentPanel.tsx',

  // ⬛ СПИСОК МАСШТАБА в пилюле над холстом (ZoomBar.tsx).
  //
  // Две причины, и обе несущие. Первая: у списка нет видимой подписи и быть
  // не должно — орган сам показывает своё значение («Вписать · 44 %»),
  // а поля библиотеки рисуют подпись обязательно, и в пилюле высотой
  // в строку она дала бы второй ряд. Вторая: масштаб сцены — ОБЩИЙ РЕСУРС
  // жестовых тестов, любая правка его раскладки роняет чужие проверки
  // прилипания через изменившуюся высоту зоны.
  'stage/ZoomBar.tsx',

  // ⬛ ПРАВКА ИМЕНИ ГЛАВЫ НА МЕСТЕ, поверх плитки дерева веток
  // (BranchesView.tsx).
  //
  // Найдено исполнителем при переводе и проверено чтением, а не памятью:
  // className у StringField уходит на ОБЁРТКУ Field, а сам input жёстко
  // пишет ed-insp-input. У органа же свой класс ed-chapter-rename, который
  // задаёт flex: 1 1 auto, свои паддинги, отсутствие рамки и фон под
  // растягивающуюся плитку. Перевод молча подменил бы класс, и орган
  // вывалился бы из флекс-раскладки плитки.
  //
  // Второе: правка НА МЕСТЕ подписи не имеет намеренно, а Field рисует её
  // всегда. Заводить «поле без подписи» ради одного случая нельзя: подпись
  // обязательна типом именно затем, чтобы её нельзя было отключить мимоходом.
  //
  // ДОЛГ, названный вслух: нужен либо проп на класс САМОГО органа, либо
  // отдельный компонент правки на месте. Записано в docs/debt.md.
  'track/BranchesView.tsx',
];

/**
 * Комментарии вычитаются ПЕРЕД поиском, и это не мелочь.
 *
 * В исходниках редактора одиннадцать мест, где тег органа упомянут
 * в пояснении: «роль вида «цвет» может нести строку, <input type=color>
 * не умеющую», «Список — обычный <select>, а не своё меню» и другие.
 * Поиск без вычитания комментариев считает их органами — проверено при
 * переписи Сессии 51: сырой греп дал 20 списков там, где их 11.
 *
 * Номера строк не едут: символ заменяется пробелом, перевод строки остаётся.
 */
function withoutComments(text: string): string {
  const out = text.split('');
  let i = 0;
  while (i < out.length) {
    if (text.startsWith('/*', i)) {
      const end = text.indexOf('*/', i + 2);
      const stop = end < 0 ? out.length : end + 2;
      for (let k = i; k < stop; k += 1) if (out[k] !== '\n') out[k] = ' ';
      i = stop;
    } else if (text.startsWith('//', i)) {
      const end = text.indexOf('\n', i);
      const stop = end < 0 ? out.length : end;
      for (let k = i; k < stop; k += 1) out[k] = ' ';
      i = stop;
    } else {
      i += 1;
    }
  }
  return out.join('');
}

/**
 * Все .tsx редактора, кроме самой библиотеки ui/. Без исключений,
 * заведённых под другие правила — см. пояснение внутри проверки органов.
 */
function everyChromeTsx(): { path: string; text: string }[] {
  const out: { path: string; text: string }[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'ui') walk(full);
      } else if (entry.name.endsWith('.tsx')) {
        out.push({ path: full.slice(SRC.length + 1).split('\\').join('/'), text: readFileSync(full, 'utf8') });
      }
    }
  };
  walk(SRC);
  return out;
}

describe('органы ввода берут из библиотеки, а не пишут руками', () => {
  /**
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ: любой возвращённый сырой input/select/textarea
   * вне ui/. Именно так копятся разнобой и неподписанные органы: копируется
   * тег, а не переиспользуется компонент.
   *
   * Перепись Сессии 51 нашла 29 таких органов в десяти файлах, из них
   * ДЕВЯТЬ без единой подписи — ни label, ни htmlFor, ни aria-label. Орган
   * без подписи не существует ни для чтения с экрана, ни для поиска
   * по имени в тесте, и заметить это глазами нельзя: он выглядит обычно.
   */
  it('вне ui/ нет сырых input, select и textarea', () => {
    const found: string[] = [];
    // СВОЙ обход, а не chromeSources(): тот исключает NOT_AN_ICON, то есть
    // track/BranchesView.tsx. Исключение заведено под ДРУГОЕ правило — про
    // сырые <svg>, — и, унаследуй его эта проверка, орган переименования
    // главы выпал бы из-под охраны МОЛЧА. Ровно он и есть один из девяти
    // неподписанных, найденных переписью. Исключение одного правила не
    // распространяется на соседнее само собой.
    for (const { path, text } of everyChromeTsx()) {
      if (RAW_ORGAN_ALLOWED.includes(path)) continue;
      const clean = withoutComments(text);
      for (const tag of ['<input', '<select', '<textarea']) {
        let at = clean.indexOf(tag);
        while (at >= 0) {
          const line = clean.slice(0, at).split('\n').length;
          found.push(`${path}:${line} — ${tag}`);
          at = clean.indexOf(tag, at + tag.length);
        }
      }
    }
    expect(found, `сырые органы вне ui/:
${found.join('\n')}`).toEqual([]);
  });

  /**
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ: поле библиотеки, у которого подпись стала
   * необязательной. Правило, выразимое типом, выражают типом — необязательную
   * подпись однажды не передадут, и молча.
   *
   * Проверяется ТЕКСТ объявления, а не поведение: тип до прогона не доживает,
   * а тест обязан ловить именно правку объявления.
   */
  it('у каждого поля библиотеки подпись объявлена обязательной', () => {
    const fields = readFileSync(join(SRC, 'ui/fields.tsx'), 'utf8');
    const optional = [...fields.matchAll(/label\?:/g)];
    expect(optional, 'подпись стала необязательной в ui/fields.tsx').toEqual([]);
    // Положительный контроль на сам прибор: обязательные подписи там ЕСТЬ,
    // и их не одна. Без него «ноль необязательных» был бы зелен и у файла,
    // в котором подписей не осталось вовсе.
    const required = [...fields.matchAll(/^ {2}label: string;$/gm)];
    expect(required.length).toBeGreaterThanOrEqual(8);
  });
});
