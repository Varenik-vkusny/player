/**
 * Разведение близких меток по рядам.
 *
 * Проверяется СВОЙСТВО, ради которого функция написана: соседи, чьи
 * прямоугольники пересекаются, попадают в разные ряды — и потому их
 * центры перестают закрывать друг друга.
 */
import { describe, expect, it } from 'vitest';

import { assignMarkRows, type RowInput } from '../src/track/markRows.js';

const W = 18;

/** Метки по заданным центрам, названные своим положением. */
function at(...xs: number[]): RowInput[] {
  return xs.map((x) => ({ key: `m${x}`, x }));
}

describe('assignMarkRows: близкие метки расходятся по рядам', () => {
  /**
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ: раскладка перестала смотреть на перекрытие
   * и кладёт всех в один ряд — то есть вернулась ровно та беда,
   * из-за которой на окне 1280 семь меток из шестнадцати нельзя было
   * выбрать нажатием.
   */
  it('перекрывающиеся соседи попадают в разные ряды', () => {
    // Центры в 4 px друг от друга при ширине 18 — перекрытие 14.
    const rows = assignMarkRows(at(100, 104), W, 2);
    expect(rows.get('m100')).not.toBe(rows.get('m104'));
  });

  /**
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ: раскладка стала чередовать ряды ВСЕГДА,
   * не глядя на расстояние. Тогда далеко стоящие метки прыгали бы
   * вверх-вниз без причины, и полоса читалась бы как случайная россыпь.
   */
  it('далёкие метки остаются в первом ряду', () => {
    const rows = assignMarkRows(at(100, 200, 300), W, 2);
    expect([...rows.values()]).toEqual([0, 0, 0]);
  });

  /**
   * Касание край в край — ещё НЕ перекрытие: правый край одной ровно
   * на левом крае другой. Граничный случай назван отдельно, потому что
   * ошибка на единицу здесь дала бы лишний ряд на ровном месте.
   */
  it('метки, стоящие вплотную, делят один ряд', () => {
    const rows = assignMarkRows(at(100, 118), W, 2);
    expect(rows.get('m100')).toBe(rows.get('m118'));
  });

  /**
   * ЦЕПОЧКА ИЗ ТРЁХ. Первая и вторая перекрываются, вторая и третья тоже,
   * а первая с третьей — уже нет. Двух рядов хватает, и третья возвращается
   * в первый: ряд освободился.
   *
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ: раскладка запоминает «занятость» ряда навсегда,
   * а не по правому краю последней метки. Тогда на длинной дорожке ряды
   * кончились бы, и всё поехало бы в последний.
   */
  it('в цепочке из трёх ряд освобождается и переиспользуется', () => {
    const rows = assignMarkRows(at(100, 110, 125), W, 2);
    expect(rows.get('m100')).toBe(0);
    expect(rows.get('m110')).toBe(1);
    expect(rows.get('m125')).toBe(0);
  });

  /**
   * ТРИ В ОДНОЙ ТОЧКЕ при двух рядах — случай, который развести нельзя
   * никаким числом рядов, и функция обязана вести себя предсказуемо,
   * а не бросать. Берётся ряд с наименьшим перекрытием.
   *
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ: выход за пределы `maxRows` — метка получила бы
   * ряд, которого в полосе нет, и уехала бы за её границу.
   */
  it('при нехватке рядов не выходит за maxRows', () => {
    const rows = assignMarkRows(at(100, 102, 104, 106, 108), W, 2);
    for (const row of rows.values()) {
      expect(row).toBeGreaterThanOrEqual(0);
      expect(row).toBeLessThan(2);
    }
  });

  /**
   * Порядок входа не важен: метки могут прийти как угодно, раскладка
   * идёт по положению. Без этого раскладка зависела бы от того, в каком
   * порядке продукт собрал список, — то есть от случайности.
   */
  it('результат не зависит от порядка на входе', () => {
    const straight = assignMarkRows(at(100, 110, 125), W, 2);
    const shuffled = assignMarkRows([...at(125, 100, 110)], W, 2);
    expect([...shuffled.entries()].sort()).toEqual([...straight.entries()].sort());
  });

  it('пустой вход даёт пустую раскладку, а не ошибку', () => {
    expect(assignMarkRows([], W, 2).size).toBe(0);
  });

  it('ноль рядов — ошибка вызова, а не молчаливая раскладка', () => {
    expect(() => assignMarkRows(at(100), W, 0)).toThrow(/ряд/i);
  });
});
