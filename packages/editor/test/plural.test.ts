import { describe, expect, it } from 'vitest';

import { ANIMATIONS, ELEMENTS, GATES, plural, pluralForm } from '../src/plural.js';

/**
 * Согласование числительного ломается всегда в одном месте — на 11–14, где
 * последняя цифра обещает одну форму, а нужна другая. Поэтому тесты идут
 * таблицей по числам, а не по паре примеров: пропущенный диапазон здесь
 * выглядит работающим кодом.
 */
describe('форма слова по числу', () => {
  const cases: readonly (readonly [number, string])[] = [
    [0, 'элементов'],
    [1, 'элемент'],
    [2, 'элемента'],
    [3, 'элемента'],
    [4, 'элемента'],
    [5, 'элементов'],
    [10, 'элементов'],
    // Исключение: последняя цифра 1–4, но форма множественная.
    [11, 'элементов'],
    [12, 'элементов'],
    [13, 'элементов'],
    [14, 'элементов'],
    [15, 'элементов'],
    [20, 'элементов'],
    [21, 'элемент'],
    [22, 'элемента'],
    [25, 'элементов'],
    [101, 'элемент'],
    [102, 'элемента'],
    // Сотня не отменяет исключения: 111 ведёт себя как 11, а не как 1.
    [111, 'элементов'],
    [112, 'элементов'],
    [121, 'элемент'],
  ];

  it.each(cases)('%i → «%s»', (count, expected) => {
    expect(pluralForm(count, ELEMENTS)).toBe(expected);
  });
});

describe('число вместе с формой', () => {
  it('подставляет само число', () => {
    expect(plural(1, ELEMENTS)).toBe('1 элемент');
    expect(plural(3, ANIMATIONS)).toBe('3 анимации');
    expect(plural(11, GATES)).toBe('11 остановок');
  });

  it('пустой набор — тоже осмысленная фраза, а не пропуск', () => {
    expect(plural(0, ELEMENTS)).toBe('0 элементов');
    expect(plural(0, GATES)).toBe('0 остановок');
  });
});

describe('чего не бывает', () => {
  it('дробное и отрицательное падают громко, а не выдают правдоподобную форму', () => {
    // Молчаливое округление здесь опаснее ошибки: «1.5 элемент» выглядит
    // как опечатка в тексте, а не как дефект вызывающего кода.
    expect(() => pluralForm(1.5, ELEMENTS)).toThrow(RangeError);
    expect(() => pluralForm(-1, ELEMENTS)).toThrow(RangeError);
    expect(() => pluralForm(Number.NaN, ELEMENTS)).toThrow(RangeError);
  });
});
