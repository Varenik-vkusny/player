/**
 * Один вид времени на один случай (Сессия 47, Задача 4).
 *
 * Тесты держат не «красивый вывод», а СОВПАДЕНИЕ: то, что автор видит
 * в двух местах про одно и то же время, обязано быть написано одинаково.
 */
import { describe, expect, it } from 'vitest';

import { MARK_HIT_SECONDS } from '../src/state/slides.js';
import { clockText, secondsText } from '../src/timeText.js';

describe('подпись секунд для автора', () => {
  it('два знака после точки и единица словом', () => {
    expect(secondsText(0)).toBe('0.00 с');
    expect(secondsText(1.45)).toBe('1.45 с');
    expect(secondsText(48.6)).toBe('48.60 с');
  });

  /**
   * НЕСУЩИЙ ТЕСТ, и он же объяснение выбора числа знаков. Что должно
   * сломаться, чтобы он покраснел: число знаков уменьшат до одного —
   * тогда две метки, стоящие на законном минимальном расстоянии,
   * получат ОДНУ И ТУ ЖЕ подпись, и автор увидит два разных слайда
   * с одинаковым временем.
   *
   * Этот тест не тождество: он связывает подпись с ЧУЖОЙ константой
   * модели (MARK_HIT_SECONDS), а не с самой собой.
   */
  it('различает две метки, стоящие на минимальном допустимом расстоянии', () => {
    expect(MARK_HIT_SECONDS).toBe(0.01);
    expect(secondsText(5)).not.toBe(secondsText(5 + MARK_HIT_SECONDS));
  });

  /**
   * Обратная сторона того же выбора: лишних знаков быть не должно.
   * Разряд мельче MARK_HIT_SECONDS в модели не существует, и показывать
   * его автору значит показывать разницу, которой не бывает.
   */
  it('не показывает разряда, которого в модели не бывает', () => {
    expect(secondsText(5.0004)).toBe(secondsText(5));
  });
});

describe('часы транспорта', () => {
  it('минуты и десятые доли', () => {
    expect(clockText(0)).toBe('00:00.0');
    expect(clockText(1.5)).toBe('00:01.5');
    expect(clockText(48.6)).toBe('00:48.6');
    expect(clockText(61.25)).toBe('01:01.3');
  });

  /**
   * Что должно сломаться, чтобы он покраснел: снимут защиту от значения,
   * которого ещё нет. Позиция приходит из аудиоконтекста, и до первого
   * кадра она бывает какой угодно; часы обязаны показывать время,
   * а не NaN.
   */
  it('нечисловое и отрицательное показывает нулём, а не NaN', () => {
    expect(clockText(Number.NaN)).toBe('00:00.0');
    expect(clockText(-3)).toBe('00:00.0');
    expect(clockText(Number.POSITIVE_INFINITY)).toBe('00:00.0');
  });
});
