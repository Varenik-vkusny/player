import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { loadProject } from '@player/core';

import { splitAtTime, splitHereProblem } from '../src/state/project.js';

/**
 * Согласие между «кнопка погашена» и «разрез отказывает».
 *
 * Предмет — не разрез сам по себе (он проверен в `split.test.ts`), а РАВЕНСТВО
 * двух ответов. Разойтись им нельзя ни в одну сторону:
 *
 * - разрешено, но бросает → редьюсер кидает исключение прямо во время
 *   обработки щелчка, React снимает всё дерево, автор видит белый экран.
 *   Ровно это владелец получил 17.08.2026, нажав «разделить здесь»;
 * - запрещено, но проходит → кнопка гаснет там, где всё было можно,
 *   и автор не понимает, почему продукт ему отказывает.
 *
 * ПОЧЕМУ ЭТО РАЗОШЛОСЬ. Функция отказа бралась одна и та же — рядом даже
 * стояло предупреждение «повтори её здесь своими условиями, и однажды кнопка
 * нажалась бы, а разрез упал». Но кнопке она считалась от длительности
 * ДОРОЖКИ (`transport.durationSeconds`), а разрезу — от длительности,
 * объявленной в ПРОЕКТЕ. Совпадать этим числам положено, и в покое они
 * совпадают; расходятся они в промежутке между сменой главы и дозагрузкой
 * её дорожки. Одинаковая функция с разными аргументами — то же самое, что
 * две разные функции.
 */

const FIXTURES = fileURLToPath(new URL('../../../fixtures/projects/', import.meta.url));

function loadFixture(name: string) {
  return loadProject(JSON.parse(readFileSync(join(FIXTURES, name), 'utf8')));
}

describe('разрез главы: кнопка и действие отвечают одинаково', () => {
  /**
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ, ЧТОБЫ ПОКРАСНЕЛ: любое расхождение условий между
   * `splitHereProblem` и тем, что проверяет сам разрез. Например, вернуть
   * `splitHereProblem` к счёту от длины ДОРОЖКИ вместо длины главы —
   * на секундах у самого конца ответы разойдутся, и `expect(...).not.toThrow`
   * упадёт настоящим исключением, а не сравнением.
   *
   * ВЕРНО ЛИ ПРИ ЛЮБОЙ РЕАЛИЗАЦИИ: нет. Сетка нарочно накрывает ОБЕ границы —
   * нулевую (до начала главы делить нечего) и хвостовую (после метки должно
   * остаться на главу), — а между ними лежат секунды, где разрез обязан
   * пройти. Реализация, которая всегда запрещает, провалит проверку «хоть
   * раз разрешено»; которая всегда разрешает — провалит `toThrow`.
   */
  it.each(['demo.json', 'split-track.json', 'conditions.json'])(
    'на %s согласие держится по всей длине главы, включая обе границы',
    (fixture) => {
      const project = loadFixture(fixture);

      for (const segment of project.segments) {
        const duration = segment.audio.duration;
        // Сетка идёт ЗА края намеренно: отрицательные секунды и секунды
        // за концом — не выдумка, головка попадает туда при смене главы.
        const grid = [
          -1, -0.001, 0, 0.001, 0.05, 0.2,
          duration / 2,
          duration - 0.3, duration - 0.25, duration - 0.24, duration - 0.001,
          duration, duration + 0.5,
        ];

        let allowedAtLeastOnce = false;

        for (const seconds of grid) {
          const problem = splitHereProblem(project, segment.id, seconds);

          if (problem === undefined) {
            allowedAtLeastOnce = true;
            expect(
              () => splitAtTime(project, segment.id, seconds),
              `разрешено на ${seconds} с, но разрез бросил — это белый экран у автора`,
            ).not.toThrow();
          } else {
            expect(
              () => splitAtTime(project, segment.id, seconds),
              `запрещено на ${seconds} с («${problem}»), но разрез прошёл`,
            ).toThrow();
          }
        }

        // Контроль прибора: если бы функция запрещала ВСЁ, цикл выше был бы
        // зелёным и не значил бы ничего.
        expect(allowedAtLeastOnce, `на главе «${segment.id}» не нашлось ни одной разрешённой секунды`)
          .toBe(true);
      }
    },
  );

  /**
   * Отдельным тестом — случай, ради которого функция вообще заведена:
   * главы с таким идентификатором в проекте НЕТ.
   *
   * ЧТО ДОЛЖНО СЛОМАТЬСЯ: убрать раннюю проверку и дать функции упасть
   * на `undefined` — вместо погашенной кнопки автор получит исключение
   * при отрисовке, то есть снова белый экран.
   * ВЕРНО ЛИ ПРИ ЛЮБОЙ РЕАЛИЗАЦИИ: нет — реализация через `requireSegment`
   * (а он в этом файле рядом и именно бросает) провалит этот тест.
   */
  it('исчезнувшая глава гасит кнопку, а не роняет редактор', () => {
    const project = loadFixture('demo.json');
    expect(() => splitHereProblem(project, 'главы-такой-нет', 1)).not.toThrow();
    expect(splitHereProblem(project, 'главы-такой-нет', 1)).toBeDefined();
  });
});
