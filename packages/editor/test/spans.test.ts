/**
 * Правила отрезков «моё»: куда упирается край и куда встаёт новый клип.
 *
 * Каждому тесту ниже задано ДВА вопроса, а не один:
 *   1. что должно сломаться, чтобы он покраснел;
 *   2. верно ли это утверждение при ЛЮБОЙ реализации предмета.
 *
 * Второй вопрос отсеивает тесты, пустые по тождеству, — те, что проверяют
 * функцию её же формулой. Поэтому здесь везде стоят КОНКРЕТНЫЕ числа
 * с назваными упорами, а не «результат лежит между соседями».
 */
import { describe, expect, it } from 'vitest';

import {
  clampEdge, clampWhole, insertionIndex, placeNew, MIN_SPAN_SECONDS, type SpanRange,
} from '../src/track/spans.js';

/** Два отрезка с промежутком: [2, 4] и [6, 8] на десятисекундной главе. */
const SPANS: SpanRange[] = [
  { fromSeconds: 2, toSeconds: 4 },
  { fromSeconds: 6, toSeconds: 8 },
];
const DURATION = 10;

describe('тяга за край', () => {
  it('левый край упирается в конец предыдущего отрезка, а не в ноль', () => {
    // СЛОМ: заменить `spans[index - 1]?.toSeconds ?? 0` на `0` — край уедет
    // на 1 и наложится на первый отрезок.
    // ПРИ ЛЮБОЙ РЕАЛИЗАЦИИ? Нет: 4 — это конец СОСЕДА, и ответ «1» (то,
    // что просили) или «0» (граница главы) даёт другая реализация.
    expect(clampEdge(SPANS, 1, 'from', 1, DURATION)).toBe(4);
  });

  it('первый отрезок упирается влево в ноль', () => {
    // СЛОМ: убрать `?? 0` — обращение к `undefined.toSeconds` уронит функцию.
    expect(clampEdge(SPANS, 0, 'from', -5, DURATION)).toBe(0);
  });

  it('правый край упирается в начало следующего отрезка', () => {
    // СЛОМ: заменить `spans[index + 1]?.fromSeconds` на `durationSeconds`.
    expect(clampEdge(SPANS, 0, 'to', 9, DURATION)).toBe(6);
  });

  it('последний отрезок упирается вправо в конец главы', () => {
    expect(clampEdge(SPANS, 1, 'to', 99, DURATION)).toBe(DURATION);
  });

  it('край не проходит сквозь собственный второй край', () => {
    // Отрезок не выворачивается наизнанку и не схлопывается в невидимый:
    // схема нулевую длину запрещает, а трёхмиллисекундный клип формально
    // законен и при этом не ловится курсором.
    //
    // СЛОМ: убрать `- MIN_SPAN_SECONDS` — вернётся 4 (нулевая длина),
    // и разбор проекта упадёт на «кончается не позже, чем начинается».
    expect(clampEdge(SPANS, 0, 'from', 7, DURATION)).toBe(4 - MIN_SPAN_SECONDS);
    expect(clampEdge(SPANS, 0, 'to', 0, DURATION)).toBe(2 + MIN_SPAN_SECONDS);
  });

  it('свободная тяга внутри промежутка отдаёт ровно то, что просили', () => {
    // Без этого теста все проверки выше выполняла бы функция,
    // возвращающая константу-упор.
    expect(clampEdge(SPANS, 1, 'from', 5, DURATION)).toBe(5);
  });
});

describe('перетаскивание отрезка целиком', () => {
  it('длина сохраняется, отрезок упирается в соседа целиком', () => {
    // СЛОМ: считать `high` без вычитания длины — отрезок [6,8] встал бы
    // началом на 4 и налез на соседа хвостом.
    // ПРИ ЛЮБОЙ РЕАЛИЗАЦИИ? Нет: 2 — это 4 (конец соседа) МИНУС ничего,
    // а вот `toSeconds` 4 доказывает, что двигали целиком.
    expect(clampWhole(SPANS, 1, 0, DURATION)).toEqual({ fromSeconds: 4, toSeconds: 6 });
  });

  it('вправо упирается так, чтобы хвост не вышел за главу', () => {
    expect(clampWhole(SPANS, 1, 99, DURATION)).toEqual({ fromSeconds: 8, toSeconds: 10 });
  });

  it('отрезок встык к соседям не двигается никуда — места нет', () => {
    // Вырожденный случай, ради которого была написана и ВЫБРОШЕНА защита
    // «промежуток короче отрезка». Такого промежутка не бывает: отрезки
    // упорядочены и не пересекаются, поэтому верхний упор не может оказаться
    // ниже нижнего. Здесь место ровно по длине — и отрезок стоит.
    //
    // СЛОМ: убрать вычитание длины из `high` — отрезок уедет вправо
    // и налезет на соседа.
    const tight: SpanRange[] = [
      { fromSeconds: 0, toSeconds: 3 },
      { fromSeconds: 3, toSeconds: 8 },
      { fromSeconds: 8, toSeconds: 10 },
    ];
    expect(clampWhole(tight, 1, 4, DURATION)).toEqual(tight[1]);
    expect(clampWhole(tight, 1, 0, DURATION)).toEqual(tight[1]);
  });
});

describe('рисование нового отрезка', () => {
  it('новый отрезок встаёт в свободный промежуток и не налезает на соседей', () => {
    // Тянем от 3.5 (внутри первого отрезка? нет — 3.5 внутри [2,4]) —
    // берём заведомо свободное место 4.5 → 7 и проверяем, что хвост
    // обрезался о начало соседа на 6.
    //
    // СЛОМ: убрать сужение `high` по соседям — вернулось бы [4.5, 7].
    expect(placeNew(SPANS, 4.5, 7, DURATION)).toEqual({ fromSeconds: 4.5, toSeconds: 6 });
  });

  it('жест, начатый ВНУТРИ существующего отрезка, не создаёт ничего', () => {
    // Ответ «нет» здесь законен: не появившийся клип виден сразу,
    // а клип, молча вставший не туда, автор заметит через полчаса.
    //
    // СЛОМ: убрать проверку `low > high` — из середины отрезка получился бы
    // клип внахлёст, и проект перестал бы разбираться.
    expect(placeNew(SPANS, 3, 3.5, DURATION)).toBeUndefined();
  });

  it('слишком короткий жест не создаёт ничего', () => {
    // Щелчок по пустому месту — это не «нарисовать отрезок нулевой длины».
    expect(placeNew(SPANS, 5, 5.05, DURATION)).toBeUndefined();
  });

  it('тяга справа налево создаёт тот же отрезок, что и слева направо', () => {
    // ПРИ ЛЮБОЙ РЕАЛИЗАЦИИ? Нет — реализация без min/max вернула бы
    // отрезок с отрицательной длиной, и схема отказала бы в разборе.
    expect(placeNew(SPANS, 5.5, 4.5, DURATION)).toEqual(placeNew(SPANS, 4.5, 5.5, DURATION));
    expect(placeNew(SPANS, 5.5, 4.5, DURATION)).toEqual({ fromSeconds: 4.5, toSeconds: 5.5 });
  });
});

describe('место вставки в упорядоченный массив', () => {
  it('отрезок, нарисованный левее всех, встаёт первым', () => {
    // СЛОМ: возвращать `spans.length` всегда — массив перестанет быть
    // упорядоченным, и схема откажет в разборе с «идут не по порядку».
    // Именно этот слом объясняет, зачем функция вообще есть: «вставить
    // в конец» работает ровно до первого отрезка левее прежних.
    expect(insertionIndex(SPANS, 0.5)).toBe(0);
  });

  it('в промежуток — между соседями', () => {
    expect(insertionIndex(SPANS, 5)).toBe(1);
  });

  it('правее всех — в конец', () => {
    expect(insertionIndex(SPANS, 9)).toBe(2);
  });
});
