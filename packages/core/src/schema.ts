/**
 * Схема проекта — единственный источник истины. Текущая версия в SCHEMA_VERSION
 * ниже; в этом заголовке её нет намеренно: числа в комментариях гниют.
 *
 * Типы TypeScript выводятся отсюда через z.infer и НИКОГДА не пишутся руками:
 * два описания одной сущности неизбежно разъедутся, причём тихо (см. ADR-004).
 *
 * Инвариант №7: любое изменение схемы = бамп версии + функция миграции +
 * фикстура + тест. Без исключений, даже для «мелкого поля».
 *
 * Три уровня, сверху вниз (ADR-015):
 *
 *   Объяснение    — костяк из сегментов, у некоторых есть ответвления
 *   Сегмент  — линейная последовательность слайдов с одной непрерывной озвучкой
 *   Слайд   — снимок состояния сцены в момент времени, не отдельная страница
 *
 * Два правила продукта выражены здесь ФОРМОЙ, а не проверкой, и потому
 * нарушить их нельзя:
 *
 *   «Гейт никуда не перекидывает» — у `Gate` нет поля для рёбер вообще.
 *   «Развилка только в конце сегмента» — `Exit` есть поле сегмента, и положить
 *   его в середину некуда.
 *
 * Правило, которое невыразимо, дешевле правила, которое надо проверять.
 */
import { z } from 'zod';

export const SCHEMA_VERSION = 17;

/**
 * Длительность перехода по умолчанию, секунды.
 *
 * Число переехало сюда из плеера (`MORPH_DURATION_S`), но НЕ изменилось.
 * Это не аккуратность, а условие доказательства: умолчание обязано
 * воспроизвести сегодняшний вид, иначе 80 скриншотных эталонов покраснеют,
 * и вместе с ними исчезнет единственная проверка, показывающая, что v9
 * ничего не сломала.
 */
export const DEFAULT_TRANSITION_SECONDS = 0.6;

/**
 * Каталог приёмов перехода между слайдами. Восемь, и каждый укладывается
 * в инвариант №8: анимируются только `transform`, `opacity`, `filter`.
 *
 * «Штора» (`wipe`) и «Круг» (`circle`) стоят здесь ПО ИЗМЕРЕНИЮ, а не
 * по рассуждению. У Canva они сделаны `clip-path`, которого в `ANIMATABLE`
 * нет и быть не должно — он уводит с композитора. Плашкой на `transform`
 * они выразимы, и это подтверждено прогоном S12 (`spikes/results/s12.json`):
 * p5 58.8 и 59.2 при пороге 55, три прогона, величина воспроизвелась
 * цифра в цифру.
 *
 * `cut` стоит первым намеренно: «нет перехода» — запись каталога, а не
 * пустой выбор. Тот же закон, что «нет цвета» ≠ «белый цвет».
 */
export const TRANSITIONS = [
  'cut', 'morph', 'dissolve', 'slide', 'scale', 'blur', 'wipe', 'circle',
] as const;

/**
 * Направления перехода. Снято с натуры 07.08.2026: у Canva в панели
 * перехода четыре кнопки-стрелки — ← → ↑ ↓, ровно эти и никаких больше.
 *
 * Порядок здесь повторяет порядок кнопок у Canva слева направо и на
 * поведение не влияет.
 */
export const TRANSITION_DIRECTIONS = ['left', 'right', 'up', 'down'] as const;

/**
 * Стрелка — НАПРАВЛЕНИЕ ДВИЖЕНИЯ того, что едет, а не сторона, откуда оно
 * приходит. У `slide` едет сцена, у `wipe` — плашка шторы.
 *
 * Сказано здесь вслух, потому что два прочтения одинаково правдоподобны
 * («влево» = уезжает влево или приезжает слева), и разойтись они могут
 * молча: картинка выглядит осмысленно при любом.
 *
 * Точное прочтение стрелки у самой Canva НЕ проверено — снят только факт,
 * что кнопок четыре. → docs/research/canva-model.md, реестр, строка 2
 */
export type TransitionDirection = (typeof TRANSITION_DIRECTIONS)[number];

/**
 * Направление, которое подставляет ПЛЕЕР, когда автор его не выбрал.
 *
 * Живёт здесь, а не в плеере, чтобы редактор и плеер не разошлись:
 * кнопка в панели обязана подсвечивать ровно то, что нарисуется.
 * Значение снято с натуры — у Canva в панели «Скольжения» выбрана
 * стрелка ←.
 *
 * Умолчание НЕ кладётся в схему через `.default()` намеренно: см.
 * `transitionDirection` ниже.
 */
export const DEFAULT_TRANSITION_DIRECTION = 'left';

/**
 * Каким приёмам направление вообще осмысленно.
 *
 * Список снят с натуры, а не выведен: у Canva стрелка стоит на плитке
 * «Скольжение», «Стирание цвета», «Линейное стирание» и «Наложение»,
 * и НЕ стоит на «Растворение», «Круговое стирание», «Сопоставление
 * и перемещение», «Поток», «Вращение».
 *
 * У нас из этого следует ровно два: `slide` и `wipe`. `circle` направления
 * не получает — у Canva «Круговое стирание» стрелок не имеет, и это
 * согласуется с геометрией: круг растёт из центра, у него нет стороны.
 */
export const DIRECTED_TRANSITIONS = ['slide', 'wipe'] as const;

/**
 * Цвета, которыми автор различает главы на доске веток. Появились в v16.
 *
 * ЗАКРЫТЫЙ ПЕРЕЧЕНЬ, А НЕ ПРОИЗВОЛЬНЫЙ ЦВЕТ, и это решение, а не лень.
 * Свободная палитра на два десятка глав даёт радугу, в которой цвет
 * перестаёт значить что-либо: сегодня автор красит «важное» красным,
 * через неделю — «проверку», и доска врёт обоим. Восемь различимых цветов
 * заставляют цвет что-то ЗНАЧИТЬ, потому что их нельзя раздать всем.
 *
 * Имена — роли, а не оттенки: конкретные значения живут в теме редактора
 * (`--ui-chapter-*`), и тёмная тема перекрашивает их, не трогая проект.
 * Записать сюда `#ff0000` значило бы протащить оформление в данные.
 */
export const CHAPTER_COLORS = [
  'gray', 'blue', 'green', 'amber', 'red', 'violet', 'teal', 'pink',
] as const;

export type ChapterColor = (typeof CHAPTER_COLORS)[number];

/**
 * Метка главы: чем автор отличает её на доске. Появилась в v16.
 *
 * Оба поля НЕОБЯЗАТЕЛЬНЫ по отдельности: «покрасить, но не подписывать»
 * и «подписать, но не красить» — обычные случаи, и требовать оба значило бы
 * заставлять автора придумывать то, чего он не хотел. Пустая метка
 * (без обоих полей) законна и означает «как по умолчанию».
 *
 * `text` короткий НАМЕРЕННО: он печатается на плитке, ширина которой равна
 * длительности главы, и на узкой плитке помещается три-четыре знака.
 * Длинное имя у главы уже есть — `title`, и оно читается подсказкой
 * и карточкой. Здесь не второе имя, а ЗНАК: «Вст», «К1», «✱».
 */
export const ChapterBadgeSchema = z.object({
  color: z.enum(CHAPTER_COLORS).optional(),
  text: z.string().min(1).max(4).optional(),
});

/**
 * Тема сцены — ЗАКРЫТЫЙ список из десяти ролей, а не свободная карта.
 *
 * Закрытый потому, что каталог палитр остаётся ДАННЫМИ только если все
 * палитры заполняют один и тот же набор ролей. Иначе чужая палитра оставит
 * часть ролей пустыми, и сославшиеся на них элементы почернеют МОЛЧА:
 * измерено S11 — браузер отбрасывает объявление `var(--неизвестный)`
 * целиком, ни ошибки, ни предупреждения в консоли.
 *
 * Отсюда же требование к ссылке на роль в `ElementState.style`: у неё
 * ОБЯЗАНО быть запасное значение — `var(--scene-accent, #4c8dff)`. Бампа
 * это не требует: ссылка остаётся обычной строкой свободной карты стиля.
 *
 * Значения по умолчанию воспроизводят сегодняшний вид сцены.
 * → `docs/design/system.md` §2
 */
export const ThemeSchema = z.object({
  '--scene-bg': z.string().default('#0f1620'),
  '--scene-ink': z.string().default('#e8eef6'),
  '--scene-ink-muted': z.string().default('#93a4b8'),
  '--scene-accent': z.string().default('#4c8dff'),
  '--scene-accent-ink': z.string().default('#06121f'),
  '--scene-surface': z.string().default('#1b2430'),
  '--scene-line': z.string().default('#2c3a4c'),
  '--scene-font': z.string().default('system-ui, sans-serif'),
  '--scene-font-display': z.string().default('Georgia, serif'),
  '--scene-radius': z.string().default('28px'),
});

/** Идентификатор внутри проекта. Непустая строка без пробелов по краям. */
const Id = z.string().min(1).refine((v) => v === v.trim(), {
  message: 'Идентификатор не должен начинаться или заканчиваться пробелом',
});

const NonNegative = z.number().finite().nonnegative();

/**
 * Слово транскрипта.
 *
 * `source` — не украшение. Спайк S5 показал, что разные инструменты дают
 * систематически разные границы: edge-tts раньше реального звука на 43–95 мс,
 * Deepgram позже на 30–98 мс, MFA в пределах 25–90 мс. Без пометки об источнике
 * через месяц нельзя отличить гарантированный тайминг от угаданного,
 * а доверие к ним разное.
 *
 * `asr` появился в версии 6 и отделён от `alignment` намеренно. Выравнивание
 * знает текст заранее и раскладывает по звуку известное; распознавание сначала
 * угадывает сами слова и только потом их границы. Ошибки у них разной природы:
 * у выравнивания сдвигается граница, у распознавания пропадает или подменяется
 * слово, и якорь `TimeRef` вида `word` теряет опору целиком.
 */
export const WordSchema = z
  .object({
    text: z.string().min(1),
    start: NonNegative,
    end: NonNegative,
    source: z.enum(['alignment', 'tts', 'asr', 'manual']),
    confidence: z.number().min(0).max(1).optional(),
  })
  .refine((w) => w.end >= w.start, {
    message: 'Конец слова не может быть раньше начала',
  });

/**
 * Якорь слова: как узнать, что метка всё ещё указывает на то же слово,
 * после того как автор поправил текст или сменил голос (см. ADR-008).
 */
export const WordAnchorSchema = z.object({
  text: z.string().min(1),
  before: z.string(),
  after: z.string(),
});

/**
 * Ссылка на момент времени — размеченное объединение.
 *
 * Именно объединение, а не число с необязательным полем: так невозможно
 * состояние «указаны и секунды, и слово, и они противоречат друг другу»,
 * а компилятор заставляет обработать оба случая везде, где время используется.
 */
export const TimeRefSchema = z.discriminatedUnion('kind', [
  z.object({
    kind: z.literal('seconds'),
    t: NonNegative,
  }),
  z.object({
    kind: z.literal('word'),
    wordIndex: z.number().int().nonnegative(),
    /** Смещение от начала слова, секунды. Может быть отрицательным. */
    offset: z.number().finite(),
    anchor: WordAnchorSchema,
  }),
  /**
   * Слово, на котором стояла метка, в новой записи не нашлось.
   *
   * Три состояния якоря из `product.md` §4 ложатся на это объединение так:
   * `bound` — вариант `word`, `pinned` — вариант `seconds` (выравнивание его
   * не трогает: `editor/state/retarget.ts`), `orphan` — этот вариант.
   * Отдельного поля-флага нет намеренно — по тому же доводу, по которому
   * ADR-008 отверг «число с необязательным полем»: состояния обязаны быть
   * взаимоисключающими по типу, а не по договорённости.
   *
   * `product.md` §4 [Р]: якорь никогда не пропадает молча и никогда
   * не ставится наугад. Раньше потерянная метка становилась секундной,
   * и наутро выглядела как осознанный выбор автора — этот вариант хранит
   * ровно то, что отличает догадку от выбора.
   */
  z.object({
    kind: z.literal('orphan'),
    /**
     * Лучшая догадка — индекс в АКТУАЛЬНОЙ расшифровке, ближайшее уцелевшее
     * слово. Не «где было», а «где скорее всего»: §4 требует показать метку
     * в лучшей догадке, а не спрятать её.
     */
    wordIndex: z.number().int().nonnegative(),
    /** Смещение от начала слова, секунды. Может быть отрицательным. */
    offset: z.number().finite(),
    /**
     * Якорь, который искали и не нашли.
     *
     * Не `anchor`, как у `word`, и это не косметика: у `word` якорь —
     * утверждение «метка стоит на этом слове», проверяемое `resolveTimeRef`.
     * У сироты такого утверждения нет. Зато есть память о том, что искали,
     * и по ней сирота может ВЕРНУТЬСЯ в `bound`, если автор перезапишет
     * кусок и произнесёт слово. Поле работает, а не документирует.
     */
    lost: WordAnchorSchema,
  }),
]);

/**
 * Элемент сегмента: КТО это и из чего сделан. Ни геометрии, ни вида.
 *
 * Элементы принадлежат сегменту, а не слайду, и живут через все его слайды
 * под устойчивым `id`. Устойчивость id — условие морфинга: именно по
 * совпадению id соседние слайды понимают, что это один и тот же элемент,
 * который едет, а не разные, один из которых ушёл, а другой пришёл.
 *
 * **Здесь намеренно нет `style`.** Всё визуально изменяемое живёт
 * в `ElementState`. Два непересекающихся списка свойств пришлось бы
 * защищать вечно и решать вкусовщиной вопрос «`color` — это идентичность
 * элемента или его состояние»; пустое множество не пересекается ни с чем
 * по построению. Цена названа честно в planning.md §11.1: смена шрифта
 * задним числом затрагивает все слайды сегмента.
 *
 * **`video` появился в v10 и стоит ТИПОМ, а не заливкой** — это выбор,
 * сделанный против внутренней модели Canva и с открытыми глазами.
 * У Canva две модели сразу: API создания знает типы `Images` и `Videos`,
 * а Design Editing API их не знает вовсе и держит носитель заливкой
 * прямоугольника («more aligned with how Canva works under the hood»).
 * Мы берём первую. Причина не в правоте, а в цене: заливка как понятие
 * тронула бы все фикстуры и рендер целиком, а `'video'` в перечислении
 * закрывает то, ради чего он нужен, — «говорящая голова элемент сцены,
 * а не фон» (product.md §2ж [Р]).
 * → docs/research/canva-model.md, реестр отличий, строки 1 и 9
 */
/**
 * Перечень типов элемента — ОДИН на весь продукт, и это не украшение.
 *
 * До v10 список был литералом внутри `z.enum`, а редактор держал свои
 * копии: `library.ts` объявлял `ElementType` руками, `style.ts` —
 * массив `ALL_TYPES`. Копии типизированы как `Element['type'][]`, то есть
 * непОлный список ошибкой НЕ является: добавь тип — и стилевые поля
 * молча перестанут к нему применяться. Проверено на себе при добавлении
 * `'video'`: из двух мест типы покраснели в одном.
 *
 * Экспортированный перечень убирает возможность разъехаться: список
 * ровно один, остальные на него ссылаются.
 */
export const ELEMENT_TYPES = ['text', 'image', 'shape', 'video', 'group'] as const;

/**
 * Карта свойств вида. Одна на состояние элемента и на стиль — намеренно.
 *
 * Второй перечень полей вида в проекте уже был бы третьим списком одного
 * смысла, а такие списки разъезжаются МОЛЧА: на этом обожглись типы
 * элементов (см. `ELEMENT_TYPES` выше — из двух мест покраснело одно).
 */
const StyleProps = z.record(z.string(), z.union([z.string(), z.number()]));

/**
 * Идентификатор стиля. Уже, чем `Id`, и это не педантизм.
 *
 * Он попадает в СЕЛЕКТОР CSS (`.st-<id>`), а селектор не принимает ни
 * пробелов, ни кириллицы, ни кавычек. Идентификатор с пробелом дал бы
 * не ошибку, а нерабочее правило: браузер отбрасывает нечитаемый селектор
 * и молчит — то же семейство отказа, что и неизвестная роль темы в S11.
 *
 * Поэтому машинный идентификатор ограничен, а человеческое имя живёт
 * отдельным полем `name` и не ограничено ничем.
 */
const StyleId = z.string().regex(/^[A-Za-z0-9_-]+$/, {
  message: 'Идентификатор стиля попадает в селектор CSS: только латиница, цифры, дефис и подчёркивание',
});

/**
 * Стиль — именованный набор свойств ВИДА. Появился в v12.
 *
 * Геометрии в нём нет и быть не может: `x`, `y`, `width`, `height`,
 * `rotation` — отдельные поля состояния, а стиль заполняет карту свойств.
 * Положить туда положение нечем. Это требование `design/styles.md` §2,
 * выраженное формой, а не проверкой.
 *
 * `type` — не украшение: стиль текста нельзя применить к фигуре, наборы
 * свойств не пересекаются. Проверяется у проекта, где видны и стили,
 * и элементы сразу.
 */
export const StyleSchema = z.object({
  id: StyleId,
  /** То, что видит автор. Может быть любым — «Заголовок», «Тихий», «Цифра». */
  name: z.string().min(1),
  type: z.enum(ELEMENT_TYPES),
  props: StyleProps.default({}),
});

/**
 * Шрифт, вшитый в проект импортом. Появился в v17. → `ProjectSchema.fonts`
 *
 * `family` — CSS-имя, которым текст ссылается на шрифт (`font-family`
 * в `ElementState.style`), ровно как отдаёт исходный файл. `assetId` — ключ
 * байтов самого файла шрифта в хранилище плеера, тем же путём, что
 * и `Element.assetId` у картинки чуть ниже.
 */
export const FontSchema = z.object({
  family: z.string().min(1),
  assetId: z.string().min(1),
});

export const ElementSchema = z.object({
  id: Id,
  type: z.enum(ELEMENT_TYPES),
  content: z.string().default(''),
  /**
   * Родительская группа. Появилось в v11.
   *
   * Дерево выражено ССЫЛКОЙ ВВЕРХ, а не списком детей у родителя, и это
   * не вкусовщина. Список детей пришлось бы согласовывать с двумя концами
   * сразу: родитель знает детей, ребёнок не знает родителя — и разъехаться
   * они могли бы МОЛЧА. Ссылка одна, рассогласовать нечего.
   *
   * Отсутствие означает «элемент верхнего уровня». Куда `parentId` может
   * указывать, ограничено проверкой у сегмента: только на элемент типа
   * `'group'` того же сегмента и без циклов.
   *
   * Решение владельца 08.08.2026: координаты ребёнка отсчитываются
   * ОТ ГРУППЫ, как у Canva. → docs/session-28-plan.md §3
   */
  parentId: z.string().optional(),
  /**
   * Запертый элемент не берётся выделением.
   *
   * У ЭЛЕМЕНТА, а не у состояния, и разница смысловая: запирание —
   * свойство авторской работы, а не кадра. «Заперт на одном слайде
   * и свободен на соседнем» — состояние, которому нельзя приписать смысл,
   * поэтому оно и не выразимо.
   */
  locked: z.boolean().default(false),
  /**
   * Ключ байтов картинки в хранилище плеера (`packages/player/src/assets.ts`).
   * Появился в v17.
   *
   * Тот же довод, что у `audio.fileId` рядом (см. ниже): сама картинка
   * в проект не попадает — JSON проекта живёт в `localStorage` с потолком
   * 5 242 869 символов, а картинка это десятки-сотни килобайт. Байты живут
   * в IndexedDB, элемент хранит только ключ.
   *
   * Допустим только у `type === 'image'` — правило выражено `.superRefine()`
   * ниже, а не комментарием: ключ байтов картинки у текста или фигуры
   * бессмыслен, и молчаливое принятие спрятало бы опечатку типа.
   */
  assetId: z.string().min(1).optional(),
  /**
   * Контур фигуры, взятый из Canva импортом: строка SVG-пути (`d`) и система
   * координат, в которой она задана. Появился в v17.
   *
   * `width`/`height` ОБЯЗАНЫ быть положительными: они дают `viewBox`,
   * которым контур масштабируется до размера состояния слайда (`width`
   * и `height` там же), а делить на ноль нечем.
   *
   * Краска (`fill`, `stroke`, `stroke-width`) сюда НЕ входит намеренно —
   * она едет в `ElementState.style`, как у любого элемента. Зашить цвет
   * в контур значило бы отнять у автора возможность перекрасить фигуру
   * полосой свойств так же, как остальные элементы.
   *
   * Допустим только у `type === 'shape'` — та же проверка `.superRefine()`,
   * что у `assetId`.
   */
  path: z.object({
    d: z.string().min(1),
    width: z.number().positive(),
    height: z.number().positive(),
    /**
     * Наконечники стрелок на концах контура. Появились в рамках v17
     * (расширение поля, не бамп: v17 не выходила за пределы этой ветки —
     * решение контроллера, Сессия 58, круг правок 1).
     *
     * `start` — у начала `d` (первая точка `M`), `end` — у конца (последняя
     * точка). Значения — как отдаёт библиотека (`'triangle'` и т.п.).
     * `'none'` НЕ кладётся вовсе: отсутствие наконечника выражается
     * отсутствием поля, тем же приёмом, что у отсутствующего текста.
     * Рисование — задача 4; здесь только данные.
     */
    startArrow: z.string().min(1).optional(),
    endArrow: z.string().min(1).optional(),
  }).optional(),
})
  .superRefine((element, ctx) => {
    if (element.assetId !== undefined && element.type !== 'image') {
      ctx.addIssue({
        code: 'custom',
        path: ['assetId'],
        message: `Ключ байтов «assetId» допустим только у картинки, а элемент «${element.id}» `
          + `имеет тип «${element.type}»`,
      });
    }
    if (element.path !== undefined && element.type !== 'shape') {
      ctx.addIssue({
        code: 'custom',
        path: ['path'],
        message: `Контур «path» допустим только у фигуры, а элемент «${element.id}» `
          + `имеет тип «${element.type}»`,
      });
    }
  });

/**
 * Состояние элемента на конкретном слайде: ГДЕ он и КАК выглядит.
 *
 * `width` и `height` неотрицательные, а не положительные: нулевой размер —
 * законное вырожденное состояние, из которого элемент вырастает. Именно
 * в него переводится `scale: 0` старых анимаций при миграции.
 *
 * Разница между «элемента нет в `states`» и `visible: false` — это два
 * РАЗНЫХ перехода, и путать их нельзя (ADR-015):
 *
 *   нет в `states` предыдущего слайда → элемент приходит; предыдущей
 *   позиции не существует, морфинга нет;
 *
 *   `visible: false → true` → элемент проявляется на своём месте; позиция
 *   известна и сохранена, поэтому он может одновременно ехать.
 */
export const ElementStateSchema = z.object({
  x: z.number().finite(),
  y: z.number().finite(),
  width: z.number().finite().nonnegative(),
  height: z.number().finite().nonnegative(),
  rotation: z.number().finite().default(0),
  zIndex: z.number().int().default(0),
  opacity: z.number().min(0).max(1).default(1),
  visible: z.boolean().default(true),
  /**
   * Отражение по горизонтали и вертикали. Появилось в v11.
   *
   * У СОСТОЯНИЯ, а не у элемента, в отличие от `locked` рядом: отражение
   * видно зрителю, значит вправе меняться от слайда к слайду — как поворот
   * и прозрачность, которые лежат здесь же.
   *
   * ОСТОРОЖНО, мина, найденная до кода. Выразить отражение «очевидным»
   * `transform: scaleX(-1)` НЕЛЬЗЯ без правки движка: морфинг анимирует
   * `scaleX` В ЕДИНИЦУ (`morph.ts`, ветка `morph`), поэтому переход молча
   * снял бы отражение — элемент доехал бы до следующего слайда
   * неотражённым. В модели при этом осталось бы `flipX: true`, то есть
   * юнит-тест на состояние был бы зелёным.
   *
   * Поэтому поля пока ТОЛЬКО в схеме: рендер и морфинг их не применяют.
   * → docs/session-28-plan.md §4а
   */
  flipX: z.boolean().default(false),
  flipY: z.boolean().default(false),
  style: StyleProps.default({}),
  /**
   * Стиль, по которому идёт элемент на ЭТОМ слайде. Появилось в v12.
   *
   * У СОСТОЯНИЯ, а не у элемента, по тому же критерию, по которому здесь
   * оказались `flipX` и поворот: вид элемента видит зритель, значит он
   * вправе меняться от слайда к слайду. Решение владельца 14.08.2026:
   * заголовок начинается «Главным» и к концу становится «Тихим».
   *
   * Ссылка и `style` рядом друг друга НЕ дублируют, и решение [Р]
   * `product.md` §2 «ни одно свойство не лежит в двух местах» не нарушено.
   * У каждого свойства ровно один действующий источник: ключ есть в `style` —
   * источник элемент, ключа нет — источник стиль. Разводит их не проверка
   * в коде, а каскад браузера: стиль лежит правилом класса, `style` —
   * инлайном, и инлайн перекрывает правило ПОКОМПОНЕНТНО. Измерено S14:
   * правка кегля рукой дала 72px, а цвет и скругление остались стилевыми.
   *
   * → docs/adr/ADR-029-styles.md
   */
  styleId: StyleId.optional(),
});

/**
 * Инвариант №8: анимируем только transform, opacity и filter.
 *
 * Кью из версии 2 больше нет, но перечень остался законом — теперь для
 * движка морфинга: это закрытый список того, что ему позволено трогать.
 *
 * Изменение `width`/`height` между слайдами инвариант НЕ нарушает: FLIP
 * анимирует его через `scaleX`/`scaleY`, то есть через `transform`. Модель
 * хранит геометрию, композитор двигает трансформацию.
 */
export const ANIMATABLE = [
  'x', 'y', 'scale', 'scaleX', 'scaleY', 'rotate', 'opacity', 'filter',
] as const;

/**
 * Слайд — снимок сцены в момент времени, а не отдельная страница.
 *
 * Хранит не список элементов, а список их состояний, поэтому переход
 * между соседними слайдами вычисляется сам: элемент есть в обоих — едет,
 * только в предыдущем — уходит, только в следующем — приходит.
 *
 * `transition: 'cut'` — намеренный разрыв, который автор выбирает сам.
 */
export const SlideSchema = z.object({
  id: Id,
  at: TimeRefSchema,
  transition: z.enum(TRANSITIONS).default('morph'),
  /**
   * Сколько длится переход К этому слайду, секунды.
   *
   * Появилось в v9. Раньше число было одно на весь продукт
   * (`MORPH_DURATION_S` в плеере), и комментарий рядом объяснял это тем,
   * что слайд описывает СОСТОЯНИЕ, а не хронометраж перехода к себе.
   * Владелец отменил ограничение 05.08.2026 — но НАПОЛОВИНУ: длительность
   * возвращается, ПЛАВНОСТЬ (`ease`) нет. Потеря `ease` при переходе
   * v2→v3 остаётся в силе.
   *
   * **ИСПРАВЛЕНО 07.08.2026.** Здесь стояло «снято с натуры: у Canva
   * в панели перехода ровно одно поле, „Продолжительность"». Это неверно,
   * и проверено открытием самой панели: полей ДВА — продолжительность
   * и направление. На решение об `ease` ошибка не влияла (направление —
   * другая ось), но утверждение о натуре стояло в обосновании решения
   * о схеме и прожило так две версии.
   *
   * Ноль законен — это срез. Отрицательного времени не бывает.
   * Урезание расстоянием до предыдущей метки делает плеер, а не схема:
   * схема не знает, где стоят соседние слайды. Натура это подтвердила:
   * у Canva переход отъедает у страницы ровно ПОЛОВИНУ своей длительности
   * (замерено: при 2.0 с страница 5.0 → 4.0), то есть урезание там тоже
   * считается снаружи модели слайда.
   */
  transitionSeconds: z.number().nonnegative().default(DEFAULT_TRANSITION_SECONDS),

  /**
   * Куда едет переход. Появилось в v10, снято с натуры: у Canva в панели
   * перехода четыре кнопки-стрелки ← → ↑ ↓.
   *
   * **Поле необязательное, и умолчания у него НЕТ.** Это тот же закон,
   * по которому `cut` стоит первым в каталоге приёмов: «нет перехода» —
   * запись каталога, а не пустой выбор, как «нет цвета» ≠ «белый цвет».
   * Направление у `dissolve` не должно подменяться на `'left'` — его
   * там не существует. Что подставить `slide` и `wipe`, когда автор
   * не выбирал, решает плеер: `DEFAULT_TRANSITION_DIRECTION`.
   *
   * Отсюда же две вещи даром: миграция v9→v10 остаётся чистым no-op
   * (дописывать нечего), и ни одна из фикстур не правится — направления
   * в них нет ни у одного слайда.
   */
  transitionDirection: z.enum(TRANSITION_DIRECTIONS).optional(),

  states: z.record(Id, ElementStateSchema),
})
  /**
   * Направление допустимо только там, где оно есть у приёма.
   *
   * Проверка стоит здесь, а не в плеере, потому что «валидность данных
   * не равна достижимости поведения»: `dissolve` с направлением разобрался
   * бы, доехал до движка и был бы там молча выброшен. Схема — единственный
   * источник истины, и выразимость бессмыслицы в ней означает, что
   * договариваться о её смысле придётся каждому, кто ниже.
   *
   * Проверяется НАЛИЧИЕ лишнего, а не отсутствие нужного: `slide` без
   * направления законен, его дорисует умолчание плеера. Требовать
   * направление у `slide` значило бы сломать существующие проекты
   * ради поля, которого в них не было.
   */
  .superRefine((slide, ctx) => {
    if (slide.transitionDirection === undefined) return;
    if ((DIRECTED_TRANSITIONS as readonly string[]).includes(slide.transition)) return;

    ctx.addIssue({
      code: 'custom',
      path: ['transitionDirection'],
      message:
        `Направление задано, но приём «${slide.transition}» его не имеет. ` +
        `Направление есть только у: ${DIRECTED_TRANSITIONS.join(', ')}.`,
    });
  });

/**
 * Условие — размеченное объединение, а не строка-предикат.
 *
 * Смотрит на переменную, записанную гейтом. Переменная может быть записана
 * в ЛЮБОМ сегменте объяснения, не обязательно в этом: ответы живут на всё
 * объяснение, и развилка вправе опереться на то, что зритель отвечал раньше.
 *
 * Объявлено ЗДЕСЬ, а не рядом с выходом сегмента, потому что условие нужно
 * в двух местах сразу: правилу выхода и варианту ответа. Порядок объявления
 * в модуле — не стилистика: `const` не поднимается, и вариант ответа ниже
 * не увидел бы схему, объявленную после него.
 *
 * `compare` несёт оператор ПОЛЕМ, а не отдельным видом на каждый знак:
 * четыре значения в одном селекте стоят столько же, сколько одно,
 * а недостающий знак стоил бы отдельного бампа схемы. → ADR-019
 */
export const ConditionSchema = z.discriminatedUnion('kind', [
  /** Ответ равен конкретному значению: для выбора — id варианта. */
  z.object({ kind: z.literal('equals'), variable: Id, value: z.string() }),
  /** Ответ НЕ равен значению. Обещано `product.md` §2 как «≠». */
  z.object({ kind: z.literal('notEquals'), variable: Id, value: z.string() }),
  z.object({ kind: z.literal('correct'), variable: Id }),
  z.object({ kind: z.literal('wrong'), variable: Id }),
  /**
   * Сравнение с числом. Значение переменной — строка (id варианта), поэтому
   * приведение к числу может не удаться; это не ошибка, а «условие не подошло».
   */
  z.object({
    kind: z.literal('compare'),
    variable: Id,
    op: z.enum(['gt', 'gte', 'lt', 'lte']),
    value: z.number().finite(),
  }),
]);

/**
 * Список условий, соединяемых через И.
 *
 * Непустой намеренно: правило без условий — это `default`, а он уже есть
 * отдельным полем. Два способа сказать одно и то же неизбежно разъезжаются.
 *
 * ИЛИ здесь нет и не будет: оно получается бесплатно СЛЕДУЮЩИМ правилом,
 * потому что правила проверяются по порядку и выигрывает первое подошедшее.
 * Скобок тоже нет — с ними это перестаёт быть языком автора.
 */
export const ConditionsSchema = z.array(ConditionSchema).min(1);

/**
 * Выбор из вариантов — и то место, где различаются две остановки продукта.
 *
 * `correctId: null` значит «верного ответа нет»: это РАЗВИЛКА, где ветки
 * равноправны, а не вопрос, на который можно ответить неверно. До версии 4
 * поле было обязательным, поэтому развилка была вынуждена назначать
 * «правильную» ветку — ложь, которая доезжала до данных и была видна
 * в `fixtures/projects/exit-branch.json`.
 *
 * Различие выражено ЗНАЧЕНИЕМ, а не отдельным флагом вида остановки:
 * флаг можно рассогласовать с `correctId`, а `null` рассогласовать не с чем.
 */
const ChoiceConfig = z.object({
  kind: z.literal('choice'),
  prompt: z.string(),
  /**
   * `when` — необязательное условие показа. Вариант виден зрителю, только
   * если условие подошло; без `when` вариант виден всегда.
   *
   * Проверки «хотя бы один безусловный» и «верный ответ безусловен» стоят
   * не здесь, а в `.refine` на `GateSchema`: `.refine` превращает объект
   * в `ZodEffects`, а `discriminatedUnion` принимает только `ZodObject`.
   */
  /**
   * `elementId` — элемент сцены, служащий кнопкой ЭТОГО ответа (ADR-035).
   *
   * До версии 15 связь держалась на СОВПАДЕНИИ идентификаторов: плеер брал
   * `this.#nodes.get(option.id)` и, найдя узел, делал его кнопкой. Совпадение
   * не ссылка: намерения из него не вывести (имена могли совпасть случайно),
   * и разрыв из него не поймать — переименуй любую из двух сторон, и связь
   * исчезнет молча. ADR-011 записал это последствие честно: «вариант просто
   * деградирует до системной кнопки».
   *
   * Ссылка проверяется на существование элемента В ТОМ ЖЕ сегменте
   * (см. `.superRefine` ниже) — так же строго, как `authorSpans[].elementId`.
   * Пусто — вариант рисуется системной кнопкой, и это законный основной
   * случай, а не недоделка.
   */
  options: z.array(z.object({
    id: Id,
    label: z.string(),
    when: ConditionsSchema.optional(),
    elementId: Id.optional(),
  })).min(2),
  correctId: Id.nullable(),
  /**
   * `promptElementId` — элемент сцены, показывающий САМ ВОПРОС.
   *
   * Симметричен `elementId` у ответа и заведён по той же причине. Без него
   * вопрос существовал бы на экране дважды: как `prompt` в данных остановки
   * и как текст на сцене, — и автор правил бы одно, а зритель читал другое.
   * Этот класс расхождения в проекте уже стоил сессии: два поля «Вопрос»
   * на одном экране поймал строгий режим Playwright тестом про другое.
   *
   * Пусто — вопрос на сцену не вынесен, и его показывает служебная плашка
   * оснастки. Законный случай: так открывается всякий старый проект.
   */
  promptElementId: Id.optional(),
});

const InputConfig = z.object({
  kind: z.literal('input'),
  prompt: z.string(),
  accept: z.array(z.string().min(1)).min(1),
  caseSensitive: z.boolean().default(false),
});

const ContinueConfig = z.object({
  kind: z.literal('continue'),
  label: z.string().default('Дальше'),
});

/**
 * Гейт — остановка ВНУТРИ сегмента. Плеер встаёт, зритель отвечает, плеер
 * едет дальше по той же дорожке.
 *
 * **Гейт никуда не перекидывает.** Рёбер у него нет и быть не может: поля
 * для них здесь просто не существует. Всё, что гейт делает с ответом, —
 * записывает его в переменную `recordAs`. Решение о следующем сегменте
 * принимает `Exit` на выходе.
 *
 * `onWrong` описывает, что зритель увидит при неверном ответе, прежде чем
 * поехать дальше:
 *
 *   `inline-explain` — разбор слоем поверх сцены, не покидая сегмент;
 *   `inline-hint`    — короткая подсказка тем же способом;
 *   `retry`          — дать ответить заново;
 *   `continue`       — не показывать ничего.
 *
 * `continue` добавлен сверх трёх видов из задания: без него каждый неверный
 * ответ обязан был бы что-то показать, а «промолчать и ехать дальше» —
 * законный и частый выбор автора. Это же значение носили гейты версии 2,
 * и без него миграция теряла бы данные там, где терять их незачем.
 */
export const GateSchema = z
  .object({
    id: Id,
    at: TimeRefSchema,
    config: z.discriminatedUnion('kind', [ChoiceConfig, InputConfig, ContinueConfig]),
    onWrong: z.enum(['inline-hint', 'inline-explain', 'retry', 'continue']).default('retry'),
    maxAttempts: z.number().int().positive().nullable().default(null),
    /** Имя переменной зрителя, в которую записывается ответ. */
    recordAs: Id,
  })
  .refine(
    (gate) => {
      // Локальная переменная нужна не для красоты: внутри колбэка сужение
      // размеченного объединения по gate.config теряется.
      const config = gate.config;
      if (config.kind !== 'choice') return true;
      // Развилка: верного ответа нет, и указывать ему на вариант незачем.
      if (config.correctId === null) return true;
      return config.options.some((option) => option.id === config.correctId);
    },
    { message: 'correctId должен указывать на один из вариантов' },
  )
  .refine(
    (gate) => {
      const config = gate.config;
      if (config.kind !== 'choice') return true;
      return config.options.some((option) => option.when === undefined);
    },
    {
      message:
        'Хотя бы один вариант ответа обязан быть безусловным: '
        + 'иначе при неудачном наборе переменных скроются все, '
        + 'и зритель упрётся в вопрос без ответов',
    },
  )
  .refine(
    (gate) => {
      const config = gate.config;
      if (config.kind !== 'choice') return true;
      if (config.correctId === null) return true;
      const correct = config.options.find((option) => option.id === config.correctId);
      // Отсутствие варианта ловит проверка выше — здесь молчим, чтобы автор
      // получил одну внятную причину, а не две сразу об одном и том же.
      return correct === undefined || correct.when === undefined;
    },
    {
      message:
        'Верный вариант ответа не может быть условным: '
        + 'спрятав его условием, автор делает вопрос непроходимым молча',
    },
  );

/**
 * Правило выхода: набор условий через И и куда вести, если все подошли.
 *
 * До версии 5 условие было ровно одно, и «ответил A и ответил B» выразить
 * было нечем — приходилось бы заводить служебную часть без содержимого
 * только ради логики. → ADR-019
 */
export const ExitRuleSchema = z.object({
  id: Id,
  when: ConditionsSchema,
  goto: Id,
});

/**
 * Выход сегмента — единственное место, где принимается решение о следующем
 * сегменте. Правила проверяются по порядку, первое подошедшее выигрывает.
 *
 * `default: null` — концовка объяснения. Это основной случай, а не краевой:
 * именно такой выход получает сегмент после миграции с версии 2.
 */
export const ExitSchema = z.object({
  rules: z.array(ExitRuleSchema).default([]),
  default: Id.nullable().default(null),
});

/**
 * Отрезок «моё»: промежуток, внутри которого элементом распоряжается АВТОР.
 *
 * Появился в v14. → ADR-032, `docs/design/bubble.md` §2
 *
 * **Почему это не выражается слайдом.** Слайд хранит состояние В ТОЧКЕ,
 * и переход между соседними слайдами вычисляется сам. Промежуток двумя
 * точками не записывается: точка не знает, что было до неё. Отсюда новое
 * поле, а не переиспользование существующего.
 *
 * **Отрезок отвечает на вопрос «кто хозяин», а не «где именно».** Внутри
 * него положение и видимость берутся из слайдов, как у любого элемента.
 * Второго описания геометрии здесь нет и быть не должно — иначе одно
 * свойство лежало бы в двух местах.
 *
 * **Края — `TimeRef`, а не секунды.** Инвариант №10: отрезок «пока я
 * показываю схему, голова прячется» привязан к сказанному, а не
 * к миллисекунде. Секунды остаются законны там, где слова нет.
 *
 * Вне отрезков элемент принадлежит ЗРИТЕЛЮ: пустое место между отрезками
 * читается само и отдельной записи не требует. Поэтому «зритель ничего
 * не может» выражается сплошным отрезком, а не флагом — иначе одно и то же
 * состояние имело бы два представления.
 */
export const AuthorSpanSchema = z.object({
  /** Чей это отрезок. В MVP полосу получает только капля, но поле общее. */
  elementId: Id,
  from: TimeRefSchema,
  to: TimeRefSchema,
});

/**
 * Сегмент — единица линейности: одна непрерывная аудиодорожка, известная
 * длительность, внутри только гейты и никаких развилок.
 */
export const SegmentSchema = z.object({
  id: Id,
  title: z.string().default(''),
  /**
   * Описание части — скелет сценария, который читает карточка на карте.
   *
   * Появилось в v9. ADR-022 отверг план части, и отверг УСЛОВНО: «План —
   * входной материал ИИ-модуля, а модуля в этой сессии не строим. Поле,
   * которое никто не читает, — фича на будущее». Карточка карты его
   * читает, значит посылка отказа отпала. Это не «ADR ошибся», а «условие
   * изменилось», и разница важна: первое требует спора, второе — новой
   * записи. → ADR-026
   *
   * Пустая строка законна, в отличие от `speech` рядом: там отсутствие
   * текста выражается отсутствием поля, потому что «кусок без озвучки» —
   * особое состояние. У описания особых состояний нет, оно просто пустое.
   */
  description: z.string().default(''),
  /**
   * Метка главы на доске веток: цвет и короткий знак. Появилась в v16.
   *
   * Решение владельца 25.08.2026: «нужно научить юзера самому отличать
   * плитки как ему надо, чтобы он мог сам красить или не красить и сам
   * давать имена, а мы будем просто такой вот как сейчас дефолт давать».
   *
   * Отсюда «необязательна»: без неё доска показывает номер и общий вид,
   * как показывала. Метка ДОБАВЛЯЕТ различение, а не заменяет умолчание.
   */
  badge: ChapterBadgeSchema.optional(),
  /**
   * Дословный текст, который на этом куске произносится.
   *
   * Не путать со сценарием: сценарий — это план объяснения, и в схеме его
   * нет (ADR-022). Не путать с расшифровкой: та лежит в `audio.words`
   * со временами и описывает, что реально прозвучало. При синтезе они
   * совпадают, при живой записи расходятся, и §4 `product.md` живёт
   * ровно на этом расхождении.
   *
   * Здесь СТРОКА, а не готовое разбиение на слова: разбиение производно
   * от текста, и второе поле можно было бы рассогласовать с первым молча.
   * Режет текст одна функция — `splitIntoWords` в `align.ts`.
   *
   * Необязательное: «кусок без текста озвучки» законен так же, как уже
   * законен «кусок без расшифровки». Пустая строка запрещена — отсутствие
   * текста выражается отсутствием поля, а не пустым значением, иначе
   * состояний становится два на один смысл.
   */
  speech: z.string().min(1).optional(),
  /**
   * Временная ось сегмента: длительность, слова и — ПО ЖЕЛАНИЮ — источник звука.
   *
   * Имя историческое и уже неточное: с версии 13 звука здесь может не быть
   * вовсе. Переименовывать не стали — цена в 39 местах чтения не окупает
   * ясности одного слова, а комментарий стоит ровно там, где смотрят.
   *
   * **Немой сегмент (v13).** Ни `src`, ни `fileId` — законное состояние:
   * автор строит объяснение из слайдов, а озвучку добавит позже или
   * не добавит никогда. Решение владельца 15.08.2026: звук и видео —
   * желательные, но необязательные.
   *
   * **Инвариант №1 при этом НЕ нарушается, и это надо понимать точно.**
   * Время проекта берётся не из дорожки, а из `AudioContext.currentTime`
   * за вычетом задержки вывода (`clock.ts`): буфер только звучит, а считает
   * контекст. У немого сегмента остаются те же аппаратные часы — те, у которых
   * измерен наклон −0.014 мс/мин за десять минут, — и не появляется ни
   * `setInterval`, ни счётчика кадров. Источником времени по-прежнему является
   * позиция в аудиоконтексте. → ADR-030
   */
  audio: z.object({
    /**
     * Файл на сервере. Не больше одного из `src` и `fileId` — см. `.superRefine()`
     * под этим объектом. НИ ОДНОГО — это немой сегмент.
     */
    src: z.string().min(1).optional(),
    /**
     * Ключ файла, который автор загрузил сам. Появилось в версии 6.
     *
     * Отдельным полем, а не префиксом внутри `src`, сознательно. Префикс
     * (`idb:...`) оставил бы тип строкой, схема продолжила бы считать такой
     * проект валидным, а разбор адреса расползся бы по всем читателям.
     * Невозможное состояние обязано быть невыразимым в схеме, а не
     * отлавливаться четвёртым по счёту потребителем.
     *
     * Само содержимое файла в проект НЕ попадает: JSON проекта ходит через
     * `localStorage`, где замерено 5 242 869 символов потолка, а секунда
     * звука это десятки килобайт. Байты живут в IndexedDB (S8: 30 МБ за 59 мс),
     * проект хранит только ключ.
     */
    fileId: z.string().min(1).optional(),
    /**
     * С какой секунды ФАЙЛА начинается дорожка этой части. Появилось в версии 4.
     *
     * Продуктовое решение [Р] «аудио физически не режется» до сих пор нигде
     * не было выражено: часть и файл были склеены один к одному, и разрезать
     * повествование на развилке было попросту нечем. Окно разлепляет их —
     * несколько частей ссылаются на один файл разными участками.
     *
     * **Смещение НЕ меняет систему координат части.** Слова транскрипта,
     * `TimeRef`, слайды и гейты по-прежнему считаются от нуля этой части,
     * а `duration` — длина окна, а не остаток файла. Иначе пришлось бы
     * переписать всё, что считает время, и потерять правило «первый слайд
     * стоит на нуле». Смещение знает только тот, кто заводит воспроизведение.
     */
    offset: NonNegative.default(0),
    /**
     * Длительность сегмента, секунды.
     *
     * У озвученного сегмента — длина окна дорожки. У немого (v13) — длина,
     * ОБЪЯВЛЕННАЯ автором: показывать слайды по расписанию всё равно надо,
     * а вывести длину не из чего. Поле было обязательным и до v13, поэтому
     * немой сегмент не заводит второго источника длительности.
     */
    duration: z.number().finite().positive(),
    /** Всегда присутствует. Пустой массив делает невалидной любую ссылку на слово. */
    words: z.array(WordSchema),
  }).superRefine((audio, ctx) => {
    if (audio.src !== undefined && audio.fileId !== undefined) {
      ctx.addIssue({
        code: 'custom',
        message:
          'У дорожки не может быть двух источников сразу: либо src (файл на сервере), '
          + 'либо fileId (файл, загруженный автором).',
      });
      return;
    }

    if (audio.src !== undefined || audio.fileId !== undefined) return;

    // Дальше — немой сегмент. Два состояния при нём бессмысленны, и оба
    // выражают одну ошибку: «звука нет, но что-то ведёт себя так, будто есть».
    // Ловить их здесь дешевле, чем разбираться, почему у немого куска
    // сместилась несуществующая дорожка.
    if (audio.words.length > 0) {
      ctx.addIssue({
        code: 'custom',
        path: ['words'],
        message:
          `У немого сегмента нет дорожки, а расшифровка описывает то, что прозвучало: `
          + `слов быть не может, а их ${audio.words.length}.`,
      });
    }
    if (audio.offset !== 0) {
      ctx.addIssue({
        code: 'custom',
        path: ['offset'],
        message:
          `Смещение отсчитывается от начала ФАЙЛА, а у немого сегмента файла нет: `
          + `ожидался 0, получено ${audio.offset}.`,
      });
    }
  }),
  elements: z.array(ElementSchema),
  /** Не меньше одного: без слайда сегменту нечего показывать. */
  slides: z.array(SlideSchema).min(1),
  gates: z.array(GateSchema).default([]),
  /**
   * Отрезки авторского владения. Появились в v14 (ADR-032).
   *
   * Умолчание — пустой массив, и это ровно сегодняшнее поведение: ни одного
   * отрезка значит, что помеченных элементов нет вовсе, а непомеченного
   * элемента зритель не касается — сцена мертва по инварианту №3.
   */
  authorSpans: z.array(AuthorSpanSchema).default([]),
  exit: ExitSchema,
})
  /**
   * Группы: что схема обязана делать НЕВЫРАЗИМЫМ (v11).
   *
   * Проверка стоит здесь, а не у элемента, по необходимости: `parentId`
   * ссылается на соседа по массиву, а условие про состояния смотрит ещё
   * и в слайды. Сегмент — единственное место, которое видит и то и другое.
   *
   * Договором «мы так не делаем» это закрывать нельзя: группа, ссылающаяся
   * на себя, повесила бы обход дерева наглухо, а ребёнок без родителя
   * не имеет позиции вовсе — его координаты отсчитываются от того, чего нет.
   * Молчаливый запасной вариант («считать родителя в нуле») запрещён
   * правилом «чини корень».
   */
  .superRefine((segment, ctx) => {
    const byId = new Map(segment.elements.map((el) => [el.id, el]));

    for (const [index, el] of segment.elements.entries()) {
      const { parentId } = el;
      if (parentId === undefined) continue;

      const parent = byId.get(parentId);
      if (!parent) {
        ctx.addIssue({
          code: 'custom',
          path: ['elements', index, 'parentId'],
          message: `Элемент «${el.id}» ссылается на группу «${parentId}», которой нет в этом сегменте.`,
        });
        continue;
      }

      if (parent.type !== 'group') {
        ctx.addIssue({
          code: 'custom',
          path: ['elements', index, 'parentId'],
          message:
            `Элемент «${el.id}» вложен в «${parentId}», а тот имеет тип «${parent.type}». `
            + 'Вкладывать можно только в group.',
        });
        continue;
      }

      // Подъём до корня: цикл обнаруживается тем, что подъём не кончается.
      const seen = new Set<string>([el.id]);
      let current: string | undefined = parentId;
      while (current !== undefined) {
        if (seen.has(current)) {
          ctx.addIssue({
            code: 'custom',
            path: ['elements', index, 'parentId'],
            message: `Вложенность зациклена: «${el.id}» оказывается собственным предком.`,
          });
          break;
        }
        seen.add(current);
        current = byId.get(current)?.parentId;
      }
    }

    /**
     * Ребёнок не может быть на слайде, где нет его предка.
     *
     * ADR-015: элемент без состояния на слайде не рисуется вовсе. Значит
     * состояние ребёнка при отсутствующем состоянии группы описывает
     * положение относительно того, чего на этом слайде нет.
     */
    for (const [slideIndex, slide] of segment.slides.entries()) {
      for (const el of segment.elements) {
        if (el.parentId === undefined) continue;
        if (slide.states[el.id] === undefined) continue;
        if (slide.states[el.parentId] !== undefined) continue;

        ctx.addIssue({
          code: 'custom',
          path: ['slides', slideIndex, 'states', el.id],
          message:
            `Элемент «${el.id}» есть на слайде, а его группы «${el.parentId}» — нет. `
            + 'Координаты ребёнка отсчитываются от группы, поэтому позиции у него не было бы.',
        });
      }
    }
  });

